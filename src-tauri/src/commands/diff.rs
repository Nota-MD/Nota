//! 差异相关命令。
//!
//! 用户 2026-09-26 点的：「**将 diff 预览加入核心库调用吧。调用率挺高**」。
//!
//! 在此之前，"看两份文本的差别"这件事**只有插件能要**（`nota.diff.make`），
//! 核心自己反而拿不到——而核心要用它的地方并不少：外部改动提示条的
//! 「查看修改」（`ui/useExternalChanges.ts`）、以后可能的"另存为前比一比"之类。
//! 所以这一条命令是**把已经写好的生成器接出来**，不是再写一遍。
//!
//! # 与前端 `review.ts` 那份 LCS 的分工（⚠️ 这条边界要说清）
//!
//! 核心这一份是**行级**的（`diff.rs` 按 `\n` 切行）。前端 `review.ts` 也有
//! 一份差异引擎，那一份是**单元级**的：喂进去的"单元"由调用方决定——
//! 源码模式是行（`review-source.ts`），所见即所得模式是**块**（`review-prose.ts`），
//! 而一个块可以是多行的（表格就是）。
//!
//! 换句话说：
//!
//! | 谁 | 干什么 | 为什么不能换成另一份 |
//! |---|---|---|
//! | 核心 `nota_diff_texts` | 生成**给人看**的统一格式差异 | 块大小不等时它能表达"这块被换掉了"，而它只认行 |
//! | 前端 `review.ts` | 算**装饰该挂在哪儿**（两侧行/块的一一对齐） | 它要的是"旧的第 7 段对应新的第 9 段"，而统一格式的段头里没有这个 |
//!
//! ⚠️ **不是"前端只好自己手写一遍"**——两份输入输出根本不同。合并任何一份
//! 到另一份上，都会让另一边多一层翻译（而翻译里丢掉的信息没有人会发现）。

/// 两段文本 → 一份**统一格式**的逐行差异。
///
/// `context` 是每段改动前后各露几行没变的（`git diff -U n` 的那个 n），
/// 不给就是 `lua/api/diff.rs::默认上下文` 那个值（3）——**同一个默认值**，
/// 免得插件和核心两条路给同一个问题两个答案。
///
/// 两段文本没有差异（含两边都是空）时给**空数组**，不是空段头。
///
/// ⚠️ 形参叫 `before` / `after` **不是** `old` / `new`：这是在迁就**前端那一侧**
/// ——JS 里 `new` 是保留字，`invoke(…, { old, new })` 那个对象字面量写得出来，
/// 可调用方要是个 `(old, new) => …` 的箭头函数就**编译不过**（TS 报
/// `'new' is a reserved word`，2026-09-26 真踩了）。名字两边一致，前端就不必
/// 在两个名字之间做一次翻译——那种翻译正是最容易只改一半的东西。
///
/// ⚠️ 这是一个**纯函数**：不碰 `AppState`、不碰文档仓。输入是前端手上那两份
/// 文本（"编辑器里现在长这样" vs "磁盘上现在长这样"），不是宿主镜像里的那份
/// ——镜像有 300ms 去抖，而"查看修改"要看的正是**此刻**编辑器里的样子。
#[tauri::command]
pub fn nota_diff_texts(
    before: String,
    after: String,
    context: Option<usize>,
) -> Vec<crate::diff::一行> {
    crate::diff::统一差异(
        &before,
        &after,
        context.unwrap_or(crate::lua::api::diff::默认上下文),
    )
}
