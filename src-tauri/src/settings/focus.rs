//! 「强制专注」那一页的设置。
//!
//! ⚠️⚠️ **这是一份核心功能的设置，不是插件的。** 用户 2026-09-26 的原话是
//! 「注意啊，这不是插件。这是核心功能」——它要窗口焦点、要开一个置顶窗、
//! 要出声，三样都超出插件沙箱（插件没有 timer、收不到宿主事件、开不了窗口，
//! 见 `docs/12` §4.7a）。
//!
//! # 计时引擎：账户余额（用户 2026-09-26 定）
//!
//! 用户的原话：「用户可以设置两个时长，第一个是专注总时长，第二个是警报时长。
//! 专注会增加账户余额，移开焦点会扣除账户余额。如果说账户余额归零了，那就
//! 警报。可以设置权重也就是 1 分钟专注加多少，1 分钟离开扣多少。」
//!
//! 于是模型是：
//!
//! | 旋钮 | 字段 | 是什么 |
//! |---|---|---|
//! | 专注总时长 | [`Focus::total_minutes`] | 余额的**上限**（"这一轮打算写多久"） |
//! | 警报时长 | [`Focus::alarm_minutes`] | **一开始**有多少余额（"一上来能摸多久鱼"） |
//! | 专注权重 | [`Focus::gain_per_minute`] | 专注 1 分钟加多少余额 |
//! | 离开权重 | [`Focus::drain_per_minute`] | 离开 1 分钟扣多少余额 |
//!
//! ⚠️ **余额的单位是「分钟」**（内部存毫秒，见 [`Focus::上限毫秒`]），不是抽象点数。
//! 这样四个旋钮各自的话都说得通：默认 **25 / 20 / 1.0 / 1.0** 读出来就是
//! "打算写 25 分钟，一上来有 20 分钟额度，写 1 分钟赚 1 分钟，摸 1 分钟鱼赔 1 分钟"。
//!
//! # 为什么是这样而不是"每 20 分钟必响一次"
//!
//! 用户先说过「设置一个长一点的时间，大概 20 分钟左右，到了这个时间无论如何都会
//! 启动报警」，紧接着**自己推翻了**：「不是不是…并不是说每 20 分钟无论怎么样都
//! 响一下」，并且点出了那个漏洞——「应该考虑到他是不是单纯切换回来就为了避免警报」。
//!
//! 定时器模型下那个漏洞是无解的：切回来 3 秒也算"回到专注"，计时器一重置，
//! 于是"每 19 分钟切过去 3 秒"就能一直不响。账户模型下它自己就没了——
//! 切回来 3 秒只赚回 3 秒的额度，不够再撑 20 分钟。**只有真的在写，额度才会涨。**
//!
//! ⚠️ 这条是这一页存在的全部理由，改模型时先回来看这一段。

use serde::{Deserialize, Serialize};

/// 余额的计价单位：毫秒。
///
/// ⚠️ 不用浮点存余额。余额要被一秒一拍地加减，浮点累加会攒出可见的漂移，
/// 而"为什么我显示还剩 0.0000001 分钟但就是不响"是没人能排查的那类故障。
/// 费率是浮点（用户可能想要 0.5），但**乘完立刻取整成毫秒**，账本本身是整数。
const 一分钟毫秒: i64 = 60_000;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Focus {
    /// 余额上限，**分钟**。默认 25（一个番茄钟）。
    ///
    /// ⚠️ 它同时是"这一轮的目标"：写满它就封顶，不能无限攒额度当免死金牌。
    pub total_minutes: u32,

    /// 一开始的余额，**分钟**。默认 20。
    ///
    /// ⚠️ **它才是"多久不写就响"的那个数**（在默认权重下）：一上来有 20 分钟，
    /// 一直摸鱼，20 分钟后归零 → 警报。用户说的"过 20 分钟失焦就要警报一次"
    /// 指的就是这个旋钮，不是 [`Self::total_minutes`]。
    pub alarm_minutes: u32,

    /// 专注 1 分钟加多少余额（分钟）。默认 1.0。
    pub gain_per_minute: f64,

    /// 离开 1 分钟扣多少余额（分钟）。默认 1.0。
    ///
    /// ⚠️ 调到比 `gain_per_minute` 大就是"惩罚重于奖励"：写 2 分钟才够摸 1 分钟。
    /// 用户要"更强的模式"时该拧这个，而不是把 `alarm_minutes` 调到很小
    /// （那只是让一上来就快响，写起来之后该磨还是磨）。
    pub drain_per_minute: f64,

    /// 失焦后的**免罚宽限**（秒）。默认 10。
    ///
    /// ⚠️ 用户原话：「如果用户在这段时间内系统窗口焦点离开这个编辑器超过 10 秒」。
    /// 没有它的话，切出去查个单词、复制一行引用都要挨一刀，而那种扣费跟"摸鱼"
    /// 一点关系都没有——**罚得太密就等于没罚**，用户会干脆关掉这个功能。
    ///
    /// ⚠️ **宽限期内不欠账**：回来（或宽限期满）之后从第 11 秒才开始扣，
    /// 不是"先记上 10 秒的账、回头一起扣"。前者是"这 10 秒当没发生"，
    /// 后者是"反正你早晚要还"，两种语义差别很大，用户要的是前者。
    /// ⚠️ 设成 0 = 一失焦就扣。
    pub grace_seconds: u32,

    /// 警报响不响。默认**响**。
    ///
    /// ⚠️ 默认值就是用户要的效果（「发出尖锐的警报声」），所以是 `true`。
    /// 给这一格是留一条"我在图书馆"的出路，而不是因为出声不重要。
    pub sound: bool,

    /// **首次说明**弹窗看过了没有。默认 `false`（没看过）。
    ///
    /// ⚠️ 用户点名要这个弹窗：「首次打开强制专注模式的时候，弹窗提示用户，
    /// 这是个什么东西。明确的告诉用户这可能会用到什么系统权限，并且保证不会
    /// 窃取你的任何数据。」内容是**必须出现一次**的，所以这个位要落盘——
    /// 只在内存里的话，每次重启都会再被拦一次，用户很快就学会闭眼点掉，
    /// 而那正好把这次说明的意义抵消掉了。
    ///
    /// ⚠️ 看过之后仍然可以在设置页里重新打开那段说明（那颗按钮不是装饰）。
    pub introduced: bool,
}

impl Default for Focus {
    fn default() -> Self {
        Self {
            total_minutes: 25,
            alarm_minutes: 20,
            gain_per_minute: 1.0,
            drain_per_minute: 1.0,
            grace_seconds: 10,
            sound: true,
            introduced: false,
        }
    }
}

impl Focus {
    /// 余额上限（毫秒）。
    pub fn 上限毫秒(&self) -> i64 {
        self.total_minutes as i64 * 一分钟毫秒
    }

    /// 一轮开始时给多少余额（毫秒）。
    ///
    /// ⚠️ 夹到上限之内：用户完全可能把"警报时长"设得比"专注总时长"还长
    ///（一上来就有 40 分钟额度、上限却只有 25），那不矛盾，只是**开局就是满的**。
    /// 不夹的话余额会显示成一个大于上限的数，界面上那条进度条当场画炸。
    pub fn 起始毫秒(&self) -> i64 {
        (self.alarm_minutes as i64 * 一分钟毫秒).min(self.上限毫秒())
    }

    /// 专注一拍（`拍毫秒`）赚多少毫秒余额。
    pub fn 赚(&self, 拍毫秒: i64) -> i64 {
        (拍毫秒 as f64 * self.gain_per_minute) as i64
    }

    /// 离开一拍赔多少毫秒余额。
    pub fn 赔(&self, 拍毫秒: i64) -> i64 {
        (拍毫秒 as f64 * self.drain_per_minute) as i64
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 默认值就是用户说的那一套() {
        let f = Focus::default();
        assert_eq!(f.total_minutes, 25);
        assert_eq!(f.alarm_minutes, 20);
        assert_eq!(f.gain_per_minute, 1.0);
        assert_eq!(f.drain_per_minute, 1.0);
    }

    #[test]
    fn 默认权重下一直摸鱼二十分钟归零() {
        // ⚠️ 这条是**承重**的：用户说的"过 20 分钟失焦就要警报一次"在默认值下
        // 必须精确成立。改了任何一个默认值，这条会红，改的人得回来看
        // `focus.rs` 头部那两段，而不是顺手把断言也改了。
        let f = Focus::default();
        let mut 余额 = f.起始毫秒();
        let 一拍 = 1000;
        let mut 秒 = 0;
        while 余额 > 0 {
            余额 -= f.赔(一拍);
            秒 += 1;
            assert!(秒 < 3600, "一直摸鱼居然没归零");
        }
        assert_eq!(秒, 20 * 60, "默认值下该是 20 分钟整归零");
    }

    #[test]
    fn 写满就封顶() {
        // 上限不是"渐渐逼近"而是硬顶：写 25 分钟之后余额是 25 分钟，
        // 再写 25 分钟还是 25 分钟。否则用户能先攒两小时额度再摸两小时鱼。
        let f = Focus::default();
        assert_eq!(f.上限毫秒(), 25 * 一分钟毫秒);
        assert_eq!(f.起始毫秒(), 20 * 一分钟毫秒);
    }

    #[test]
    fn 起始余额不会超过上限() {
        let f = Focus {
            total_minutes: 5,
            alarm_minutes: 40,
            ..Focus::default()
        };
        assert_eq!(f.起始毫秒(), 5 * 一分钟毫秒);
    }

    #[test]
    fn 权重可以是小数() {
        let f = Focus {
            drain_per_minute: 0.5,
            ..Focus::default()
        };
        // 0.5 倍：摸 1 分钟只赔 30 秒
        assert_eq!(f.赔(60_000), 30_000);
        assert_eq!(f.赔(1000), 500);
    }

    #[test]
    fn 宽限期默认是用户说的十秒() {
        assert_eq!(Focus::default().grace_seconds, 10);
    }

    #[test]
    fn 警报默认要响() {
        assert!(Focus::default().sound);
    }

    #[test]
    fn 说明弹窗默认没看过() {
        assert!(!Focus::default().introduced);
    }

    /// ⚠️ 这里曾经有一条 `宽限名单默认是空的`。2026-09-26 用户把宽限名单整个砍了
    ///（「宽限名单不用开了。把这个功能删掉吧，干脆」），字段没了，测试跟着走。
    /// 为什么砍、砍得有道理在哪儿，写在 `crate::focus` 的模块头「它不做什么」那一段。
    #[test]
    fn 设置里没有任何看别的应用的东西() {
        // ⚠️ 这条是**承重**的，不是形式主义。它守的是一个决定：
        // **强制专注只看本应用自己的窗口有没有焦点，不越过应用的边界。**
        // 要加回"读活动窗口"这类能力，先改 `focus` 模块头那段说明，
        // 然后这条测试会红，然后改它的人必须解释为什么。
        let text = toml::to_string_pretty(&Focus::default()).unwrap().to_lowercase();
        for 禁 in ["app", "window", "foreground", "xprop", "process", "title"] {
            assert!(
                !text.contains(禁),
                "强制专注的设置里不该出现「{禁}」——它不该看别的应用：\n{text}"
            );
        }
    }

    #[test]
    fn 落盘形状是_focus_表() {
        // 形状要和 `settings/mod.rs` 头部那张"新字段一律进 [页名] 表"对得上。
        #[derive(Serialize)]
        struct 外壳 {
            focus: Focus,
        }
        let text = toml::to_string_pretty(&外壳 {
            focus: Focus::default(),
        })
        .unwrap();
        assert!(text.contains("[focus]"), "{text}");
        assert!(text.contains("total_minutes = 25"), "{text}");
    }
}
