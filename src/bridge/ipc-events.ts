/**
 * 事件通道：宿主推给前端的「此刻发生了一件事」。
 *
 * 2026-10-17 从 `ipc.ts` 拆出（那边新增打印接口后到 1006 行，破了
 * `docs/09` §4 的 1000 行硬线）。切点是现成的：`ipc.ts` 只留命令调用，
 * 事件订阅与频道名在这里。`ipc.ts` 末尾原样再导出，所以所有
 * `import { events, on } from "@/bridge/ipc"` 的调用点一处都不用改。
 */

import { listen, type UnlistenFn } from "@tauri-apps/api/event";

/**
 * 订阅一个宿主事件。返回退订函数——**组件卸载时一定要调**，
 * 不然热重载几轮之后同一个事件会有好几个监听者，一次通知弹好几遍。
 */
export function on<T>(event: string, handler: (payload: T) => void): Promise<UnlistenFn> {
  return listen<T>(event, (e) => handler(e.payload));
}

