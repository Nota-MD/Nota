/**
 * 「严格模式」在前端的**唯一一份判据**。
 *
 * 严格模式（`Settings.strict_markdown`，在「偏好设置 → Markdown」那一节里）
 * **默认关**，目前只管一件事：**ATX 标题的井号后面必须有空格**。
 *
 * | 模式 | `#你好` | `# 你好` |
 * |---|---|---|
 * | 关（默认，下面叫**宽松**） | **算标题**（进大纲、进标签页标题） | 是 |
 * | 开（严格） | 不是，就是普通段落 | 是 |
 *
 * # ⚠️ "默认关"意味着**把 Nota 从来的行为放宽**
 *
 * Nota 的解析与序列化处处按 CommonMark 来——等于**一直待在严格那一档**。
 * 所以这个开关的真实含义是"默认变成宽松"，写在这里免得下次有人以为反了。
 * 标题识别的判据、两种模式的完整口径见 `docs/05` §2.1c。
 *
 * # ⚠️⚠️ 宽松模式**一个字节都不改，也不改长相**（用户 2026-09-24 / 09-26 两次定的）
 *
 * 原话一是「**如果关闭，存盘不要自动修复。**」（2026-09-24），
 * 二是「**应该作为标识符的 `#` 不要变换位置和大小。**」（2026-09-26）。
 *
 * 所以宽松**不是**"把 `#你好` 补成 `# 你好` 再当标题"——那种做法在存盘时
 * 会把用户写的字改掉（第一版就是这么写的，被否了）。**文档树里它一直就是
 * 普通段落**（解析器一个字都不动）→ 存盘必然存回 `#你好`。
 *
 * ⚠️ **正文那侧的长相改过三次，现在是第三次**（2026-09-30）：
 *
 * | 时间 | `#你好` 在正文里长什么样 |
 * |---|---|
 * | 09-26 之前 | 整段套一层 `h1` 排（装饰是 `Decoration.node`） |
 * | 09-26 ～ 09-29 | 与普通段落**一模一样**（第二句原话就是冲着上一版说的） |
 * | 09-29 ～ 09-30 | 那段文字按该级标题字号排、井号不动 |
 * | **09-30 起（现在）** | **只加粗**——和 `# 你好` 走完全同一条路：没按回车只加粗，按了回车才成块放大 |
 *
 * 最后一次改的理由是用户当天那句「**类似 `# 你好`。就是不回车只是显示加粗，
 * 回车变成标题。**」，判据与代价写在 `heading-on-enter.ts` 文件头。
 * ⚠️ **"认不认"这件事从头到尾没取消过**——来回变的只是长相；本文件这几条
 * 判据一直是同一份，四处（正文装饰／大纲／源码模式／标签页标题）共用。
 *
 * ⚠️ "不改字"这条规矩是**结构性**的：从"段落"到"文件"这条路上没有任何一步
 * 会改字，所以"存盘被自动修复"不可能发生。任何"补个空格"式的改动都会破坏它。
 *
 * ⚠️ **一处例外，2026-09-30 定，边界要记清**：宽松档下**用户自己按回车**
 * 把 `#你好` 变成标题块时，序列化出来是 `# 你好`——**多一颗空格**（标题节点
 * 固定是"井号 ＋ 空格 ＋ 正文"，见 `heading-on-enter.ts`）。那不是"自动修复"，
 * 是用户按下去要的那个结果（原话「回车变成标题」）。
 * **不按回车，一个字节都不动**——上面那条规矩仍然成立，别把它读成可以随便补。
 *
 * # 为什么单独一个文件
 *
 * 认标题的地方**不止一处**，判据必须**一模一样**（一律引本文件，不各写一份）：
 *
 * 1. 源码模式里"这一行已经是标题了吗" —— `source.ts` 用 `atxPrefixRe`（本文件）；
 * 2. 大纲 —— `ui/outline.ts` 用 `atxTextRe`（本文件）。
 *
 * ⚠️ **后端有一份同构的**：`src-tauri/src/document/mod.rs` 的 `strip_atx`
 * （从正文猜标签页标题用）。**两边一起改**，改完两边的测试都跑
 * （`cargo test --lib` + `npx tsc --noEmit`）。
 *
 * ⚠️ 原来这里还有一个 `宽松标题层数`（判"这段文本算几级宽松标题"），给那条
 * 显示层装饰用的；装饰删掉之后它就没有调用者了，**2026-09-26 一并删掉**
 * ——判据本身没丢：`atxTextRe(false)` 认的正是同一批行。
 */

/**
 * 抽标题正文用的正则：`m[1]` 是井号（层数），`m[2]` 是正文。
 *
 * 严格 = 井号后**至少一个空白**；宽松 = 空白可有可无。
 * ⚠️ 宽松那份用 `\s*` 是因为**真的没有**空白（`#你好`），不是"容忍多余空格"。
 */
export function atxTextRe(strict: boolean): RegExp {
  return strict ? /^(#{1,6})\s+(.*)$/ : /^(#{1,6})\s*(.*)$/;
}

/**
 * 行首标记正则：源码模式里"这一行已经是标题了吗"（`setLinePrefix` 拿它决定
 * 该清掉多长一段）。
 *
 * ⚠️ 宽松那份的 ` ?` 是**可选**：`#你好` 也要被认出"已经带了井号"，
 * 否则按「标题 1」会得到 `# #你好`，按「正文」则什么都不发生。
 */
export function atxPrefixRe(strict: boolean): RegExp {
  return strict ? /^#{1,6} +/ : /^#{1,6} ?/;
}

/**
 * 一段文本**整段**是一个 ATX 标题写法吗？是的话返回前缀那两样东西
 * （层数 ＋ 长度），不是返回 `null`。
 *
 * ⚠️ **判据与 [`atxTextRe`] 是同一份**，不是照着重写一遍：`#你好` 在宽松档下
 * 算标题这件事，大纲、源码模式、标签页标题**三处早就认了**，只有正文那一处
 * 不认——用户 2026-09-29 报的「严格模式关闭后 `#标题` 还是无法正常显示」
 * 说的就是这个自相矛盾。所以正文这边**引同一份正则**，往后谁改了那一条，
 * 四处一起动。
 *
 * ⚠️ 长度用 `m[0].length - m[2].length` 算，**不要**另写一条 `^#{1,6}\s*`
 * 去数井号：宽松那条的 `\s*` 会把 `#` 与正文之间**任意多个**空白都吃掉，
 * 自己数井号会把 `#  标题` 那段空白留在加粗范围里。少想一步，多一个分叉。
 *
 * ⚠️ **层数给的是 `m[1].length`**（井号的个数），`#` 与 `##` 就是靠它分开的。
 * **正文那侧现在两个数都要**：`长度` 决定装饰从哪儿起（`算装饰条目`），
 * `层数` 决定回车成块时 `create` 成几级标题（`回车成标题`）。
 * ⚠️ 层数在正文那边**曾有过第三个用处**——选 `.nota-lax-hN` 那一档字号
 * （09-29 ～ 09-30 那版），那条长相没了，别照旧稿找它。
 * 两个数一起返回，是因为**从同一个匹配里出来**——分成两个函数各 exec 一次，
 * 两份结果哪天对不上就是"字号和井号个数不一样"。
 */
export function atxPrefix(text2: string, strict: boolean): { layerNumber: number; lengthDegree: number } | null {
  const m = atxTextRe(strict).exec(text2);
  if (!m) return null;
  return { layerNumber: m[1]!.length, lengthDegree: m[0].length - (m[2] ?? "").length };
}
