/**
 * 「严格模式」在前端的**唯一一份判据**。
 *
 * 严格模式（`Settings.strict_markdown`，在「偏好设置 → Markdown」那一节里）
 * **默认关**，目前只管一件事：**ATX 标题的井号后面必须有空格**。
 *
 * | 模式 | `#你好` | `# 你好` |
 * |---|---|---|
 * | 关（默认，下面叫**宽松**） | **是一级标题** | 是 |
 * | 开（严格） | 不是，就是普通段落 | 是 |
 *
 * # ⚠️ "默认关"意味着**把 Nota 从来的行为放宽**
 *
 * 这不是我拍的：对标对象 Typora 的「严格模式」本身就默认关着（位置、
 * 官方记的两条差异见 `docs/10-typora-parity.md` §11.3）。而 Nota 从第一天起
 * 处处按 CommonMark 来——等于**一直待在严格那一档**。所以这个开关的真实含义
 * 是"默认变成宽松"，写在这里免得下次有人以为反了。
 *
 * # ⚠️⚠️ 宽松模式**一个字节都不改**（用户 2026-09-24 定的死规矩）
 *
 * 原话：「**如果关闭，存盘不要自动修复。**」
 *
 * 所以宽松**不是**"把 `#你好` 补成 `# 你好` 再当标题"——那种做法在存盘时
 * 会把用户写的字改掉（第一版就是这么写的，被否了）。现在的做法是：
 *
 * - **文档树里它就是普通段落**（解析器一个字都不动）→ 存盘必然存回 `#你好`；
 * - 只是**显示上**按标题排版（`lax-heading.ts` 挂一个装饰，真标签、假节点）。
 *
 * ⚠️ 这条规矩是**结构性**的：从"段落"到"文件"这条路上没有任何一步会改字，
 * 所以"存盘被自动修复"不可能发生。想加"顺手补个空格"的念头，先回来看这段。
 *
 * # 为什么单独一个文件
 *
 * 认标题的地方**不止一处**，判据必须**一模一样**（引本文件，别各写一份）：
 *
 * 1. 正文里怎么**显示**成标题 —— `lax-heading.ts` 用 `宽松标题层数`（本文件）；
 * 2. 源码模式里"这一行已经是标题了吗" —— `source.ts` 用 `atxPrefixRe`（本文件）；
 * 3. 大纲 —— `ui/outline.ts` 用 `atxTextRe`（本文件）。
 *
 * ⚠️ **后端有一份同构的**：`src-tauri/src/document/mod.rs` 的 `strip_atx`
 * （从正文猜标签页标题用）。**两边一起改**，改完两边的测试都跑
 * （`cargo test --lib` + `npx tsc --noEmit`）。
 */

/**
 * 判据本体：行首井号后面**直接**跟正文（中间一个空白都没有）。
 *
 * ⚠️ 零宽先行（`(?=…)`）：只判"井号后面紧跟的不是空白"，**不吃正文**——
 * 下面几个用它的地方都是要拿"层数"或"剩余正文"，吃了一定会丢字。
 */
const LAX_ATX = /^(#{1,6})(?=[^\s#])/;

/**
 * 这段文字算不算**宽松标题**：算 → 返回层数 1..6，不算 → 返回 0。
 *
 * ⚠️ 传进来的必须是**段落开头那一段纯文本**，不是整篇、也不是 `textContent`：
 * 行内代码（`` `#你好` ``）和小标题里的井号不是标题的井号，调用方要挡掉
 * （见 `lax-heading.ts` 里"第一个孩子是文本节点"那一条）。
 */
export function 宽松标题层数(text: string): number {
  const m = LAX_ATX.exec(text);
  return m ? m[1]!.length : 0;
}

/**
 * 抽标题正文用的正则：`m[1]` 是井号（层数），`m[2]` 是正文。
 *
 * 严格 = 井号后**至少一个空白**；宽松 = 空白可有可无。
 * ⚠️ 宽松那份用 `\s*` 是因为**真的没有**空白（`#你好`），不是"容忍多余空格"。
 */
export function atxTextRe(strict: boolean): RegExp {
  return strict ? /^(#{1,6})\s+(.*)$/ : /^(#{1,6})\s*(.*)$/;
}

/**
 * 行首标记正则：源码模式里"这一行已经是标题了吗"（`setLinePrefix` 拿它决定
 * 该清掉多长一段）。
 *
 * ⚠️ 宽松那份的 ` ?` 是**可选**：`#你好` 也要被认出"已经带了井号"，
 * 否则按「标题 1」会得到 `# #你好`，按「正文」则什么都不发生。
 */
export function atxPrefixRe(strict: boolean): RegExp {
  return strict ? /^#{1,6} +/ : /^#{1,6} ?/;
}
