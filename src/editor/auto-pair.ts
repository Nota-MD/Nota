/**
 * **自动配对**（打 `(` 当场补一颗 `)`）＋ **Tab 跳出右半边**。
 * 2026-09-28 落地，用户原话：「Tab 跳出右半边，Tab 跳出右半边」（说了两遍，
 * 意思很明确）。对标对象是 VMark 的 `src/plugins/autoPair/`（五个文件、约一千
 * 一百行），本文件按 Nota 的口径重写——**三处刻意的差别**在第 4 节。
 *
 * # 1. 两件事，一张表
 *
 * | 什么时候 | 做什么 |
 * |---|---|
 * | 打一个**开括号** | 当场补上它那颗**闭括号**，光标落在中间（`(` ⇒ `()`，光标在 `(` 后面） |
 * | 打一颗**闭括号**、而右边**正好就有一颗一样的** | **不插**，光标跳过它（用户在"把这一对写完"） |
 * | 光标**夹在一对空的括号中间**按退格 | 两颗一起删（不然要按两次） |
 * | 光标右边**紧挨着一颗闭括号**时按 `Tab` | 光标**跨过去**（"跳出右半边"），**不改字** |
 * | 光标左边**紧挨着一颗开括号**时按 `Shift+Tab` | 光标**跨回去**（对称的那半边） |
 * | 打一颗 **`*`** | **自配对**（见 §2.1）：`*` ⇒ `*|*`，再打一颗 ⇒ `**|**`；**收尾那一颗把它落成斜体 / 粗体**（§2.3） |
 * | 打一颗 **`[`** | 补一颗 `]`；⚠️ 光标夹在一对**空的**方括号里再打一颗 ⇒ `[[|]]`（见 §2.2） |
 *
 * ⚠️ **后两条是"移动"不是"编辑"**：派出去的事务带 `addToHistory: false`，
 * 所以 `Ctrl+Z` **不会**为"按了一次 Tab"回退一步——那是导航，不是改动。
 *
 * ⚠️ **整条插件由一个开关管**（`Settings.editor.smart_symbols`，
 * 界面上的「智能符号补全」，**默认开**）：关掉时 {@link 配对处理} 返回 `[]`，
 * 也就是**这条插件不装**。用户 2026-09-28 原话：「自动补全 `*`、`[` 这种在设置中
 * 搞一个选项，智能符号补全。默认为开。」
 *
 * # 2. 表里收哪些、不收哪些（**这是本文件最要紧的一段**）
 *
 * 收：`(` `{` 与中文那一族 `（【「『《〈`，**`[`**（§2.2），以及 **`*`**
 * ——⚠️ 它**不进 {@link 配对表}**，走的是 {@link 自配对表} 那条路（§2.1）。
 *
 * 不收的**每一个都有具体理由**，不是忘了：
 *
 * - **`"` / `'`** —— 智能标点（`smart-punctuation.ts` 的输入规则）**已经管着**
 *   这两颗字符：它按"前面那一个字符"决定弯成 `“` 还是 `”`。这里再补一颗，
 *   同一颗按键就有两套规则，症状随"哪个插件排在前面"变——**不能这么干。**
 * - **`` ` ``** —— ⚠️ 收了它反而会让**行内代码永远标不出来**：上游
 *   `inlineCodeInputRule`（`preset-commonmark` 的 `/`([^`]+)`$/`）要的是
 *   **用户亲手敲下闭引号那一下**才把中间那段标成 `inlineCode`；我们补的
 *   那颗闭引号**不是"敲"进来的**，等用户打 `` ` `` 想收尾时，又会被本文件的
 *   "跳过闭括号"吃掉——于是文档里是一串**没有标记的**反引号。得不偿失。
 * - **`_` `~` `=`** —— 全是 Markdown 的**标记字符**（斜体 / 删除线 / 高亮）。
 *   补一颗就等于替用户改了语法，理由与 `*` 那条同源（§2.1 的"判断为是"）。
 *
 * ## 2.1 ⚠️ `*` 是**例外**：2026-09-28 用户点名把它收了
 *
 * 用户原话：「**写一个算法判断比如输入一个 `*` 自动补全另一个。如果判断为是则
 * 就补全**」。所以这一条**不是**"忘了它也是标记字符"，是**推翻**了上面那条
 * 一刀切——要点在他自己那句话里：**"判断为是"**。`*` 补不补，是要看现场的。
 *
 * 三条规则（判据是 {@link 要补标记}）：
 *
 * | 现场 | 做什么 |
 * |---|---|
 * | 正文里打一颗 `*` | 补一颗，光标落中间（`*\|*`） |
 * | 光标正夹在一对**空的**星号里再打一颗（`*\|*`） | **升级**成 `**\|**`（打一颗就变粗体） |
 * | 右边已经有星号、而**左边不是**（`*粗\|*`、`**粗\|**`） | **落成真标记**（斜体 / 粗体） |
 *
 * ⚠️ 第三行 2026-09-29 从"跳过"改成了"落成真标记"（BUG-54，见 §2.3）：
 * **跳过那一下白跳**——我们补的那颗闭星号不是用户敲的，上游那条强调的输入规则
 * 永远等不到，于是屏幕上留着两颗字面星号、存盘还要被转义成 `\*粗\*`。
 * 落标记之后屏幕上就是斜体，盘上是干干净净的 `*粗*`。
 *
 * 三条"不补"（其余在 {@link 要补标记} 上逐条写着）：**段首**（那是项目符号
 * `* 项目`，补了就废掉一个列表项）、**有选区**（括号上那是"包起来"，星号上
 * 那是替用户按了斜体）、**代码里 / 转义**（与前四条同源）。
 *
 * ⚠️ 为什么**单开一张表**不进 {@link 配对表}：那张表的四个判据全都建立在
 * "开 ≠ 闭"上，把 `*` 塞进去会让 `*\|*` 里的退格、`Tab` 同时匹配两边的规则。
 *
 * ⚠️ **`_` / `~` / `=` 照旧不收**：它们论形状与 `*` 同类，但用户那个"比如"
 * 不构成替另外三颗做主（见 {@link 自配对表} 上那段）。
 *
 * ## 2.2 ⚠️ `[` 2026-09-28 从「不收」改成了「收」（用户点名）
 *
 * 用户原话：「自动补全 `*`、**`[`** 这种在设置中搞一个选项，智能符号补全。
 * 默认为开。」⚠️ 他点的是**这颗字符本身**，不是「随便再收几个」。
 *
 * ⚠️ **它当年是被专门挡在门外的**，那一条现在读起来仍然有道理：`[` 是
 * Markdown 链接的开头（`[文字](地址)`），补一颗 `]` 有可能把语法弄坏。
 * 今天照用户的话收进来，靠三件事把那个风险压住：
 *
 * ① **打 `]` 时「跳过」**：用户写链接是 `[` → 文字 → `]` → `(地址)`，
 *    那颗敲下去的 `]` 不插字、只跨过我们补的那一颗，于是链路仍然是
 *    `[文字](地址)`。⚠️ **这一条没有在真窗口里逐键走过**（列在 `docs/07` §4）。
 * ② **`[[` 升级**（{@link 可升级表}）：Wiki 链接 `[[页面]]` 打两次 `[`
 *    得到 `[[|]]`，不是 `[][]`——那个形状**打不出** `[[..]]`。
 * ③ **一个开关就能关掉整条插件**（`smart_symbols`，见 §1 末）：真被咬到了，
 *    用户不必等我们发版。
 *
 * ⚠️ 与 `*` 那条不同的是，`[` **进 {@link 配对表}**（开 ≠ 闭，那四个判据
 * 全都成立），只有「升级」那一下走 {@link 可升级表}。
 *
 * ## 2.3 ⚠️ 收尾那一下要**落成真标记**（BUG-54；2026-09-29 首修，**2026-09-30 补齐触发时机**）
 *
 * 用户 2026-09-28 的原话：「**所见即所得模式下，自动补全的星号在代码模式下
 * 前面有斜杠导致无效**」。量到的现场是：所见即所得里打 `*甲*`（闭星号是补出来
 * 的），切到源码模式一看是 `\*甲\*` ——一对星号成了字面文本。
 *
 * **反斜杠不是 bug，是症状。** `mdast-util-to-markdown` 对"字面星号"就该转义
 * （不加反斜杠它重开时会变成斜体，那是改用户的数据），所以序列化器那一侧**不
 * 能动**——修法只能在编辑器这一侧：**让这一对星号真的成为 `emphasis`**。
 * ⚠️ 别被"去掉反斜杠"这个方向带跑，`inline-marks.ts` 的 `不转义孤立波浪号`
 * 顶上那段把这条道理写透过（宁可留着噪音，不许改数据）。
 *
 * **为什么这一对星号连"字面星号"都算不上**：我们补的那颗闭星号**不是用户敲
 * 的**，上游 `emphasisInputRule` 要的是"用户刚敲下的那一颗就是闭定界符"，它永
 * 远等不到。于是老代码在收尾那一下只做"光标跨过去"——**白按**。
 *
 * ### ⚠️⚠️ 首修为什么没修好（2026-09-30，用户第二次报同一件事）
 *
 * 用户原话：「**还是会自动插入斜杠。渲染仍未成功。**」（截图里 `*你好*` 是
 * 正体、两颗星都在）。首修只改了 {@link 补标记} 的「跳过」那一支——**那一支要
 * 求有一颗真的按键落在闭星号上**。可 `*` 是自配对的：闭星号是**我们插进去的
 * 字符**，永远不会有按键走到那里。于是那一条**只在用户自己把第三颗星敲出来时
 * 才走得到**，而用户抱怨的恰恰是「不敲第三颗」那条路（`x` → `*` → `你好`，屏幕
 * 上看着已经是 `x*你好*` 了，谁还会再敲一颗）。
 *
 * 现在同一个 {@link 收尾事务} 挂在**三个触发时机**上（哪三个、各走哪条路，逐
 * 条写在那个函数的 jsdoc 上，连同判据与代价），另外还有一条**兜底**：
 *
 * ⚠️ **拼音输入法压根不走 `handleTextInput`**：候选框上屏是一笔直接插字的
 * `Transaction`。所以 {@link 配对处理} 里另挂了 `appendTransaction`，对**每一
 * 笔**落定的事务重问一遍 {@link 收尾事务}。⚠️ 它只在这一对**已经进文档之后**
 * 才看得见现场，那一次传 `结束 = false`（人还在这一对**里面**打字，标记得继续
 * 生效——传 `true` 会把光标后的输入踢出斜体，实测过）。⚠️ 还得真挂在插件上才
 * 跑得到，光有函数不算数；`tests/auto-pair.test.ts` 第十二组正是靠那份
 * `plugins: [收尾插件]` 才量到这条路。
 *
 * ⚠️ **已有标记的尾巴上再敲 `*` ⇒ 一个字符都不加**（{@link 尾巴带标记} ＋
 * {@link 到此为止事务}）：插一颗字面星号进去，盘上就会是 `*甲*\*`——**正是用户
 * 抱怨的"自动插入斜杠"**。宁可吞掉这颗按键，也不亲手制造那份噪音。
 *
 * 于是：
 *
 * | 用户打的 | 屏幕上 | 存到盘上 |
 * |---|---|---|
 * | `*` → `甲` → `*`（收尾） | *甲* | `*甲*` ✓ |
 * | `*` → `*` → `甲` → `*`（收尾） | **甲** | `**甲**` ✓ |
 * | `*` → `甲`（**不敲第三颗**） | *甲* | `*甲*` ✓ ← 首修漏的就是这一条 |
 * | `甲` 打成斜体后再敲 `*` | 不变 | 不变（那颗键被吞掉） |
 *
 * # 3. 判据全是纯函数，落点只有一个
 *
 * {@link 读现场} 把 `EditorState` 收成一小份 {@link 现场}（前一颗字符 / 后一颗
 * 字符 / **后第二颗** / 在不在代码里 / 选区空不空），{@link 要配对} 那五个
 * **只吃这份现场**。
 * 于是 `tests/auto-pair.test.ts` 不用建 `Editor` 实例就能把每一种边界钉住
 * （`lang-guess.ts` / `url-link.ts` 同一套手法）。⚠️ 这也是**唯一的落点**：
 * 插件那一层只负责"读现场 → 问判据 → 派事务"，一个判断都不多做。
 *
 * # 4. 与 VMark 的三处差别（**不是漏抄**）
 *
 * ① **配对表短得多**：VMark 收 `[` / 反引号 / 直引号（外加一个"反引号切换
 *    行内代码"的独立模块 `backtickToggle.ts`）。本仓收 `[`（2026-09-28，
 *    用户点名）**不收**反引号与直引号，理由在上一节。⚠️ 它们的代价是 VMark
 *    那套要额外维护"IME 宽限期"、"右双引号规范化"那一堆补丁——那些补丁本身
 *    就是在收拾这张长表的后果。
 * ② **`Tab` 走 `handleKeyDown`，不走 `handleDOMEvents.keydown`**：VMark 那么写
 *    是为了抢在 Tiptap 自己的键位表前面。Nota 这边 `handleKeyDown` 是
 *    **本仓既有的口径**（`table-input.ts` 顶上明写过"必须是 `handleKeyDown`，
 *    不能写成 `$useKeymap` 抢 priority"），而且 `.use()` 顺序足够让它排在
 *    `indent` 前面。
 * ③ **只有一个设置项，而且是用户点名要的**：`smart_symbols`（界面上的
 *    「智能符号补全」，**默认开**，2026-09-28 加）。VMark 有四个开关
 *    （`enabled` / `includeCJK` / `includeCurlyQuotes` /
 *    `normalizeRightDoubleQuote`），我们**只收它第一个**——其余三个是
 *    "把这套规则拆细"，而本仓的口径是**一件事一个开关**（同 `emoji` 那条：
 *    一个开关管"短代码替换 ＋ 补全面板"两件事）。⚠️ 加这一格要同时动 Rust
 *    设置、界面控件、中文包与文档，这一批都做了。
 *
 * # 5. 已知边界（如实记着）
 *
 * - ⚠️ **没"收尾"的那一对星号仍是字面文本**（§2.3 末）：存盘会被转义成
 *   `\*甲\*`。要有意保留字面星号就**别去打最后那一颗**；打了就是"我要斜体"。
 *   ⚠️ **2026-09-30 起只有"打了一半"才落在这条上**：`*甲` 停在半路（或者中途
 *   把光标点到别处）仍是字面文本；`x` → `*` → `甲` 这条**已经算收尾**了，
 *   因为补出来的闭星号就在光标右边——首修把这两件事混成一件，才有第二次报。
 *
 * - ⚠️ **中文输入法在组字时一律不动**（`view.composing`）：打 `（` 的过程里
 *   有一次 composition，那期间插手会把候选框里的东西打乱。代价是
 *   **中文全角括号常常配不上对**——它们多数是输入法直接上屏的，压根不走
 *   `handleTextInput`。这是**有意**的取舍：宁可少配几次，不能干扰输入法。
 * - ⚠️ **代码块与行内代码里不配对、也不跳 Tab**（`在代码里` 那道闸）：
 *   代码里要的是原样字符，而 `Tab` 在那里该**缩进**（上游 `indent` 插件干这个）。
 *   ⚠️ **但"跳过闭括号"与"退格删成对"在代码里**照常——那两条只作用于用户
 *   自己敲出来的字符，且都是常规编辑器的做法。
 * - ⚠️ **转义不配对**：光标前面紧挨着 `\` 时一律不动（用户写 `\(` 就是想要
 *   一颗光秃秃的左括号）。**但不去判"这个反斜杠自己是不是被转义的"**
 *   （`\\(` 那种）：多一层判断换来的场景太少。
 * - ⚠️ **不补"配对之外"的东西**：不管引号朝向、不管 Markdown 标记、
 *   不做"打 `]` 自动补 `(地址)`"那种 Smart Brackets。那些都是另一件事。
 */

import { $prose } from "@milkdown/kit/utils";
import type { Node as 模型节点 } from "@milkdown/kit/prose/model";
import { Plugin, PluginKey, TextSelection } from "@milkdown/kit/prose/state";
import type { EditorState, Transaction } from "@milkdown/kit/prose/state";
import type { EditorView } from "@milkdown/kit/prose/view";

/** 插件键。⚠️ 起了名字才好在上游那一串里认出自己（调试时 `state.plugins` 上看）。 */
export const 配对键 = new PluginKey("notaAutoPair");

/**
 * **开括号 → 闭括号**。⚠️ 加项之前先读文件头第 2 节：那里逐条写着**不收**
 * 的几个字符（引号 / 反引号 / Markdown 标记）各自的具体理由。
 *
 * ⚠️ **`[` 2026-09-28 从"不收"改成了"收"**（用户点名，见文件头 §2.2）——
 * 它当年被挡在门外是因为"少一个便利"换"别把 Markdown 链接弄坏"，而
 * {@link 可升级表} 那一层把 `[[`（Wiki 链接）也安顿好了。
 */
export const 配对表: Readonly<Record<string, string>> = {
  "(": ")",
  "{": "}",
  /* ⚠️ 用户 2026-09-28 点名要的：「自动补全 `*`、`[` 这种」。 */
  "[": "]",
  /* 中文全角那一族。⚠️ 与 VMark 那份一致，唯独没抄它的 `（）` 之外的引号。 */
  "（": "）",
  "【": "】",
  "「": "」",
  "『": "』",
  "《": "》",
  "〈": "〉",
};

/**
 * 反过来的那张（闭 → 开）。**从 {@link 配对表} 推出来**，不手写第二份
 * （手写就会两边不同步，而那是"配对"这件事最不能出的错）。
 */
const 反表: Readonly<Record<string, string>> = (() => {
  const 表: Record<string, string> = {};
  for (const [开, 闭] of Object.entries(配对表)) 表[闭] = 开;
  return 表;
})();

/** 这颗字是不是本文件认的开括号。 */
export function 是开括号(字: string): boolean {
  return 配对表[字] !== undefined;
}

/** 这颗字是不是本文件认的闭括号。 */
export function 是闭括号(字: string): boolean {
  return 反表[字] !== undefined;
}

/**
 * 这颗开括号配哪颗闭括号；不是开括号给 `null`。
 *
 * ⚠️ 用 `?? null` 而不是 `配对表[字]` 直接返回：表里查不到给的是 `undefined`，
 * 而调用方一律按 `null` 判（`if (!闭)` 那种写法两个都能过，但混着用迟早
 * 会在 `===` 比较上翻车）。
 */
export function 闭括号(开: string): string | null {
  return 配对表[开] ?? null;
}

/** 这颗闭括号配哪颗开括号；不是闭括号给 `null`。 */
export function 开括号(闭: string): string | null {
  return 反表[闭] ?? null;
}

/* ── 现场：把 EditorState 收成一小份，判据只吃它 ───────────────────────── */

/**
 * **判据要的全部上下文**。四格，一格不多。
 *
 * ⚠️ 刻意**不把 `EditorState` 传进判据**：那样测试就得造一个真 schema ＋
 * 真实例，而本仓没有 jsdom、也不许为测试装包（`tests/` 那一族全是这个口径）。
 */
export interface 现场 {
  /** 光标**左边**那一颗字符；行首（或前面是图片这类原子）给 `""`。 */
  前: string;
  /** 光标**右边**那一颗字符；行尾给 `""`。 */
  后: string;
  /**
   * 光标右边**第二颗**字符；不足两颗给 `""`。
   *
   * ⚠️ 今天**只有自配对字符用得上**（{@link 要补标记}）：`*\|*` 与 `*粗\|*`
   * 的区别全在这里——前者右边只有一颗星（用户在扩成粗体），后者右边也是
   * 一颗星、但左边不是（用户在收尾）。括号那一族不需要它。
   */
  后二: string;
  /** 光标落在代码块或行内代码里。 */
  代码: boolean;
  /**
   * 光标在**代码块**里（`code_block` 那个节点里），而不是行内代码 `` `x` ``。
   *
   * ⚠️ 与上面那个布尔分开是 2026-10-06 加的：两者原先合成一个，于是
   * 「代码里不配对」这条**把代码块也一起管了**——而代码块里打 `(` 补一个 `)`
   * 恰恰是**任何编辑器都有的手感**（用户当天：「代码输入框没有类似真正编辑器的
   * 手感（比如自动补全对半符号和缩进）」）。行内代码仍旧不配（那是正文里的一句话）。
   */
  代码块: boolean;
  /** 选区是空的（没有选中任何东西）。 */
  空选区: boolean;
  /**
   * 光标左边那一颗字符**正好是这一段的第一颗**（`前` 是段首，`前` 之前没有字）。
   *
   * ⚠️ 2026-10-16 加，只为一件事：**段首那颗 `*` 是"没配上对的"**（见
   * {@link 要补标记} 的第 ⑤ 条：段首打 `*` 是项目符号，故意不补）。于是
   * 用户接着打第二颗时，现场是 `*|`（左边一颗、右边什么都没有），与
   * "在别处打了一颗没配上对"长得一样——判据要能把这两者分开，
   * 「补齐」那一支才敢动手。理由与那次报的缺陷见 {@link 要补标记}。
   *
   * ⚠️ 它**只描述光标左边那一颗的位置**，不描述"整段是不是空的"。
   */
  前是段首: boolean;
}

/** 光标在某一段文字里的"前一颗 / 后一颗"。⚠️ 边界与原子节点一律给 `""`。 */
function 取字符(state: EditorState, 位置: number, 偏移: -1 | 1): string {
  const 尺寸 = state.doc.content.size;
  if (位置 < 0 || 位置 > 尺寸) return "";
  const $位 = state.doc.resolve(位置);
  // ⚠️ 块级位置上（`parent` 不是行内容）取不到"字符"——那说明光标在
  // 两段之间，不是"挨着一颗括号"。
  if (!$位.parent.inlineContent) return "";
  const 起 = $位.parentOffset + (偏移 === -1 ? -1 : 0);
  const 止 = 起 + 1;
  const 长 = $位.parent.content.size;
  if (起 < 0 || 止 > 长) return "";
  // ⚠️ `textBetween` 的 `leafText` 不传 ⇒ 图片、公式那类原子贡献 `""`
  //（它们身上没有"字符"可配对），这正是想要的。
  return $位.parent.textBetween(起, 止, "");
}

/** 光标在**代码块**里吗（只看节点那一层，**不看行内代码那个 mark**）。 */
function 在代码块里(state: EditorState): boolean {
  const { $from } = state.selection;
  for (let 层 = $from.depth; 层 > 0; 层--) {
    if ($from.node(层).type.spec.code) return true;
  }
  return false;
}

/** 光标在代码块 / 行内代码里吗。 */
function 在代码里(state: EditorState): boolean {
  const { $from } = state.selection;
  for (let 层 = $from.depth; 层 > 0; 层--) {
    // ⚠️ 判 `spec.code` 而不是判名字：`code_block` 是上游起的名字，
    // 而 `spec.code` 才是 schema 自己那份"这是个原样文本块"的声明。
    if ($from.node(层).type.spec.code) return true;
  }
  // 行内代码是**标记**不是节点，得另问一次。
  return $from.marks().some((标记) => 标记.type.spec.code);
}

/**
 * 读一份 {@link 现场}。
 *
 * @param 位置 光标位置。⚠️ **必须显式传进来**：`handleTextInput` 给的
 *   `from` / `to` 是**这次输入之前**的选区，与 `state.selection` 未必是同一个
 *   （上游 `trailing` / `indent` 那几条都可能动过），拿 `state.selection.from`
 *   去替代会让判据落在错的位置上。**位置只有一个来源：调用方给的那个。**
 */
export function 读现场(state: EditorState, 位置: number): 现场 {
  const { from, to } = state.selection;
  return {
    前: 取字符(state, 位置, -1),
    后: 取字符(state, 位置, 1),
    // ⚠️ "后第二颗" = 从**后一颗的位置**再往后看一颗（偏移仍是 `1`）。
    后二: 取字符(state, 位置 + 1, 1),
    代码: 在代码里(state),
    代码块: 在代码块里(state),
    空选区: from === to,
    前是段首: 位置前那一颗是段首(state, 位置),
  };
}

/**
 * 光标左边那一颗字符，是不是这一段的第一颗（`*|` 里那颗星是不是段首那颗）。
 *
 * ⚠️ 判据是**它在父节点里的偏移是 0**，不是"这一段只有它一颗"：
 * `* 项目` 里那颗星同样是段首（用户可能只是先打了星号、还没接着打）。
 */
function 位置前那一颗是段首(state: EditorState, 位置: number): boolean {
  const 尺寸 = state.doc.content.size;
  if (位置 <= 0 || 位置 > 尺寸) return false;
  const $位 = state.doc.resolve(位置);
  if (!$位.parent.inlineContent) return false;
  // 光标左边那一颗的偏移是 `parentOffset - 1`；它在段首 ⟺ 那个偏移是 0。
  return $位.parentOffset === 1;
}

/* ── 四条判据（纯函数，`tests/auto-pair.test.ts` 只用这一层）────────────── */

/**
 * 打这颗开括号时，该补的闭括号是哪一颗；**不该补时给 `null`**。
 *
 * 四种"不该补"：
 *
 * ① 不是开括号（表外字符）；
 * ② 在代码块 / 行内代码里；
 * ③ 光标前面紧挨着 `\`（用户在转义）；
 * ④ **光标右边已经就是那颗闭括号、而且没选中东西**——补了就成 `())`。
 *    ⚠️ "没选中东西"这半句是**必须**的：选中一段再打 `(`，要的是**把它包起来**，
 *    这时右边那颗闭括号正是我们想要的。
 */
export function 要配对(现场: 现场, 字: string): string | null {
  const 闭 = 闭括号(字);
  if (!闭) return null;
  // ⚠️ 行内代码里不配；**代码块里配**（2026-10-06 把这两个情况分开了）。
  if (现场.代码 && !现场.代码块) return null;
  // ⚠️ 代码块里**不配那几颗 Markdown 标记符号**（`*`）：代码里打 `*` 要的是
  // 字面星号（乘法、指针、通配），补成一对是帮倒忙。括号那一族照配。
  if (现场.代码块 && 字 === "*") return null;
  if (现场.前 === "\\") return null;
  if (现场.空选区 && 现场.后 === 闭) return null;
  return 闭;
}

/**
 * 打这颗闭括号时，该不该"跳过"（不插字、光标右移一位）。
 *
 * ⚠️ **不判代码块**：配对在代码里是关的，但"跳过"作用于**用户自己敲出来的**
 * 那颗闭括号，在代码里同样是常规做法。⚠️ 也**不判"左边那颗开括号是不是
 * 我们补的"**——那要靠插件状态去记，而这里刻意无状态（记错了的症状是
 * "有时候跳有时候不跳"，比统一不跳难查得多）。
 */
export function 要跳过(现场: 现场, 字: string): boolean {
  if (!现场.空选区) return false;
  if (!是闭括号(字)) return false;
  return 现场.后 === 字;
}

/** 光标夹在一对**空的**括号中间时按退格：该不该两颗一起删。 */
export function 要删成对(现场: 现场): boolean {
  if (!现场.空选区) return false;
  const 闭 = 闭括号(现场.前);
  if (!闭) return false;
  return 闭 === 现场.后;
}

/**
 * 该不该"跨一位"。
 *
 * @param 方向 `1` = `Tab`（右边那颗闭括号，跳出去）；`-1` = `Shift+Tab`
 *   （左边那颗开括号，跳回来）。
 *
 * ⚠️ **在代码里一律不跳**：那里 `Tab` 的职责是**缩进**（上游 `indent` 插件），
 * 而"跨一位"会把缩进这件事废掉——两个都想抢同一颗按键时，让缩进赢。
 */
export function 要跳(现场: 现场, 方向: 1 | -1): boolean {
  if (!现场.空选区) return false;
  if (现场.代码) return false;
  if (方向 === 1) return 是闭括号(现场.后);
  return 是开括号(现场.前);
}

/* ── 自配对字符（`*`）──────────────────────────────────────────────────── */

/**
 * **自配对**：开与闭是同一颗字符的那些。
 *
 * ⚠️ 单独一张表，**不进 {@link 配对表}**：那张表四个判据全都建立在"开 ≠ 闭"
 * 上（`要跳过` 判"右边是不是那颗**闭**括号"、`要删成对` 判"前是开、后是闭"
 * ……）。把 `*` 塞进去，`*|*` 中间那一下退格、那一下 `Tab` 会**同时**匹配
 * 两边的规则——不是"哪条更对"，是那两条规则在这里根本没说清要什么。
 *
 * ⚠️ **今天只有 `*` 一项**。`_` / `~` / `=` 论字符形状与它同类，但**不收**：
 * 用户 2026-09-28 点名的原话是「比如输入一个`*`自动补全另一个」（见文件头
 * 第 2.1 节），那个"比如"不构成替另外三颗做主。加项之前请先回答
 * "补错了怎么收场"——`*` 敢收是因为它有一整套"什么时候**不**补"的判据。
 */
export const 自配对表: Readonly<Record<string, string>> = { "*": "*" };

/**
 * **可以"升级"的开括号**：第二次敲同一颗时把这一对**撑成双层**。
 *
 * | 现场 | 敲 | 结果 |
 * |---|---|---|
 * | `[\|]`（光标夹在一对**空的**方括号里） | `[` | `[[\|]]`，光标在正中间 |
 *
 * ⚠️ **为什么必须有它**：`[` 进了 {@link 配对表} 之后，打第二颗 `[` 会得到
 * `[[]`——**少一颗闭括号**（第一颗是被我们补的，第二颗敲的 `]` 会被"跳过"
 * 吃掉），于是 `[[页面]]` 这种 Wiki 链接**根本打不出来**。升级那一下把它补平。
 * ⚠️ 与 `*` 那条同源（`*|*` ⇒ `**|**`），只是这里的开闭**不是同一颗字符**，
 * 所以数字由 {@link 补标记} 现算（`字 + 字 + 闭 + 闭`），不写死四颗。
 */
export const 可升级表: Readonly<Record<string, string>> = { "[": "]" };

/**
 * **收尾时该落哪个标记**：自配对字符 → 「一颗 / 两颗」两档的 mark 名。
 *
 * ⚠️ 两个名字是 `@milkdown/preset-commonmark` 起的（`$markSchema("emphasis", …)`
 * 与 `"strong"`），**不是 `em`**——`mark-hint.ts` 顶上专门记过这个坑
 * （`command-state.ts` 那边也一直写的是 `有("emphasis")`）。
 *
 * ⚠️ **不在表里的字符，收尾就只是"跳过去"**（{@link 补标记} 的 `跳过` 那一支，
 * 原样保留）：今天只有 `*` 一项——只有它既在 {@link 自配对表} 里、又真的有
 * 一个 mark 可落。`[` 补出来的 `]` 收尾时没有对应标记，照旧只是跳过。
 */
const 落标记表: Readonly<Record<string, readonly [一颗: string, 两颗: string]>> = {
  "*": ["emphasis", "strong"],
};

/**
 * 打一颗自配对字符之后该做哪一件事。
 *
 * ⚠️ **三选一，不是"补或不补"**：`*` 自配对，所以"右边已经有一颗星"这件事
 * **有两种意思**——用户可能在收尾（`*粗|*`），也可能正把单星号扩成粗体
 * （`*|*`）。合成一条的症状是"想收尾却被补成四颗星"，而那时用户只会觉得
 * "这个自动补全疯了"，无从描述。
 */
export type 标记动作 =
  /** 补一颗，光标落中间（`*` ⇒ `*|*`）。 */
  | "补一对"
  /**
   * **把"没配上对的那一颗"补齐成一对**（`*` ⇒ `**|**`，光标落正中）。
   *
   * ⚠️ 只发生在**段首那颗星**上（2026-10-16 修的用户报的缺陷，见
   * {@link 要补标记} 那张表最后一行）：那颗星是"项目符号"的意思、故意没补，
   * 用户接着又打一颗时，他要的是**两边各两颗**（`**|**`）——只补右边一颗的
   * 话屏幕上留着 `**|*`，而他会发现自己打了两颗星、右边却只有一颗。
   */
  | "补齐"
  /** 把夹着的那两颗换成四颗（`*|*` ⇒ `**|**`）：打一颗就变粗体。 */
  | "升级"
  /** 不插字，光标右移一位（收尾）。意思同括号那条"跳过"。 */
  | "跳过";

/**
 * 打这颗自配对字符时该做什么；**不该插手时给 `null`**（让上游照常插入）。
 *
 * 五条"不插手"，前三条与 {@link 要配对} 逐条同源：
 *
 * ① 不是自配对字符；
 * ② 在代码块或行内代码里；
 * ③ 光标前面紧挨着 `\`（用户写 `\*` 要的就是一颗光秃秃的星号）；
 * ④ **有选区**——⚠️ 这一条与 `要配对` **不同**：括号上"有选区"是
 *    **把它包起来**（`选中的字` ⇒ `(选中的字)`，正是用户要的），而星号包起来
 *    是 `*选中的字*`，那是**替用户按下了斜体**，不是"把选中的字括起来"。
 * ⑤ **段首**（光标左边一个字都没有）：那里打 `*` 是**项目符号**，
 *    补一颗会当场变成 `*|* 项目`——一个列表项就这么废了。
 *
 * ⚠️ ⑤ 只看**紧挨着的那一颗**（`现场.前 === ""`），所以**缩进过的**列表
 * （`    * 项目`）拦不住。要拦住得一路回看到段首，代价与收益不成比例，
 * 如实记在 `docs/07` 那一项里。
 */
export function 要补标记(现场: 现场, 字: string): 标记动作 | null {
  const 自配 = 自配对表[字];
  const 升级闭 = 可升级表[字];
  if (!自配 && !升级闭) return null;
  if (现场.代码) return null;
  if (现场.前 === "\\") return null;
  if (自配) {
    if (!现场.空选区) return null;
    if (现场.前 === "") return null;
    if (现场.后 === 字) {
      // 右边还跟着第二颗（`**粗|**`）：用户在**把这一对写完**，跳过去。
      if (现场.后二 === 字) return "跳过";
      // 左边也是同一颗 ⇒ 光标正夹在一对**空的**星号里（`*|*`）：
      // 这是"再打一颗变粗体"，**不是**收尾。⚠️ 反过来的 `*粗|*` 左边是
      // 普通文字，那才是收尾——两者的分别全在 `前` 这一格上。
      return 现场.前 === 字 ? "升级" : "跳过";
    }
    // ⚠️⚠️ **段首那颗星没配上对，挨着它再打一颗要"补齐"**（2026-10-16 修的
    // 用户报的缺陷，原话：「按下两次星号键**另一边只补全出了一个**」）。
    //
    // 现场 `*|`（左边一颗星、右边空）＋ `前是段首` = 用户先打了一颗、
    // 而那一颗**被当成项目符号**故意没补（⑤ 条），现在他又打了一颗。他要的是
    // **两边各两颗**（`**|**`）；落到「补一对」那一支只补右边一颗，屏幕上留着
    // `**|*`——正是他报的那个样子。
    //
    // ⚠️ 判据里那个 `前是段首` **不能省**：不在段首的 `前 === 字 && 后 === ""`
    // 是另一种现场（比如用户从别处粘了一句结尾带 `*` 的话、接着想再打一颗），
    // 那里"补一对"是对的。省掉它会让那一类也变成四颗星。
    if (现场.前 === 字 && 现场.后 === "" && 现场.前是段首) return "补齐";
    return "补一对";
  }
  // 可升级的开括号（今天只有 `[`，见 {@link 可升级表}）：**只有一种情况要插手**
  // ——光标正夹在一对**空的**方括号里再敲一颗（`[|]` ⇒ `[[|]]`）。
  // ⚠️ 其余一律 `null`，**交给 {@link 要配对}**：普通配对、包住选区、代码里
  // 不补、反斜杠转义那几条它都有；在这里再判一遍就是两份实现。
  if (现场.空选区 && 现场.前 === 字 && 现场.后 === 升级闭 && 现场.后二 === 升级闭) {
    return "升级";
  }
  return null;
}

/** 往回找开定界符时最多看这么多颗字符（正常一对星号不会隔这么远）。 */
const 回看上限 = 200;

/** 在这一段行内内容里取 `[从, 到)` 那几个字符；越界给 `""`，**不抛**。 */
function 块内文(父: 模型节点, 从: number, 到: number): string {
  if (从 < 0 || 从 >= 到 || 到 > 父.content.size) return "";
  return 父.textBetween(从, 到, "");
}

/**
 * **把这一对星号落成真的标记**（BUG-54；2026-09-30 扩成三个触发时机）。
 *
 * # 病灶
 *
 * {@link 补标记} 的「补一对」是把**字符**插进去（`*` ⇒ `*|*`），而插完那颗
 * 闭星号在光标**后面**——上游 `emphasisInputRule` 要的是"用户刚敲下的那一颗
 * 就是闭定界符"，永远等不到。⚠️ 反斜杠本身**不是 bug**，修法只能在**编辑器这
 * 一侧**：让这一对星号真的成为 `emphasis`，**不许去动序列化器**。整条来龙去脉
 * （含 2026-09-30 用户第二次报同一件事）在文件头 §2.3。
 *
 * # 三个触发时机（2026-09-30 补齐后两个）
 *
 * | # | 现场 | 谁叫的 |
 * |---|---|---|
 * | ① | `*甲` 后面**用户自己敲下**收尾那颗 `*` | {@link 要补标记} 给 `补一对`，但右边没有星号 ⇒ 先问这一句 |
 * | ② | `*甲\|*` 里用户敲的星号落在**补出来的**闭定界符正前面 | {@link 要补标记} 给 `跳过` |
 * | ③ | 打正文把夹着的那一对**打完**了（`*甲\|*` 里打进 `甲`） | 普通文字那一路的最后一句 |
 *
 * ⚠️ **② 是 2026-09-29 加的那个，③ 是 2026-09-30 用户第二次报同一件事时加的**：
 * 用户原话「**还是会自动插入斜杠。渲染仍未成功。**」——他只打 `*甲`，
 * 那颗闭星号是**我们补的**，他没有任何理由再敲一遍，"等用户敲收尾那颗"这个
 * 前提在 `*` 上根本不成立。所以 ③ 的条件不是"用户敲了什么"，而是**文档的
 * 形状**：光标紧贴着一颗闭定界符、往回又扫得出成对的开定界符。
 *
 * ⚠️ **代价如实记着**：`2*3` 这样的正文里的星号（补全开着时它会变成 `2*3*`）
 * 也会被 ③ 落成 `2` ＋ *3*。CommonMark 对 `2*3*` 本来就判成强调，本仓只是
 * 提前把它落定；真要字面星号请写 `\*` 或关掉「智能符号补全」。
 *
 * # 判据（逐条都是"宁可不动"）
 *
 * 往回扫到开定界符，要求：内文非空、两头都不是空白（`* 甲*` 那样的星号在
 * CommonMark 里压根不构成强调，落了标记反而是替用户改意思）、开闭**颗数相同**
 * （一颗对一颗、两颗对两颗）、开定界符前面**不是** `\`（用户在转义）。
 * 任一条不成立就交回调用方（① 退回「补一对」、② 退回"只跨过去"、③ 什么都不做），
 * **一个字都不改**。
 *
 * ⚠️ **扫的时候撞上原子节点（图片 / 公式）就停**：`*![图](…) *` 这种不碰
 *（`textBetween` 对原子给 `""`，也正是 {@link 取字符} 那套的口径）。
 *
 * @param 内文尾巴 已经敲下、还**没进文档**的那一颗字（③ 那一路用它；①② 给 `""`）。
 *   ⚠️ 它要一起过"非空 / 两头无空白"那两条判据，否则 `*甲` 尾随一颗空格时会被
 *   当成收尾。
 * @param 结束 落完标记之后**还要不要接着斜**。
 *   ⚠️ 这条**按触发时机分**，不是随意的：① ② 两条是"用户敲下了闭定界符"，
 *   他按那一颗键的意思就是"斜体到这儿结束"⇒ `true`，接着打的字是平的；
 *   ③ 是"用户在星号中间打字"，那一对在他心里**还开着** ⇒ `false`，
 *   后面的字**继续斜**（Typora 里就是一直斜下去，想收尾得自己按一颗星号，
 *   那一下由 {@link 尾巴带标记} 那条岔路接住）。
 */
function 收尾事务(
  state: EditorState,
  位置: number,
  字: string,
  内文尾巴: string,
  结束: boolean,
): Transaction | null {
  const 名 = 落标记表[字];
  if (!名) return null;
  const $位 = state.doc.resolve(位置);
  if (!$位.parent.inlineContent) return null;
  // ⚠️ **行内代码里的星号是原样文字**，不是标记的定界符。`在代码里` 只覆盖
  // `state.selection`，而这里的位置是调用方给的，所以自己再问一次标记那一半。
  if ($位.marks().some((标记) => 标记.type.spec.code)) return null;
  const 父 = $位.parent;
  const 起 = $位.parentOffset;
  // 闭定界符几颗：光标右边连着几颗同一颗字符（最多两颗）。
  const 盘上 =
    块内文(父, 起, 起 + 1) === 字 ? (块内文(父, 起 + 1, 起 + 2) === 字 ? 2 : 1) : 0;
  // ⚠️ 盘上一颗都没有时，**正在敲的那一颗**就是闭定界符（①：`*甲` 后面敲 `*`）。
  // 但"敲的是正文"那条路（`内文尾巴` 非空）不适用——它要求右边真有闭定界符。
  const 闭长 = 盘上 || (内文尾巴 === "" ? 1 : 0);
  if (!闭长) return null;
  // 往回扫内文：撞到同一颗字符（= 开定界符）或取不到字符（段首 / 原子）就停。
  const 内: string[] = [];
  while (内.length < 回看上限) {
    const 文 = 块内文(父, 起 - 内.length - 1, 起 - 内.length);
    if (文 === "" || 文 === 字) break;
    内.push(文);
  }
  // ⚠️ 扫描的颗数用 `内.length`（盘中真实存在的），判"非空"用 `内文`（含尾巴）。
  const 内文 = 内.reverse().join("") + 内文尾巴;
  // ⚠️ 正好扫满上限 = 压根没找到开定界符，**不是**"找到了一对很长的"。
  if (内文 === "" || 内.length >= 回看上限) return null;
  if (/^\s|\s$/.test(内文)) return null;
  if (块内文(父, 起 - 内.length - 1, 起 - 内.length) !== 字) return null;
  // ⚠️ **下面这几个下标全是"父节点内容坐标"**（`textBetween` 吃的那套），
  // **不是文档位置**——两套差着 1（位置 = 内容坐标 ＋ 块首），混用一次就是
  // 差一颗字符（第一版把转义那一判写成 `开起 - 1`，正好指着开定界符**自己**，
  // 于是 `\*甲*` 照样被落了标记，测试当场抓住）。
  const 开前 = 块内文(父, 起 - 内.length - 2, 起 - 内.length - 1);
  // 开定界符前面紧挨着 `\` ⇒ 用户在转义（`\*甲*` 那种），不碰——与
  // {@link 要补标记} 的 ③ 同源。⚠️ 只判这一颗，不追"这个反斜杠自己是不是
  // 被转义的"（`\\*甲*`），理由同上那一条的注释。
  if (开前 === "\\") return null;
  const 开长 = 开前 === 字 ? 2 : 1;
  if (开长 !== 闭长) return null;
  const 开起 = 位置 - 开长 - 内.length;
  // ⚠️ 下标写成 `闭长 - 1` 过不了 `tsc`（元组的变量下标一律是 `string | undefined`），
  // 拆成两支反而把"一颗对一颗、两颗对两颗"这件事写在脸上了。
  const 标记类型 = state.schema.marks[闭长 === 2 ? 名[1] : 名[0]];
  if (!标记类型) return null;
  // ⚠️ 替换范围的右端是 `位置 + 盘上`：**盘上有几颗就吃掉几颗**（① 是 0，
  // 那一颗是用户正在敲的、压根没进文档；②③ 是 1 或 2）。
  const 事务 = state.tr.replaceWith(
    开起,
    位置 + 盘上,
    state.schema.text(内文, [标记类型.create()]),
  );
  // 光标落在**标记之后**：`*甲|*` ⇒ `*甲*`（标记版）里 `甲` 后面那一格。
  // ⚠️ 是 `开起 + 内文.length` **不是** `位置`：闭定界符那几颗已经被换掉了，
  // 老坐标在新文档里指的位置早就不对了。
  事务.setSelection(TextSelection.create(事务.doc, 开起 + 内文.length));
  // ⚠️ **说清楚"到此为止"**：光标落在标记尾巴上，ProseMirror 默认会拿
  // `$from.marks()`（= 前一颗字那套 `emphasis`）接着用，于是用户接着打的字
  // **还是斜的**——而他刚敲下那颗星号的意思正是"斜体到这儿结束"。
  // ⚠️ 空数组**是**有效值：`insertText` 判的是 `this.storedMarks || $from.marks()`，
  // 而空数组在 JS 里为真，所以它会赢过"继承前一颗字的标记"。
  if (结束) 事务.setStoredMarks([]);
  return 事务;
}

/**
 * 光标左边紧挨着的那颗字**身上带着标记**吗（斜体 / 粗体那两档）。
 *
 * 用途只有一个：在**已经落成标记的**文字尾巴上再敲一颗星号时，那一颗的意思是
 * 「到此为止」而不是「再来一颗字面星号」，更不该被 {@link 要补标记} 当成
 * "再补一对"。⚠️ 判据只答"要不要让它继承那套标记"，**吞键是调用方的事**
 *（见 {@link 到此为止事务}）。
 */
function 尾巴带标记(state: EditorState, 位置: number): boolean {
  const $位 = state.doc.resolve(位置);
  if (!$位.parent.inlineContent) return false;
  const 前 = $位.nodeBefore;
  if (!前) return false;
  return 前.marks.some((标记) => 标记.type.name === "emphasis" || 标记.type.name === "strong");
}

/**
 * 「**到此为止**」：一个字都不插，只把"接着打的字跟着斜"这件事断掉。
 *
 * 用在**已经落成标记的尾巴上再敲一颗星号**那一下（`*甲*` 已经成了 *甲*，
 * 用户又按了一次 `*`）。这颗星号的意思是把斜体收在**已经收好的位置**，
 * 不是"再来一颗字面星号"——⚠️ 插一颗字面星号会让存盘写成 `*甲*\*`，
 * **正好就是用户报的那个"自动插入斜杠"**，所以这里选择**吃掉这一颗键**。
 *
 * ⚠️ 副作用如实记着：连着敲两颗星号想紧接着再开一段斜体（`*甲**乙*`）时，
 * 第一颗被吃掉；想接着开就把光标挪开一位，或者先打一颗空格。
 */
function 到此为止事务(state: EditorState): Transaction {
  const 事务 = state.tr.setStoredMarks([]);
  // 只改"接下来用什么标记"，文档一个字节都没动 —— 不进撤销历史。
  事务.setMeta("addToHistory", false);
  return 事务;
}

/**
 * 把 {@link 标记动作} 落到事务上。
 *
 * ⚠️ "升级"那一条**一次 `replaceWith` 换掉夹着的那两颗**，不是"插一颗、
 * 再插一颗"：同一事务里第二次插入的坐标要自己 `map`，而 `Transaction` 的
 * 坐标是**原始文档**坐标——写错一步的表现是"偶尔多一颗星"，没人会往这里找。
 */
function 补标记(view: EditorView, 位置: number, 字: string, 动作: 标记动作): boolean {
  if (动作 === "跳过") {
    // ⚠️ **收尾是"这一对写完了"的意思**，所以先问一句能不能落成真标记
    //（{@link 收尾事务}，BUG-54）；落不了才退回"只把光标跨过去"。
    // ⚠️ 顺序不能反：跨过去之后光标就不在闭定界符前面了，那颗键白按。
    const 事务 = 收尾事务(view.state, 位置, 字, "", true);
    if (事务) {
      view.dispatch(事务);
      return true;
    }
    跨一位(view, 1);
    return true;
  }
  if (动作 === "升级") {
    const { state } = view;
    // ⚠️ **两颗哪一颗是闭，要现查**：`*` 是自配对（{@link 配对表} 里没有它，
    // 落到 `?? 字`），`[` 的闭是 `]`（表里有）。写死"四颗同一颗字"的话，
    // `[` 那一支会补成 `[[[[`。
    const 闭 = 配对表[字] ?? 字;
    const 事务 = state.tr.replaceWith(位置 - 1, 位置 + 1, state.schema.text(字 + 字 + 闭 + 闭));
    // 四颗里光标落在正中间：`**|**` / `[[|]]`。
    事务.setSelection(TextSelection.create(事务.doc, 位置 + 1));
    view.dispatch(事务);
    return true;
  }
  if (动作 === "补齐") {
    // 现场是 `*|`（左边一颗、右边空）：把**那一颗**换成四颗，光标落正中。
    // ⚠️ 范围是 `[位置-1, 位置)`——**不含右边**（那边本来就没有东西）；写成
    // 「升级」那种 `[位置-1, 位置+1)` 会把右边一个字一并吃掉（右边是正文时
    // 症状是"打颗星吃掉后面一个字母"，而那种错没人会往自动配对这边想）。
    const { state } = view;
    const 闭 = 配对表[字] ?? 字;
    const 事务 = state.tr.replaceWith(位置 - 1, 位置, state.schema.text(字 + 字 + 闭 + 闭));
    事务.setSelection(TextSelection.create(事务.doc, 位置 + 1));
    view.dispatch(事务);
    return true;
  }
  // 「补一对」：与括号那条同一个落点（空选区那半支）。
  return 配对(view, 位置, 位置, 字, 字);
}

/* ── 落点：插件 ────────────────────────────────────────────────────────── */

/** 光标右移 / 左移一位，**不计进撤销历史**（那是导航不是改动）。 */
function 跨一位(view: EditorView, 步: 1 | -1): void {
  const { state } = view;
  const 到 = state.selection.from + 步;
  view.dispatch(
    state.tr.setSelection(TextSelection.create(state.doc, 到)).setMeta("addToHistory", false),
  );
}

/**
 * 补一对括号。
 *
 * ⚠️ **选中东西时是"把它包起来"**，两种插法的顺序有讲究：
 *
 * - 有选区：**先插闭括号（在 `到`）再插开括号（在 `从`）**——先插后面的，
 *   前面那些位置才不会被顶偏。⚠️ 直接 `insertText` 包在选区**外面**，
 *   **不是**拿 `textBetween` 拼一串再 `replaceWith`：后者会把选区里的
 *   **标记、原子、跨块结构全部抹平**（VMark 那边踩过，注释里留着"会剥掉标记、
 *   删掉原子"这句）。⚠️ 两端必须都在行内（`isTextblock`）：`Ctrl+A` 那种
 *   整篇选区上插字符会造出两个**只含一颗括号的段落**，不如不插手。
 * - 空选区：两颗一起插，光标落在中间。
 */
function 配对(view: EditorView, 从: number, 到: number, 开: string, 闭: string): boolean {
  const { state } = view;
  const 事务 = state.tr;
  if (从 !== 到) {
    const $从 = state.doc.resolve(从);
    const $到 = state.doc.resolve(到);
    if (!$从.parent.isTextblock || !$到.parent.isTextblock) return false;
    事务.insertText(闭, 到, 到);
    事务.insertText(开, 从, 从);
    // 开括号插在 `从` ⇒ 原本 `[从, 到)` 的内容整体右移一位，闭括号现在落在
    // `到 + 1`。光标摆到它前面 = 包住的那段之后。
    事务.setSelection(TextSelection.create(事务.doc, 到 + 1));
  } else {
    事务.insertText(开 + 闭, 从);
    事务.setSelection(TextSelection.create(事务.doc, 从 + 1));
  }
  view.dispatch(事务);
  return true;
}

/**
 * 键盘那一路。⚠️ **`Tab` 只在那一种情况下返回 `true`**，其余一律放行——
 * 放行的意思是"让上游 `indent` 去缩进"，不是"什么都不做"。
 */
function 按键(view: EditorView, event: KeyboardEvent): boolean {
  // ⚠️ 带修饰键的一概不碰：`Ctrl+Tab` / `Alt+Tab` 是窗口管理器的，
  // `Cmd+Z` 是撤销的。Shift 不算修饰键（`Shift+Tab` 正是我们要的那一条）。
  if (event.ctrlKey || event.altKey || event.metaKey) return false;
  const { state } = view;
  const 位置 = state.selection.from;
  const 现场 = 读现场(state, 位置);
  if (event.key === "Tab") {
    const 方向 = event.shiftKey ? -1 : 1;
    if (!要跳(现场, 方向)) return false;
    跨一位(view, 方向);
    return true;
  }
  if (event.key === "Backspace") {
    if (!要删成对(现场)) return false;
    view.dispatch(state.tr.delete(位置 - 1, 位置 + 1));
    return true;
  }
  if (event.key.length === 1 && 要跳过(现场, event.key)) {
    跨一位(view, 1);
    return true;
  }
  return false;
}

/**
 * 挂进 `.use()` 的那一条。
 *
 * ⚠️ **位置：排在 `indent` 前面**——`Tab` 那颗键两边都想接，上游 `indent`
 * （`@milkdown/plugin-indent`）绑的正是 `Tab`。ProseMirror 按
 * `state.plugins` 顺序问 `handleKeyDown`，**第一个返回 `true` 的赢**；
 * 排到它后面去，"跳出右半边"永远不会发生。⚠️ 反过来，**别的地方一律放行**，
 * 所以缩进该发生的时候照旧发生。
 *
 * ⚠️ **组字期间（`view.composing`）一律不插手**：中文输入法打全角括号、
 * 打引号时都有一次 composition，那期间动文档会把候选框里的东西打乱。
 * 代价如实记在文件头第 5 节（全角括号常常配不上对）。
 */
export function 配对处理(开 = true) {
  // ⚠️ **关掉 = 这条插件不装**（返回 `[]`，与 `smart-punctuation.ts` 的
  // `标点输入` 同一个做法）：四件事（补一对 / 跳过 / 空对退格 / `Tab` 跳出）
  // 是**一条插件**，只关一半等于让 `Tab` 去跳一颗根本没补出来的括号。
  // ⚠️ 参数默认 `true`：老调用点（以及测试）不传就是开，与 Rust 那边
  // `smart_symbols` 的默认值一致。
  if (!开) return [];
  // ⚠️ 只有最后那条兜底要用到视图（要问一句 `view.composing`）。
  let 视图: EditorView | null = null;
  return $prose(
    () =>
      new Plugin({
        key: 配对键,
        view: (现在这个) => {
          视图 = 现在这个;
          return {
            destroy: () => {
              视图 = null;
            },
          };
        },
        /**
         * **兜底**：打完一颗字，夹着的那一对星号可能就此完整了。
         *
         * ⚠️ 这一条**不是**重复劳动：中文输入法上屏那一路**压根不走
         * `handleTextInput`**（组字是 DOM 观察器直接落进文档的），所以
         * 「打完 `你好` 这一对就完整了」在拼音输入法下**只有这只眼睛看得见**。
         * 用户 2026-09-30 报的那张截图（两颗字面星号夹着 `你好`）就是这么来的。
         *
         * 判据与 `handleTextInput` 的 ③ 完全同一份（{@link 收尾事务}），
         * 一个字都没多写；这里只负责在**每一次事务之后**再问一遍。
         */
        appendTransaction: (_事务们, _旧, 新) => {
          // ⚠️ 组字期间一律不插手（与 `handleTextInput` 第一句同源）：
          // 那期间动文档会把候选框里的东西打乱。
          if (视图?.composing) return null;
          if (!新.selection.empty) return null;
          const 从 = 新.selection.from;
          const 字 = 取字符(新, 从, 1);
          if (!字) return null;
          return 收尾事务(新, 从, 字, "", false);
        },
        props: {
          handleTextInput: (view, 从, 到, 文) => {
            if (view.composing) return false;
            // ⚠️ 一次只认一颗字符：粘贴、IME 提交、拖放都会带着一整串进来，
            // 而那些都**不是"打了一颗开括号"**。
            if (文.length !== 1) return false;
            const 此现场 = 读现场(view.state, 从);
            // ⚠️ 自配对先问：它的判据比 `要配对` 多两条（段首 / 升级），
            // 而 `配对表` 里没有 `*`，两个判据的适用范围不重叠、顺序无所谓
            // ——先问它只是为了让"星号"这件事在这段里读起来是一句话。
            const 动作 = 要补标记(此现场, 文);
            if (动作 === "补一对") {
              // ① 这颗星号可能其实是**收尾**：前面已经有一颗开星号、内文也合法，
              // 而右边一颗星号都没有（`*甲` 后面用户自己敲下闭定界符那一下）。
              // ⚠️ 先问它再补——补了就多出一颗用户没打过的星号（`*甲**`），
              // 而那个形状**谁都认不出来**（用户 2026-09-30 报的就是它）。
              const 收尾 = 收尾事务(view.state, 从, 文, "", true);
              if (收尾) {
                view.dispatch(收尾);
                return true;
              }
              // 已经落成标记的尾巴上再敲一颗：意思是"到此为止"，**吃掉这一颗键**
              //（⚠️ 不能插一颗字面星号——那会让存盘写成 `*甲*\*`，正是用户报的
              //"自动插入斜杠"）。⚠️ `storedMarks` 已经是空数组 = 上一颗星号刚
              // 说过一次"到此为止"了，这时再敲就是要**另开一对**，别再吃。
              if (view.state.storedMarks?.length !== 0 && 尾巴带标记(view.state, 从)) {
                view.dispatch(到此为止事务(view.state));
                return true;
              }
              return 补标记(view, 从, 文, 动作);
            }
            if (动作) return 补标记(view, 从, 文, 动作);
            const 闭 = 要配对(此现场, 文);
            if (闭) return 配对(view, 从, 到, 文, 闭);
            // ③ **普通正文**：这一颗字打下去，夹着的那一对星号可能就此完整了
            //（`*甲\|*` 里打进 `甲`）。⚠️ 排在最后：括号与 `*` 各有各的落点，
            // 轮到这里的一定是"没什么结构含义的一颗字"。
            const 收尾 = 收尾事务(view.state, 从, 取字符(view.state, 从, 1), 文, false);
            if (收尾) {
              view.dispatch(收尾);
              return true;
            }
            return false;
          },
          handleKeyDown: (view, event) => {
            if (view.composing) return false;
            return 按键(view, event);
          },
        },
      }),
  );
}
