/**
 * **`$` 当钱写的时候不算公式**（2026-10-04，`docs/07` backlog 第 54 项）。
 *
 * # 症状
 *
 * `价格 $100 和 $200 元` —— 两颗 `$` 之间被读成一颗行内公式（值 `100 和 `），
 * 屏幕上**突然冒出一块公式**。⚠️ 存盘的字节是原样的（这不是"改用户字节"那条病），
 * 只是看着不对。用户 2026-09-2x 报的。
 *
 * # 为什么不照最简单的那个写法
 *
 * 「`$` 后面紧跟数字就不当开定界符」——这句话单独用会**误伤真公式**，
 * 而且伤得比原病更重。三个实测的形状（都写进 `tests/math-currency.test.ts` 了）：
 *
 * | 源码 | 只按"开定界符右边是数字"拒 | 后果 |
 * |---|---|---|
 * | `$2+2$ 和 $x$` | 第一颗 `$` 被拒 ⇒ 它右边那颗 `$` 顶上当开定界符 | **`2+2$ 和 ` 整段成了公式** ✗✗ |
 * | `$0 < x < 1$` | 被拒 ⇒ 整段还原成正文 | 该渲染的公式不渲染了 ✗ |
 * | `$\frac{a}{b}$` | 没事（右边是 `\`） | —— |
 *
 * 第一行那种是**把正文吃进公式里**，比"钱被看成公式"更难看，所以不能这么写。
 *
 * # 口径（照 Pandoc，但只取它的一半）
 *
 * Pandoc 手册的原文是三条：**开定界符右边得是非空白**、**闭定界符左边得是非空白**、
 * **闭定界符右边不能紧跟数字**。本仓的口径是：
 *
 * 1. **门槛**：开头的 `$` **只有一颗**（`$$…$$` 一律不算，钱不会那么写），
 *    而且它右边**紧跟一颗数字**；
 * 2. 过了门槛之后，**再要**下面任一条成立，这一对才判成正文：
 *    - 闭定界符**右边紧跟一颗数字**（`$100 和 $200` 的第二颗 `$` 后面正是 `2`）；
 *    - 闭定界符**左边是一颗空白**（`$50，公式 $x+y$ 里` 那一对）。
 *
 * ⚠️ **2 里那两条就是 Pandoc 的第 2、3 条**，一个字没改；差的是**我们只在门槛之内
 * 才拿它们判**。不设门槛的话，第 2、3 条会把 `$ \LaTeX $` 也判成正文——
 * 那正是用户 2026-10-04 下午拍板**整条撤回**的那条（BUG-62，`math-delim.ts`
 * 文件头记着当事人与代价）。设了门槛之后 `$ \LaTeX $` 连门都进不来（右边是空格、
 * 不是数字），**照旧渲染** ✓。
 *
 * 真值表（前四行是本文件存在的理由，后两行是**故意不动手**的形状）：
 *
 * | 源码 | 退给谁 | 判 |
 * |---|---|---|
 * | `价格 $100 和 $200 元` | 正文 | ✓ 本项要治的就是它 |
 * | `$5 到 $10 不好说` | 正文 | ✓ 第二颗 `$` 后面是 `1` |
 * | `$50，公式 $x+y$ 里` | 正文 ＋ 一颗公式 `x+y` | ✓ 闭定界符左边是空白 |
 * | `$100 降到 $50，公式 $x+y$` | 正文 ＋ 一颗公式 `x+y` | ✓ 见下面那段"为什么要包 tokenizer" |
 * | `$2+2$` / `$0 < x < 1$` / `$2 + 2$` | 公式 | ✓ 闭定界符后面不是数字、左边不是空白 |
 * | `$ \LaTeX $` | 公式 | ✓ 右边是空格 ⇒ 门槛都没过 |
 *
 * # ⚠️ 已知差别（如实记，不进设置当开关）
 *
 * - **它会改变已存文档的解析结果**：一份写着 `$100 … $200` 的文档，今天看着是公式，
 *   改完以后看着是钱。用户 2026-10-04 拍的是「照 Pandoc 判据改，写进"已知差别"」，
 *   **没要开关**（`docs/07` 第 54 项那一行）。
 * - **认不出的形状照样是公式**：`$100 和 200$ 元`（收尾那颗 `$` 后面没有数字、
 *   左边也不是空白）—— 这一对**不动手**，行为与改动前一样。它与
 *   `$0 < x < 1$` 逐条都长一样，**这一层判据分不开**，所以宁可不动。
 * - **`$1$2` 这种会判成正文**（闭定界符右边是数字）。它本来也像钱。
 * - **打开→存盘，字节不变**：判成正文那一对**不会**被写成 `\$`——那是
 *   `math-delim.ts` 第四格（`不转义美元`）管的，它的判据 2 在这几个形状上都成立
 *   （整段的 `$` 都在这颗文本节点里）。⚠️ 这一条**靠那条判据兜着**，不是这一层保证的。
 *
 * # 为什么包 tokenizer，而不是在 mdast 那一层把 `inlineMath` 改回正文
 *
 * mdast 那一层能看见的只有"**上游已经配好的那一对**"，而"配错了以后该退到哪里"
 * 它算不出来：上面第 4 行 `$100 降到 $50，公式 $x+y$` 里，上游先配出
 * `$100 降到 $`，把它改回正文之后，**`$50` 那颗 `$` 要重新当开定界符去配后面那颗**
 * ——mdast 那一层没有"重新分词"这一步，只能硬凑，而硬凑的典型后果就是把
 * `50，公式 ` 吃进公式里。包在 tokenizer 上就不用管这些：**退回正文 = 把这一对
 * 否掉**，剩下全交给 micromark 自己重扫（它本来就会在下一颗 `$` 上再试一次），
 * 配出来的结果与"从来就没有这条规则、只是这段源码恰好这么写"完全一致。
 *
 * # 怎么挂上去（三件事，少一件就静默失效）
 *
 * 1. **拿上游那一条**：从 `this.data("micromarkExtensions")` 里把 `text[36]` 找出来
 *    （认它的 `name === "mathText"`）。⚠️ **不 import `micromark-extension-math`
 *    自己造一条**：那条构造的行为取决于 `remark-math` 拿到的选项，自己造就得把
 *    选项抄一遍，抄错了是静默的。从处理机上**现场取**，谁配的就用谁的。
 *    找不到（上游改名了、`remark-math` 还没挂上）⇒ **什么都不做**，退回上游行为。
 * 2. **包一层**：`tokenize` 里把 `effects` 换成"转发 + 记下吃掉的字符"的影子，
 *    再把上游那条**原样跑一遍**；它成功那一刻回调里带着**闭定界符右边那颗字符**，
 *    加上影子里记下的几颗，形状就齐了。判成正文 ⇒ 调 `nok`（分词器自己回滚），
 *    否则 ⇒ 调 `ok`。⚠️ **一个字节都没有自己拼**：进/出哪些 token、`resolve` 怎么
 *    收尾，全是上游那条在干。
 * 3. **把上游那条按名字停掉**：`disable: {null: ["mathText"]}`。⚠️ 不这么做的话，
 *    我们这条 `nok` 之后**会在同一个位置上试下一条构造**，而下一条正是上游那条
 *    ——它可是来者不拒，于是又配成了公式。⚠️ 代价是**我们自己那条也不能叫这个名字**
 *    （停用是按名字查的），所以包装那份的 `name` 必须去掉。
 *
 * # 证明不了什么
 *
 * - **开窗目检**没做（`docs/06` §5 的做法）：真浏览器里敲 `价格 $100 和 $200 元`、
 *   看着它不冒公式、`Ctrl+S` 再 `cat` 文件——那是另一件事。这里的判据全是
 *   真 `unified()` ＋ 真两台状态机跑出来的，但**没有一颗真 DOM**。
 * - **剪贴板、粘贴、打字**那几条路：这次改的是**分词器**，三条路共用一个解析器，
 *   所以按说不必各验一遍；⚠️ 但"打字时按的那条输入规则"（`math-input.ts`）是
 *   **另一套判据**，它不经过这里——`$100 ` 打出来会不会当场变公式，是那条在管。
 * - **`docs/11` 那类"已知差别"表**：本项改的是解析口径，落点见 `docs/07` §4。
 */

import { $remark } from "@milkdown/kit/utils";

/* ── 类型（不引 `micromark-util-types`，够用就好，与 `math-delim.ts` 同一套写法）── */

/**
 * micromark 的"一颗字符"：正常是码点，末尾是 `null`。
 *
 * ⚠️ **空白与行尾是负数**（`micromark-util-symbol` 那几张表）：`32` 是真空格，
 * `-1` 是虚拟空格，`-2` 是 Tab，`-3/-4/-5` 是三种换行。判空白请走 `是空白`，
 * 别去 `String.fromCharCode`。
 */
export type 码 = number | null;

/** 一个分词状态：吃掉一颗字符，返回下一个状态。 */
export type 状态 = (code: 码) => unknown;

/** 上游那条构造的"工具箱"。我们只包 `consume`，其余原样转发。 */
export type 效果 = { consume: (code: 码) => void } & Record<string, unknown>;

/** 一条 micromark 构造：只写本文件用得到的那几个字段。 */
export type 构造 = {
  name?: string;
  previous?: (code: 码) => boolean;
  resolve?: (...参数: never[]) => unknown;
  resolveTo?: (...参数: never[]) => unknown;
  resolveAll?: boolean;
  tokenize: (this: unknown, effects: 效果, ok: 状态, nok: 状态) => unknown;
};

/* ── 判据（纯函数，测试直接量这几个）──────────────────────────────────── */

/** 这一颗是不是 ASCII 数字。⚠️ 只认 `0-9`：全角数字不在判据里（`$１００` 不当钱）。 */
export function 是数字(code: 码): boolean {
  return code !== null && code >= 48 && code <= 57;
}

/** 这一颗是不是空白（真空格、虚拟空格、Tab、三种换行）。 */
export function 是空白(code: 码): boolean {
  return code === 32 || (code !== null && code < 0);
}

/** 一对 `$…$` 从分词器那儿量得到的五个数 —— 判据的全部输入。 */
export type 形状 = {
  /** 开头连着几颗 `$`（1、2、3…）。 */
  开几颗: number;
  /** 紧跟开定界符右边的那一颗。 */
  开右邻: 码;
  /** 紧挨闭定界符左边的那一颗。 */
  闭左邻: 码;
  /** 闭定界符自己（应当是 `$`；不是就说明形状没认对，此时一律不动手）。 */
  闭本身: 码;
  /** 紧挨闭定界符右边的那一颗。 */
  闭右邻: 码;
};

/**
 * **这一对该判成正文吗**（`true` = 不是公式）。
 *
 * 门槛：**单颗 `$` 起头 ＋ 右边紧跟数字**。过了门槛再看 Pandoc 那两条
 * （闭的右边是数字 / 闭的左边是空白）。为什么这么组合、每一行对应什么源码，
 * 全在文件头那张真值表里。
 */
export function 该判成正文(形: 形状): boolean {
  if (形.闭本身 !== 36) return false; // 收尾那颗不是 `$`：形状没认对
  if (形.开几颗 !== 1) return false; // `$$…$$` 不可能是钱
  if (!是数字(形.开右邻)) return false; // 门槛
  return 是数字(形.闭右邻) || 是空白(形.闭左邻);
}

/* ── 包一层：把上游那条行内公式构造改成"先问一句" ───────────────────── */

/**
 * 把 `上游` 那条构造包一层：**行为一模一样，只在它配成一对之后问一句
 * `该判成正文`**，是就不认（`nok`，分词器自己回滚成正文）。
 *
 * 影子 `effects` 只干一件事：**记下吃掉的那几颗字符**，够算 `形状` 就行
 * （开头连着几颗 `$`、紧跟着的那颗，以及最后两颗）。⚠️ 所以它是 **O(1)** 的——
 * 一段没配成对的 `$` 后面跟着几万字，也不会把这几万字攒在内存里。
 */
export function 收窄美元公式(上游: 构造): 构造 {
  return {
    ...上游,
    // ⚠️ 必须去掉：停用是按名字查的（`disable: {null: ["mathText"]}`），
    // 带着这个名字的话我们自己这条也会被停掉，规则就静默失效了。
    name: undefined,
    tokenize(this: unknown, effects: 效果, ok: 状态, nok: 状态): unknown {
      let 开几颗 = 0;
      let 开右邻: 码 = null;
      let 头数完了 = false;
      /** 最近吃掉的两颗。成功那一刻，最后那颗应当是闭定界符。 */
      const 尾两颗: 码[] = [];

      const 影: 效果 = {
        ...effects,
        consume(code: 码): void {
          if (!头数完了) {
            if (code === 36) 开几颗++;
            else {
              头数完了 = true;
              开右邻 = code;
            }
          }
          尾两颗.push(code);
          if (尾两颗.length > 2) 尾两颗.shift();
          effects.consume(code);
        },
      };

      /** 上游成功那一刻的回调。`code` 就是**闭定界符右边紧挨着的那一颗**。 */
      const 收尾: 状态 = (code: 码) => {
        const 形: 形状 = {
          开几颗,
          开右邻,
          闭左邻: 尾两颗.length >= 2 ? 尾两颗[0] ?? null : null,
          闭本身: 尾两颗.length >= 1 ? 尾两颗[尾两颗.length - 1] ?? null : null,
          闭右邻: code,
        };
        return 该判成正文(形) ? nok(code) : ok(code);
      };

      return 上游.tokenize.call(this, 影, 收尾, nok);
    },
  };
}

/* ── 从处理机上把上游那一条找出来 ─────────────────────────────────────── */

/**
 * 在 `micromarkExtensions` 那一串里找**上游那条行内公式构造**（`name === "mathText"`）。
 *
 * ⚠️ 认**名字**不认身份：这样 `remark-math` 换选项、换版本都不用跟着改。
 * 找不到就返回 `undefined`，调用方**什么都不做**（退回上游行为），不猜。
 */
export function 找上游美元(扩展表: readonly unknown[]): 构造 | undefined {
  for (const 项 of 扩展表) {
    const 表 = (项 as { text?: Record<number, unknown> } | null)?.text;
    if (!表) continue;
    const 条 = 表[36];
    const 列 = Array.isArray(条) ? 条 : 条 ? [条] : [];
    for (const 颗 of 列) {
      const 候选 = 颗 as 构造 | undefined;
      if (候选?.name === "mathText" && typeof 候选.tokenize === "function") return 候选;
    }
  }
  return undefined;
}

/* ── 挂给 milkdown 的那一份 ───────────────────────────────────────────── */

/**
 * remark 插件：**在别人的插件都挂完之后**（`remark-math` 那份已经在表里了），
 * 把包装过的那一条追加进去。
 *
 * ⚠️ **必须排在 `remark-math` 后面**（`create.ts` 里 `.use(math)` 在它前面）：
 * 排在前面的话表里还没有上游那一条，`找上游美元` 找不着，这个插件就白挂了。
 * ⚠️ 这条约束**测试量得到**（`tests/math-currency.test.ts` 最后那一组直接读
 * `create.ts`），别只写在注释里。
 */
export function 收严美元插件(this: unknown): void {
  const 机 = this as { data: () => Record<string, unknown> };
  const 全部 = 机.data();
  const 表 = 全部["micromarkExtensions"];
  if (!Array.isArray(表)) return;
  const 上游 = 找上游美元(表);
  if (!上游) return;
  表.push({
    text: { 36: 收窄美元公式(上游) },
    // ⚠️ 上游那条按名字停掉（它是来者不拒的，不停掉的话我们 `nok` 之后
    // 会在同一个位置上再问它一次，然后它又配成了公式）。
    disable: { null: ["mathText"] },
  });
}

/** `$remark` 那个工厂的类型（与 `math-delim.ts` 同一套写法：**从它自己的参数里反推**）。 */
type 转换器工厂 = Parameters<typeof $remark<"收严美元", undefined>>[1];

/** 那个插件本体（三层里的**后两层**：选项 → 插件）。 */
const 收严美元工厂: 转换器工厂 = () => 收严美元插件;

/** 挂给 milkdown 的那一份：`.use()` 得**排在 `math` 后面**。 */
export const 收严美元 = $remark("收严美元", 收严美元工厂);
