/**
 * 界面国际化的**前端那一半**。
 *
 * # 规矩只有一条：**键就是原文，缺键就用原文**
 *
 * ```ts
 * t("插件")   // 英文表里有 → "Plugins"；没有 → "插件"
 * ```
 *
 * 所以：
 *
 * - 中文**没有表**。中文是原文，一张空表而已——不必维护一份"中文翻译中文"的
 *   文件（那种文件的下场是没人更新它）；
 * - 只有要翻译的那些才进 `en.ts`；
 * - 加一句界面文字**不用先登记 key**，直接 `t("…")` 就完了。
 *
 * ⚠️ 代价：**改了中文原文＝改了一个键**，那条英文会悄悄失效（退回中文，不报错）。
 * 这与插件那边（`src-tauri/src/lua/api/i18n.rs`）是**同一条规矩**——两处同一套，
 * 用户/作者只需要记一次。
 *
 * # 语言从哪儿来
 *
 * 宿主（`commands/settings.rs::nota_app_lang`）。⚠️ 拿的是**启动时算好的那个
 * 有效语言**，不是"设置里那一格的现值"：用户改了设置要**重启**才生效
 * （插件在启动时按那个语言读好了自己的文案表），前端跟着一起换才不会出现
 * "界面英文、插件中文"的中间态。理由写在 `settings/general.rs::language`。
 *
 * # 为什么是个订阅式的小 store，而不是 React context
 *
 * 因为**非组件的地方也要用**：`PluginDock.tsx::来源说明`、`ReviewPane.tsx::预览标题`
 * 都是纯函数，它们拿不到 context。一个模块级的"当前语言" + `useSyncExternalStore`
 * 订阅，两头都能用（组件里用 [`useT`]，别处用 [`t`]）。
 *
 * # 覆盖范围（2026-09-26 起：整个界面）
 *
 * 起点只有插件那一面（插件栏、面板内容块、编辑区预览），2026-09-26 那天铺到了
 * 整个界面：菜单栏、设置九页、状态栏、侧边栏、对话框、工具条都在里面。
 * `tools/i18n-check.sh` 拿代码里 `t("…")` 的调用与英文表逐条对，欠账条数就是
 * 进度；那天收尾时是 730 / 730、0 欠账，**2026-09-26 晚实测已长到 732 / 732**
 *（加了别的东西，键数就跟着长）。⚠️ **这个数会随着 `t("…")` 的增删自己动**
 *——引用它的时候现跑一遍 `tools/i18n-check.sh`，别照抄。
 *
 * ⚠️ **这就是 [`兜底`] 翻成 `en` 的前提**（见下）。宿主的兜底
 * （`src-tauri/src/lang.rs::应用兜底`）**必须同值**，不然"界面自洽"这条不成立。
 */

import { useSyncExternalStore } from "react";

import { 英文表 } from "@/i18n/en";

/**
 * 兜底语言。⚠️ 与宿主那边（`src-tauri/src/lang.rs::应用兜底`）是同一个值。
 *
 * ⚠️ **2026-09-26 从 `zh-CN` 翻成了 `en`**，理由有两条，缺一条都不该翻：
 *
 * 1. **覆盖齐了**：翻之前先量过——英文表与代码里的 `t("…")` 调用
 *    730 对 730、0 欠账（现已是 732 / 732，见上面"覆盖范围"那段）。没齐就翻的后果是**界面被切成两半**（新的那句英文、
 *    没翻的那句中文），而那种"半英文"比整片中文更难看懂；
 * 2. **它是"未命中"的落点**（`lang.rs::应用兜底` 那段同一条）：
 *    系统语区不在支持列表里时落到这个值。基准是英文，那么落点也该是英文
 *    ——落到中文等于**替用户假定他读中文**，而系统语区恰好说明不了这件事。
 *
 * ⚠️ 它**不是**"默认语言"：中文语区的用户照旧拿到中文界面（宿主按系统语区
 * 算，`zh-CN` 在支持列表里）。这里是兜底，只在**认不出来**时才用上。
 */
const 兜底 = "en";

/** 语言 → 表。中文不进这张表：它的表是空的（缺键用原文）。 */
const 表: Record<string, Record<string, string>> = {
  en: 英文表,
};

let 当前 = 兜底;
const 听众 = new Set<() => void>();

/** 宿主报了语言之后调这一下。**只该由 `App.tsx` 启动那一段调**。 */
export function 定语言(语言: string): void {
  if (语言 === 当前) return;
  当前 = 语言;
  听众.forEach((f) => f());
}

/** 此刻在说哪种语言（`zh-CN` / `en`）。 */
export function 语言(): string {
  return 当前;
}

/**
 * 取一句文案。`{0}` / `{1}` 是参数占位符。
 *
 * ⚠️ **同一个键在两个地方要有两种译法时，别指望这张表**：它按原文去查，
 * 查到的只有一条。真遇到那种情况就把原文改成两句不同的话（键不同，译法自然不同）。
 */
export function t(原文: string, ...参数: (string | number)[]): string {
  const 句 = 表[当前]?.[原文] ?? 原文;
  if (参数.length === 0) return 句;
  return 句.replace(/\{(\d+)\}/g, (整, i: string) => {
    const v = 参数[Number(i)];
    return v === undefined ? 整 : String(v);
  });
}

function 订阅(f: () => void): () => void {
  听众.add(f);
  return () => 听众.delete(f);
}

/**
 * 组件里用这个：它**订阅**了语言变化，宿主报来语言之后这一块会重画。
 *
 * ⚠️ 组件里请 `const t = useT();`（局部名盖住模块那个 `t`），别直接调模块级的
 * `t(...)` 就算完——那样首帧画的是兜底语言，而**没有任何东西会通知它重画**。
 * 首帧与宿主答话之间只差几毫秒，但那几毫秒里画出来的字是错的。
 */
export function useT(): typeof t {
  useSyncExternalStore(订阅, 语言, 语言);
  return t;
}

/**
 * 组件/hook 里要"语言变了就重做一遍某件事"时用这个（订阅的就是当前语言本身）。
 *
 * ⚠️ 与 [`useT`] 的分工：**要画字**就用 `useT`（它顺手把订阅做了）；**不是画字、
 * 而是把语言当依赖**（推原生菜单、重建什么东西）才用它。用 `useT()` 去干这件事
 * 会多一个没人看的 `t` 变量，而被 `noUnusedLocals` 拦下。
 *
 * ⚠️ 值今天是"重启才变"的（见 `settings/general.rs::language`），但这不构成
 * "那就别订阅了"的理由：写死一个不动的依赖，等哪天热切语言真做了，症状是
 * **原生菜单栏还是旧语言**——而那种地方没人会想到去查依赖数组。
 */
export function use语言(): string {
  return useSyncExternalStore(订阅, 语言, 语言);
}
