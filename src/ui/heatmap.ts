/**
 * **长期记录的热力图**（Contribution Graph 那种一格一天的小方格，2026-09-27 加，
 * 写作统计要的）。
 *
 * 用户原话：「加一个功能，类似 Contribution Graph 那样的热力图，记录长期数据。
 * 仅记录打字数。」——三句话定下三件事：**一格一天**（不是一小时、不是一次）、
 * **看得见长期**（默认铺半年，最多一年）、**只有打字数**（不比速度、不掺别的）。
 *
 * # 这一份只算格子的位置，不画
 *
 * 与 `ui/chart-ticks.ts` 同一条分工：**插件说数据、这里说版式、`PanelBody.tsx`
 * 画**。这样"哪一格是哪一天"可以脱离 React 单独测（`tests/heatmap.test.ts`），
 * 而 260px 宽的一栏里格子该多大、什么颜色是样式表的事（`styles/heatmap.css`）。
 *
 * # 三条口径
 *
 * | 事 | 怎么办 | 为什么 |
 * |---|---|---|
 * | 一列 = 一周 | **从周一起**，7 行 | 中文界面里的日历就是从周一起（周日打头是另一套习惯，选了就别改） |
 * | 最后那一列 | 到 `止` 那天为止，**下面留空** | 今天是周三就只画三格：把未来几天画成"0 字"是在编数据 |
 * | 缺的那些天 | 当 **0**，不是当"没有" | 热力图要回答的是"最近写得勤不勤"，空白格正是答案的一半 |
 *
 * ⚠️ **它不认识"今天"**：窗口的右端由插件给的 `止` 决定（写作统计给的是
 * `nota.time.now()` 那一天）。拿不到时间来源时插件根本不会发这一块，
 * 所以这里不需要处理"今天几号"——那是插件的事，而它在沙箱里只有一条时间来源。
 *
 * ⚠️ **上限两条，都在这里夹**：`面板节点上限`（200）逼得插件不能一天一项地发
 * （一年 365 天），所以记录走的是**一个字符串**（格式由宿主定，见
 * `读热力记录`）；而画多少列是插件说的（`weeks`），这里夹在 8~53。
 *
 * ⚠️ 月份那行标签（`9月` / `Sep`）走 `Intl`，**不写死「月」**：这张图既在面板上、
 * 也在分享图上，而分享图是要发出去的（英文界面下发出「9月」等于没翻译）。语言取
 * `i18n` 那一份全局真相——和 `ui/share-card.ts::当前卡色()` 读 `<html>` 同一个道理：
 * 那是全应用唯一的一份，不该从调用方一层层传进来。
 */

import { 语言 } from "../i18n";

/** 一天的记录。 */
export interface 热力记录 {
  /** `2026-09-27`。 */
  日: string;
  /** 那一天写了多少字。**只有字**——用户点名「仅记录打字数」。 */
  值: number;
}

/** 一格。 */
export interface 热力格 {
  /** `2026-09-27`。渲染层拿它做悬停提示。 */
  日: string;
  值: number;
  /** 颜色深浅，**0 = 没写**（`1`~`4` 由大到小）。 */
  档: 0 | 1 | 2 | 3 | 4;
}

/** 一列 = 一周。 */
export interface 热力列 {
  /** 这一列顶上那个月份（`9月`）。**空串 = 不标**（同一个月只标一次）。 */
  月: string;
  /** 从周一到周日，最多 7 格。最后一列可能不足 7 格。 */
  格: 热力格[];
}

/** 一张算好的热力图。 */
export interface 热力图 {
  列: 热力列[];
  /** 窗口里最大的一天（定每档的深浅）。 */
  最大: number;
  /** 窗口里的总和（「这半年一共写了多少字」）。 */
  总计: number;
  /** 窗口里**有字**的天数（不是窗口长度——"写了 173 天"比"这半年"更有用）。 */
  天数: number;
  /** 窗口的第一天 / 最后一天（`2026-04-06` / `2026-09-27`）。 */
  起: string;
  止: string;
}

/** 一年最多这些列。再多一年就摆不下了（53 周 = 371 天）。 */
const 周数上限 = 53;
/** 少于这个列数不成"长期"（8 周 = 两个月）。 */
const 周数下限 = 8;
/** 插件没写 `weeks` 时铺多久：半年。 */
const 默认周数 = 26;
/** 最多认这么多天的记录（比一年略多，防手里的账本比窗口还长）。 */
const 记录上限 = 400;

/**
 * 读插件给的 `days` 字符串。
 *
 * **格式是宿主定的**（不是插件自由发挥）：`2026-09-27:1284 2026-09-26:0`，
 * 一对之间用空白隔开，日期是 `YYYY-MM-DD`，值是**非负整数**。
 *
 * ⚠️ **为什么不是数组**：宿主对**一层里的项数**有 200 的上限
 * （`lua/api/ui.rs::面板节点上限`，那是防"一次渲染几千行"的），而一年是 365 天。
 * 字符串这一条路走的是另一条上限（一个文本字段 20000 字），365 天大约 5 KB，
 * 宽裕。所以这个格式是**被上限逼出来的**，不是设计偏好——真要改成数组，
 * 得先把那一层的上限改了，而 200 那条线是别的块（`list` / `diff` / `graph`）
 * 一起在用的。
 *
 * ⚠️ **坏项丢掉、不报错**（同 `读刻度`）：一个日期写错不该让整张图消失。
 * ⚠️ 日期**要比对真日历**：`2026-02-30` 长得像日期、`2026-13-01` 也像，
 * 但都不存在——它们会往后溢出成 3 月 2 日 / 次年 1 月 1 日，在图上就是一格
 * 凭空多出来的字。所以这里走的是与铺格子同一个 `日号()`。
 * ⚠️ 同一天出现两次**后写的赢**：那是"账本里有重复行"的症状，而这里不是
 * 修账的地方（`plugins/stats/main.lua` 那边按天索引，本来就不会重复）。
 */
export function 读热力记录(raw: unknown): 热力记录[] {
  if (typeof raw !== "string") return [];
  const 表 = new Map<string, number>();
  for (const 段 of raw.split(/\s+/)) {
    if (!段 || 表.size >= 记录上限) continue;
    const 切 = 段.indexOf(":");
    if (切 <= 0) continue;
    const 日 = 段.slice(0, 切);
    if (!日号(日)) continue;
    const 值 = Number(段.slice(切 + 1));
    if (!Number.isFinite(值) || 值 < 0) continue;
    表.set(日, Math.floor(值));
  }
  return [...表].map(([日, 值]) => ({ 日, 值 }));
}

/** `YYYY-MM-DD` 才算。 */
function 是日期(s: string): boolean {
  return /^\d{4}-\d{2}-\d{2}$/.test(s);
}

/**
 * `2026-09-27` → **本地时区**的那一天零点。
 *
 * ⚠️ 不能写 `new Date("2026-09-27")`：那一串会被当成 **UTC** 解析，在东八区
 * 变成前一天早上八点——整张图会整体偏一格，而且只在某些时区偏。所以自己拆。
 */
function 日号(日: string): Date | null {
  if (!是日期(日)) return null;
  const 年 = Number(日.slice(0, 4));
  const 月 = Number(日.slice(5, 7));
  const 天 = Number(日.slice(8, 10));
  if (月 < 1 || 月 > 12 || 天 < 1 || 天 > 31) return null;
  const d = new Date(年, 月 - 1, 天);
  // 溢出的日期（`2026-02-30` → 3 月 2 日）不算那一天，当没有。
  if (d.getMonth() !== 月 - 1 || d.getDate() !== 天) return null;
  return d;
}

/** 反过来：本地那一天 → `2026-09-27`。 */
function 日串(d: Date): string {
  const 月 = String(d.getMonth() + 1).padStart(2, "0");
  const 天 = String(d.getDate()).padStart(2, "0");
  return `${d.getFullYear()}-${月}-${天}`;
}

/** 加减天数。⚠️ 走 `setDate`（会自己跨月跨年），不是"加 86400 秒"——夏令时那天不是 24 小时。 */
function 移(d: Date, 天: number): Date {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate() + 天);
}

/** 周一 = 0，周日 = 6。 */
function 星期几(d: Date): number {
  return (d.getDay() + 6) % 7;
}

/** 数值 → 颜色档。⚠️ 相对**这张图的最大值**分四档（不写死阈值：一天 300 字和一天 3000 字都该有自己的深浅）。 */
function 档(值: number, 最大: number): 0 | 1 | 2 | 3 | 4 {
  if (值 <= 0) return 0;
  if (最大 <= 0) return 1;
  if (值 * 4 <= 最大) return 1;
  if (值 * 2 <= 最大) return 2;
  if (值 * 4 <= 最大 * 3) return 3;
  return 4;
}

/**
 * 把记录铺成格子。
 *
 * `止` 是窗口右端那一天（`YYYY-MM-DD`），`周数` 是窗口有几列（夹在 8~53，
 * 认不出来用 26）。`止` 认不出来时退到**记录里最晚的那一天**——两张都认不出来
 * 就是一张空图（`列` 是空数组，渲染层不画）。
 */
export function 算热力(记录: 热力记录[], 止: string, 周数: number): 热力图 {
  const 空: 热力图 = { 列: [], 最大: 0, 总计: 0, 天数: 0, 起: "", 止: "" };
  const 表 = new Map(记录.map((r) => [r.日, r.值]));

  let 末日 = 日号(止);
  if (!末日) {
    for (const r of 记录) {
      const d = 日号(r.日);
      if (d && (!末日 || d > 末日)) 末日 = d;
    }
  }
  if (!末日) return 空;

  const 列数 = Math.min(周数上限, Math.max(周数下限, Math.floor(周数) || 默认周数));
  // 末列的**周一**：今天是周三就退回两天，好让最后一列还是"周一到周日"。
  const 末列起 = 移(末日, -星期几(末日));
  const 首列起 = 移(末列起, -(列数 - 1) * 7);

  const 列: 热力列[] = [];
  let 最大 = 0;
  let 总计 = 0;
  let 天数 = 0;
  let 上个标签 = "";
  for (let c = 0; c < 列数; c++) {
    const 本列起 = 移(首列起, c * 7);
    const 格: 热力格[] = [];
    for (let r = 0; r < 7; r++) {
      const 本日 = 移(本列起, r);
      if (本日 > 末日) break; // 最后一列：未来的那几天不画（`break` 不是 `continue`）
      const 键 = 日串(本日);
      const 值 = 表.get(键) ?? 0;
      if (值 > 最大) 最大 = 值;
      总计 += 值;
      if (值 > 0) 天数 += 1;
      格.push({ 日: 键, 值, 档: 0 }); // 档要等最大出来才知道，下面补
    }
    // ⚠️ 标签先算进一个局部量再 push：`列[列.length - 1]` 那种写法在
    // `noUncheckedIndexedAccess` 下是"可能没有"，而且它读的正是刚写进去的东西。
    const 本标签 = 月标签(本列起, 上个标签);
    列.push({ 月: 本标签, 格 });
    上个标签 = 本标签 || 上个标签;
  }

  // ⚠️ **两遍**：深浅是相对最大值的，而最大值要等所有格子都数完才知道。
  for (const 一列 of 列) {
    for (const 一 of 一列.格) 一.档 = 档(一.值, 最大);
  }

  return { 列, 最大, 总计, 天数, 起: 日串(首列起), 止: 日串(末日) };
}

/**
 * 那一列表头要写哪个月（`9月` / `Sep`）。**同一个月只标一次**（写在它出现的第一列上）。
 *
 * ⚠️ 判据是"与**上一列的标签**不同"，不是"与上一列的日子不同"：跨月的那一列
 * 常常是半截（上个月的最后几天 ＋ 这个月的头几天），拿日子比会在两个月之间
 * 来回跳着标。
 *
 * ⚠️ `month: "short"` 是**唯一**能同时给出「9月」和「Sep」的档：`"long"` 在中文
 * 里还是「9月」、在英文里变成「September」（26 列里挤不下），`"narrow"` 在英文
 * 里退化成一个字母「S」（9 月和 11 月长得一模一样）。
 */
function 月标签(本列起: Date, 上个: string): string {
  const 本 = 月名(本列起);
  return 本 === 上个 ? "" : 本;
}

/** 月份名随界面语言走。**按语言缓存一个**——26 列会问 26 次，而语言几乎不变。 */
let 月格式: { 语言: string; 器: Intl.DateTimeFormat } | null = null;

function 月名(d: Date): string {
  const 语 = 语言();
  if (!月格式 || 月格式.语言 !== 语) {
    月格式 = { 语言: 语, 器: new Intl.DateTimeFormat(语, { month: "short" }) };
  }
  return 月格式.器.format(d);
}
