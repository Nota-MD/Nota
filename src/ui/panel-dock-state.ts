/**
 * 右侧插件栏的**两份账**：每个面板拉回来的内容、以及某个插件正在往外吐的那段字。
 *
 * # ⚠️ 它们为什么不住在组件里（2026-10-10 用户报的那条，第 111 项）
 *
 * 用户原话：「**AI插件运行中关掉插件面板再打开就找不到了**」。
 *
 * 根因是**两件事叠在一起**，缺一件都复现不出来：
 *
 * 1. **关掉这一栏 = 组件被卸载**（`App.tsx` 里那一句 `{dockOpen && <PluginDock/>}`），
 *    于是组件里的 `useState`（当前是哪一页、每页拉回来的内容、正在吐的那段字）
 *    **全部丢掉**。从前这个代价是看得见的、也是可接受的——切回来只是"重新拉一次"，
 *    慢接口下闪一下「正在读取…」；
 * 2. 而**插件的一条命令正在跑的时候，宿主一直握着 `plugins` 锁**，
 *    `nota_plugin_panel_content` 要的**正是同一把锁**（这条不变量的出处：
 *    `lua/api/ui.rs::实时表` 顶上那段，以及 `commands/plugin.rs::nota_plugin_call`）。
 *    所以那一次"重新拉"**回不来**：它一直等到那条命令整个跑完才落地。
 *
 * 两条一叠，症状就是用户看见的那个：跑一条 AI 请求（几十秒）→ 关掉这一栏 →
 * 再打开 → **面板一直空着**（拉不回内容），而"正在写的那段字"当时也画不出来
 * ——它从前挂在"内容已经拉回来"（`state === "ok"`）那一支下面。
 *
 * 所以这里做两件事，是**同一件事的两半**：
 *
 * - 这份模块把上面那两份账**记在组件外面**（关掉再打开时按原样恢复：回到原来那一页、
 *   内容立刻就在、流式文字接着往末尾长）；
 * - [`这一页画什么`] 把"这一刻该画什么"抽成**纯函数**，其中一条就是
 *   **内容还没拉回来、但有流式文字时先画那段文字**——这是上面第 2 条的正面回答：
 *   锁拿不到是宿主的设计，界面不该因此变成一块空白。
 *
 * # 记下来的东西里有一样**故意抹掉**
 *
 * `busy`（这一页正在跑哪条命令）**不进记忆**（[`记住内容表`]）。理由是它会**卡住**：
 * 跑完那一下是"这一趟请求的 `finally` 里再拉一次"，而那次拉在面板**关着**的时候
 * 落在了一个已经卸载的组件上——它改不动任何东西。要是把 `busy` 一起记下来，
 * 用户重开面板时看到的是一排**永远灰着的按钮**，而且没有任何东西会把它解开。
 * 记下来的只有"这一页长什么样"，跑没在跑由**当下**这一份 state 说。
 *
 * ⚠️ 这份记忆是**进程内、不落盘**的：它只是一份显示缓存，关掉应用就该忘掉
 *（真内容在插件自己那边，重开时照旧拉一次）。
 */

import { normalise, type PanelNode } from "@/ui/panel-nodes";

/** 一个面板此刻的状态。`loading` 只在**第一次**拉的时候出现——
 *  重拉时保留旧内容，否则每按一次「刷新」面板就闪一下白。 */
export type 面板状态 =
  | { state: "loading" }
  | { state: "ok"; nodes: PanelNode[]; busy: string | null }
  | { state: "error"; message: string; busy: string | null };

/** 页签的坐标。`null` = 「插件」那一页（插件清单，不是插件声明的面板）。 */
export type 页 = string | null;

/** 关掉这一栏再打开时**要接着用的那一份**（见文件头）。 */
export interface 面板记忆 {
  /**
   * 上一次停在那一页。
   *
   * ⚠️ 三态，别拿 `??` 去接：`undefined` = 还没选过（那时才该落到第一页）、
   * `null` = **用户自己停在「插件」那一页**（那是一个正经的选择，不该被顶掉）。
   */
  当前: 页 | undefined;
  内容表: Record<string, 面板状态>;
  实时表: Record<string, string>;
}

/** 这份记忆**只有一份**（一个应用一个窗口一栏）。 */
export const 记忆: 面板记忆 = { 当前: undefined, 内容表: {}, 实时表: {} };

/**
 * 这一栏**开起来的时候停在哪一页**。
 *
 * ⚠️⚠️ 这里是三态，写成 `记得的 ?? 键们[0]` 就错了：`null` 的意思是
 * **用户自己停在「插件」那一页**（一个正经的选择），`??` 会把它当成"没有"
 * 顶回第一个面板去——症状是"我明明留在插件清单那一页，重开又跳回 AI 了"。
 * 只有 `undefined`（这份记忆里从没记过）才该落到第一页。
 *
 * ⚠️ 抽成纯函数是为了能在 `tests/panel-dock-state.test.ts` 里把三态各钉一条
 * （`null` / `undefined` / 清单还空着）。
 */
export function 起始页(记得的: 页 | undefined, 键们: readonly string[]): 页 {
  return 记得的 !== undefined ? 记得的 : (键们[0] ?? null);
}

/**
 * 把一份内容表抄进记忆，**只做一件事：把 `busy` 抹掉**（理由见文件头）。
 *
 * ⚠️ 抄的是**新的对象**，不是那一份 state 本身：留在记忆里的东西不许和
 * 组件手上的那一份共用引用，否则后面谁就地改了它，两份会一起变。
 * ⚠️ 连 `nodes` 那个**数组**也要抄一份——`: { ...态 }` 只是浅拷贝，
 * 数组还是同一个；测试里往记忆那份 `push` 一条，组件手上那份会跟着多一条
 * （`tests/panel-dock-state.test.ts` 第 (4) 组钉着这一条，它当时就是这么红的）。
 */
export function 记住内容表(表: Record<string, 面板状态>): Record<string, 面板状态> {
  const 出: Record<string, 面板状态> = {};
  for (const [键, 态] of Object.entries(表)) {
    // ⚠️ 两档都要抹（`ok` 与 `error` 都带 `busy` 那一格）。
    出[键] =
      态.state === "ok"
        ? { ...态, nodes: [...态.nodes], busy: null }
        : 态.state === "error"
          ? { ...态, busy: null }
          : 态;
  }
  return 出;
}

/** [`这一页画什么`] 的结论。 */
export interface 该画什么 {
  /** 这一页要画的节点（已经收窄过、已经拼上流式那一条）。 */
  节点们: PanelNode[];
  /** 没有节点可画时那句提示。 */
  提示: "载入" | "空" | null;
  /** 拉失败那一句（有它就不画别的）。 */
  错误: string | null;
  /** 这一页正在跑哪条命令（按钮要不要灰着）。 */
  busy: string | null;
}

/**
 * 这一刻该画什么。**纯函数**，好让 `tests/panel-dock-state.test.ts` 在纯 node 里
 * 把三档（正在拉 / 拉到了 / 拉失败了）各钉一遍——尤其是"**正在拉、但有流式文字**"
 * 那一档，它正是这次那条报障的可见那一半。
 *
 * ⚠️ 流式那条**拼在最后**：它是"此刻正在写的东西"，位置就该在这一页的末尾。
 * 它走 `normalise` 收窄，理由与 `PluginDock` 里那句一样——它是所有节点形状的
 * 唯一那道门（长度上限、字段名、缺省），绕过它拼出来的东西不受那些上限管。
 *
 * ⚠️ 拉失败（`error`）时**不画流式文字**：那一段的意义是"结果马上就来"，
 * 而拉失败恰恰是"这一页坏了"——两句话叠在一起，用户读不出哪句是真的。
 */
export function 这一页画什么(态: 面板状态, 实时: string): 该画什么 {
  if (态.state === "error") {
    return { 节点们: [], 提示: null, 错误: 态.message, busy: 态.busy };
  }

  const 实时节点 =
    实时 === "" ? null : (normalise([{ kind: "message", from: "ai", text: 实时 }])[0] ?? null);

  if (态.state === "loading") {
    // ⚠️ 这一支就是这次的修法（见文件头）：**内容还拉不回来的时候，先把正在吐的
    // 那段字画出来**。没有它，命令跑着的时候重开面板只能看见一句「正在读取…」，
    // 而那一次的"读取"要等命令跑完（锁在宿主那边）。
    return 实时节点
      ? { 节点们: [实时节点], 提示: null, 错误: null, busy: null }
      : { 节点们: [], 提示: "载入", 错误: null, busy: null };
  }

  const 节点们 = 实时节点 === null ? 态.nodes : [...态.nodes, 实时节点];
  return {
    节点们,
    提示: 节点们.length === 0 ? "空" : null,
    错误: null,
    busy: 态.busy,
  };
}
