/**
 * **表格列宽侧车**的读写（2026-10-07 从 `ui/EditorPane.tsx` 搬出来的，
 * `docs/07` 第 89 项）。
 *
 * 列宽不是文档内容，是一份按**路径**记的偏好（`~/.local/share/nota/` 下的
 * 侧车，后端 `nota_table_widths_get` / `nota_table_widths_set`）。这一层管
 * "哪一份文档、什么时候读、什么时候写"，**怎么算列宽、怎么认指纹**在编辑器
 * 那一侧（`editor/table-width.ts`）。
 *
 * # ⚠️ 没有路径就一个字都不碰
 *
 * `doc.path` 是 `null` = 一份还没落盘的新文档。侧车是按路径记的，一份没有
 * 落盘的东西**没有可记的地方**：
 *
 * - 读：查了只会拿到空（那一瞬间它还不存在于任何一张表里），不如不查；
 * - 写：写不了（没有键）。⚠️ 这也是**为什么不把 `doc.path` 传进 `createEditor`**：
 *   "存到哪儿"是调用方的事，编辑器不该知道有文件这回事——它只报"哪张表拖成了
 *   什么样"（`onTableResize`），落到哪儿由这里决定。
 *
 * ⚠️ 拖了列宽但没落盘的文档**不会**在保存之后补记：那一笔在拖的那一刻被丢
 * 掉了。这是有意的（记一份还不存在的路径，等它改名 / 改到别处之后就是一条
 * 永远对不上的垃圾记录）。
 *
 * # ⚠️ 两个方向都不许拦路
 *
 * - **读失败**（侧车文件坏了、权限不对）不拦着建编辑器：侧车是排版偏好，
 *   读不到就按自动排版显示，比"因为一个记录文件读不出来所以打不开文档"
 *   合理得多；
 * - **写失败**只 warn：用户此刻已经看到那张表被拖宽了，弹条提示也换不回
 *   什么——下一次同一个格子上还会再写一遍。
 */

import { api } from "@/bridge/ipc";

/** 一张表的列宽记录：指纹 → 各列宽度（像素）。 */
export interface 一张表的列宽 {
  /** `editor/table-width.ts` 算出来的指纹。⚠️ 内容变了指纹就变，旧记录自然作废。 */
  指纹: string;
  /** 各列宽度，按列序。 */
  宽度: number[];
}

/**
 * 读这份文档记过的列宽。**没记过 / 没有路径 / 读失败都给空对象**——调用方
 * 不需要区分这三种情况（空 = 按自动排版显示）。
 *
 * ⚠️ 拿到的可能是**任何**文档的键混在一起？不会：后端按 `path` 分。
 * ⚠️ 这里面可能有一条记录**对不上任何一张现存的表**（表被改了 / 删了）——
 * 不在这里清：编辑器只按指纹查自己要的那几条（`table-width.ts::读出列宽`），
 * 对不上的记录烂在侧车里无害，而"顺手清一遍"会在多窗口同时开着同一份文档时
 * 删掉另一个窗口刚写的那条。
 */
export async function 读表格列宽(
  路径: string | null | undefined,
): Promise<Record<string, number[]>> {
  if (!路径) return {};
  try {
    return await api.tableWidths.get(路径);
  } catch (e) {
    console.warn("[nota] 读表格列宽记录失败，按自动排版显示：", e);
    return {};
  }
}

/**
 * 把编辑器报来的这一批记进侧车。
 *
 * ⚠️ 报来的是**这一刻所有拖过的表**（不是"刚拖的那一张"）：宿主按指纹逐条
 * 记，多报几条没拖过的也无妨——它们本来就不在结果里（见 `table-width.ts::
 * 读出列宽`）。这样编辑器那一侧不必记住"上一次报的是什么"。
 *
 * ⚠️ **不 await**（每条各飘各的）：这是排版偏好，写慢了写丢了都不该让用户的
 * 下一步动作等它。失败只 warn，理由见文件头。
 */
export function 存表格列宽(路径: string | null | undefined, 表: 一张表的列宽[]): void {
  if (!路径) return;
  for (const 一张 of 表) {
    api.tableWidths
      .set(路径, 一张.指纹, 一张.宽度)
      .catch((e) => console.warn("[nota] 记表格列宽失败：", e));
  }
}
