/* ── 二、黑字还是白字：**必须重现出厂那 13 对** ─────────────────────── */

/**
 * 从 `theme/color.css` 里读出厂那几对 `--accent` / `--accent-fg`。
 *
 * ⚠️⚠️ **读真文件，不在这里抄一份表**。抄一份的症状是：改了颜色而忘了改这份
 * 测试，于是"测试全绿"和"判据对不上出厂值"同时成立——那正是这条判据第一版
 * 栽的地方（7 对不一致，测试却是绿的）。同一件事的先例见
 * `tests/atom-space.test.ts` 顶上那段"判据只有一个：读落盘字节"。
 */
function 读出厂的强调色对(): { accent: string; fg: string }[] {
  // ⚠️ 用 `process.cwd()` 而不是 `__dirname`：这份测试**先被 esbuild 打成一个
  // `.mjs` 再跑**（见文件头的跑法），`__dirname` 在 ESM 里根本不存在。
  // 所以**必须在仓库根目录跑**，同 `atom-space.test.ts` 那条。
  const 路径 = resolve(process.cwd(), "src/styles/theme/color.css");
  const 行 = readFileSync(路径, "utf8").split("\n");
  const 对: { accent: string; fg: string }[] = [];
  for (let i = 0; i < 行.length; i++) {
    const a = 行[i].match(/--accent:\s*(#[0-9a-fA-F]{3,6})/);
    if (!a) continue;
    const f = 行[i + 1]?.match(/--accent-fg:\s*(#[0-9a-fA-F]{3,6})/);
    if (f) 对.push({ accent: a[1].toLowerCase(), fg: f[1].toLowerCase() });
  }
  return 对;
}

组("二、accentFg 的分界必须重现 color.css 那 13 对（**这条是本次改动的由来**）");

测("出厂那 13 对，一对不落，判据都得落在同一边", () => {
  const 对 = 读出厂的强调色对();
  // ⚠️ 数量也断言：正则哪天读不到东西了，"零对全过"是**假绿**。
  // ⚠️ **2026-10-07 从 15 降到 13**：用户说「只需要 Yaru，不需要 Yaru Blue 了」，
  // 那个风格整档删掉（`color.css` 里少了两段，一浅一深）。⇒ 现在是
  // **7 档 × 明暗 = 14 段，其中 windows10 两段同值 ⇒ 13 对**。
  等(对.length, 13, "color.css 里该有 13 对（7 档 × 明暗，其中一处两档同值）");
  const 不一致: string[] = [];
  for (const { accent, fg } of 对) {
    const 出厂用白 = fg === 白;
    const 我方用白 = accentFg(accent) === 白;
    if (出厂用白 !== 我方用白) {
      不一致.push(`${accent}（出厂 ${fg}，我方 ${accentFg(accent)}）`);
    }
  }
  断言(
    不一致.length === 0,
    `有 ${不一致.length} 对和出厂值落在了不同边：\n      ${不一致.join("\n      ")}\n` +
      `      改这条判据之前先读 accent.ts 的「分界亮度」那段。`,
  );
});

测("分界亮度 0.25 正好卡在出厂两边的极值中间", () => {
  const 对 = 读出厂的强调色对();
  const 白那边 = 对.filter((p) => p.fg === 白).map((p) => 相对亮度(p.accent));
  const 深那边 = 对.filter((p) => p.fg !== 白).map((p) => 相对亮度(p.accent));
  const 白最高 = Math.max(...白那边);
  const 深最低 = Math.min(...深那边);
  断言(白最高 < 0.25 && 0.25 <= 深最低, `白字那侧最高 ${白最高}，深字那侧最低 ${深最低}，0.25 该夹在中间`);
  // ⚠️ 这两个数就是 `分界亮度` 那段引用的那两个：`#e95420`／`#0a84ff` 与 `#f3732e`。
  // 把具体值也钉住，是为了让"0.25 是从哪来的"这句话**可查**：
  // 出厂值哪天改了，这个断言会红，然后读那段注释的人会看到需要重新取线。
  等(白最高.toFixed(3), "0.238", "白字那侧最高的一对（Yaru 橙 #e95420 ／ macOS 深色 #0a84ff，都是 0.238）");
  // ⚠️ 这一格**2026-10-07 换过人**：原来是 Yaru 蓝深色的 `#208fe9`（0.258），
  // 那一档删掉之后，深字那侧最低的变成 Yaru 深色的 `#f3732e`（0.315）。
  // ⚠️ **0.25 这条线仍然夹在中间**（0.238 < 0.25 ≤ 0.315），而且余量更大了。
  等(深最低.toFixed(3), "0.315", "深字那侧最低的一对（Yaru 深色 #f3732e）");
});

测("出厂 13 对里最低的对比度是 3.65:1（如实认账，不是新引入的）", () => {
  const 对 = 读出厂的强调色对();
  let 最低 = Infinity;
  let 谁 = "";
  for (const { accent, fg } of 对) {
    const c = 对比度(相对亮度(accent), 相对亮度(fg));
    if (c < 最低) {
      最低 = c;
      谁 = `${accent} / ${fg}`;
    }
  }
  console.log(`      出厂最低：${谁} = ${最低.toFixed(2)}:1（Yaru 橙 #e95420 也是同一档）`);
  // ⚠️ 这条**不是**"我们够 AA 了"的证明——3.65 低于 WCAG AA 对正文的 4.5。
  // 它是一条**不许更坏**的底线：判据改成阈值之后，"白字可以低到多少"
  // 至少要跟出厂值一样好。哪天有人把分界亮度往上调，这里会红。
  断言(最低 >= 3.5, `出厂最低对比度掉到了 ${最低.toFixed(2)}:1（${谁}），比 3.5 还低`);
  // ⚠️ 具体值也钉住：它是 `accent.ts` 里"认了白字可以低到 3.5:1"那句话的依据。
  等(最低.toFixed(2), "3.65", "出厂最低那一对");
});

