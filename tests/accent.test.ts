/* ── 一支极小的测试工装（与 `atom-space.test.ts` / `math-input.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 两个数差得在容差以内。⚠️ 只给"会有定点舍入"的那类量用（色相、坐标）。 */
function 近(实际: number, 期望: number, 容差: number, 说明: string): void {
  if (!(Math.abs(实际 - 期望) <= 容差)) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}±${容差}，实际 ${JSON.stringify(实际)}`);
  }
}

