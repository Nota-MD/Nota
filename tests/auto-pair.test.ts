/**
 * `src/editor/auto-pair.ts`（自动配对 ＋ Tab 跳出右半边）的**可运行**测试集。
 * 2026-09-28 写，与那个文件同批落地。
 *
 * # 跑法
 *
 * ```sh
 * npx esbuild tests/auto-pair.test.ts --bundle --platform=node --format=esm \
 *   --outfile=/tmp/nota-测试/auto-pair.mjs
 * node /tmp/nota-测试/auto-pair.mjs
 * ```
 *
 * # 这份测试盯的是什么
 *
 * 这一格的对错**全在判据上**：补错了字符、该跳的时候没跳、不该补的时候补了，
 * 屏幕上都不会报错——只会"手感不对"。所以五组：
 *
 * - 一、**两张表互为反表**（防死行：闭括号写错一颗，半年后才有人发现）；
 * - 二、**该收的收了、不该收的没收**——文件头第 2 节那张"不收的每一个都有
 *   理由"在这里是可执行的：`[` / 引号 / 反引号 / Markdown 标记一个都不许在表里；
 * - 三、`要配对` 的四种"不该补"；
 * - 四、另外三条判据（跳过 / 删成对 / 跳）的边界；
 * - 五、装配（只能证明"挂上去了"）。
 *
 * # ⚠️ 这份测试**证明不了**什么
 *
 * - ⚠️⚠️ **「打 `(` 屏幕上真出现 `()`」这条主路径没验**，只验到
 *   `配对处理()` 返回了一个非空的插件描述。真跑要 `Editor.make()` ＋ 真 DOM
 *   （本仓没有 jsdom，也不许为这件事装包）。**这是最大的空白。**
 * - ⚠️ **「`Tab` 真的跨过去了、而且没被 `indent` 抢走」没验**：那是
 *   `handleKeyDown` ＋ 真键位事件的顺序问题，只能开窗目检
 *   （`docs/07` 那一项里列着）。
 * - ⚠️ **「组字期间不插手」（`view.composing`）没验**：那要真 view ＋ 真 IME。
 * - ⚠️ **「`addToHistory: false` 所以 `Ctrl+Z` 不回退一步」没验**：那是
 *   `prosemirror-history` 的事，要真 view。
 */

import {
  配对表,
  闭括号,
  开括号,
  是开括号,
  是闭括号,
  要配对,
  要跳过,
  要删成对,
  要跳,
  配对处理,
  type 现场,
} from "../src/editor/auto-pair";

/* ── 一支极小的测试工装（与 `auto-correct.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 造一份现场，只写要变的那几格。默认：行首、行尾、正文、没选东西。 */
function 场(部分: Partial<现场> = {}): 现场 {
  return { 前: "", 后: "", 代码: false, 空选区: true, ...部分 };
}

/* ── 一、两张表 ─────────────────────────────────────────────────────── */

组("一、两张表（防死行）");

测("`配对表` 里每一条都能被 `闭括号` 查出来", () => {
  const 坏的: string[] = [];
  for (const [开, 闭] of Object.entries(配对表)) {
    if (闭括号(开) !== 闭) 坏的.push(`${开} → ${闭}（实际 ${闭括号(开)}）`);
  }
  if (坏的.length) throw new Error(`有 ${坏的.length} 条不生效：${坏的.join("、")}`);
});

测("反表与正表严格互逆（左右一一对应）", () => {
  // ⚠️ 这一条是**这份文件里最要紧的断言**：`开括号` 与 `闭括号` 要是对不上，
  // 症状是"跳得进去跳不出来"这类莫名其妙的手感问题。
  const 坏的: string[] = [];
  for (const [开, 闭] of Object.entries(配对表)) {
    if (开括号(闭) !== 开) 坏的.push(`${闭} 反查得到 ${开括号(闭)}，该是 ${开}`);
  }
  if (坏的.length) throw new Error(`反表有 ${坏的.length} 条不对：${坏的.join("；")}`);
});

测("表外的字符一律给 null（不是 undefined）", () => {
  for (const 字 of ["a", "`", "[", "]", "*", "」x", "", " "]) {
    等(闭括号(字), null, `闭括号(${JSON.stringify(字)})`);
    等(开括号(字), null, `开括号(${JSON.stringify(字)})`);
    等(是开括号(字), false, `是开括号(${JSON.stringify(字)})`);
    等(是闭括号(字), false, `是闭括号(${JSON.stringify(字)})`);
  }
});

测("是多字符的整串不算（`（）` 那种两字符串）", () => {
  // ⚠️ 判据吃的是**一颗**字符；整串进来必须落空，不能把首字符挑出来。
  等(是开括号("（)"), false, "两字符串");
});

/* ── 二、收哪些、不收哪些（文件头第 2 节的可执行版）──────────────────── */

组("二、该收的收了、不该收的没收");

测("该收的：`(` `{` 与中文那一族", () => {
  for (const [开, 闭] of [
    ["(", ")"],
    ["{", "}"],
    ["（", "）"],
    ["【", "】"],
    ["「", "」"],
    ["『", "』"],
    ["《", "》"],
    ["〈", "〉"],
  ]) {
    等(闭括号(开 as string), 闭, `${开}配${闭}`);
  }
});

测("⚠️ 不收 `[`：Markdown 链接 `[文字](地址)` 会被弄坏", () => {
  // 文件头第 2 节第一条。这条断言是**给改表的人看的**：想加 `[` 之前，
  // 先回答"`](` 那颗闭方括号落在地址前面怎么办"。
  等(配对表["["], undefined, "`[` 不在表里");
  等(是闭括号("]"), false, "`]` 也不在");
});

测("⚠️ 不收直引号：智能标点管着它们", () => {
  // `smart-punctuation.ts` 的输入规则按前一个字符决定弯成 `“` 还是 `”`。
  // 这里再补一颗 = 同一颗按键两套规则。
  for (const 字 of ['"', "'", "“", "”", "‘", "’"]) {
    等(是开括号(字), false, `${字} 不该在表里`);
    等(是闭括号(字), false, `${字} 不该在闭表里`);
  }
});

测("⚠️ 不收反引号：收了 `inlineCode` 就永远标不出来", () => {
  等(是开括号("`"), false, "反引号不在表里");
  等(是闭括号("`"), false, "闭表里也没有");
});

测("⚠️ 不收 Markdown 标记字符", () => {
  for (const 字 of ["*", "_", "~", "=", "#", ">", "|"]) {
    等(是开括号(字), false, `${字} 不该在表里`);
  }
});

/* ── 三、要配对 ─────────────────────────────────────────────────────── */

组("三、要配对");

测("正文里打 `(`：补 `)`", () => {
  等(要配对(场(), "("), ")", "空行打左括号");
  等(要配对(场({ 前: "甲" }), "("), ")", "字后面打");
});

测("⚠️ 代码块 / 行内代码里不补", () => {
  等(要配对(场({ 代码: true }), "("), null, "代码里");
});

测("⚠️ 前面紧挨着反斜杠不补（用户在转义）", () => {
  等(要配对(场({ 前: "\\" }), "("), null, "转义");
  等(要配对(场({ 前: "甲" }), "("), ")", "隔着一颗别的字照补");
});

测("⚠️ 右边已经就是那颗闭括号、又没选东西：不补（否则成 `())`）", () => {
  等(要配对(场({ 后: ")" }), "("), null, "光标在 `)` 前面");
  等(要配对(场({ 后: "】" }), "【"), null, "全角同理");
  等(要配对(场({ 后: "]" }), "("), ")", "右边是别的闭括号，照补");
});

测("⚠️ 选中东西时右边那颗闭括号**正**是我们要的：照补（包起来）", () => {
  等(要配对(场({ 后: ")", 空选区: false }), "("), ")", "有选区");
});

测("表外字符一个都不补", () => {
  for (const 字 of ["a", "]", "*", "「」"]) {
    等(要配对(场(), 字), null, `打 ${字}`);
  }
});

/* ── 四、跳过 / 删成对 / 跳 ─────────────────────────────────────────── */

组("四、跳过（打闭括号时右边正好有一颗一样的）");

测("右边是同一颗：跳", () => {
  等(要跳过(场({ 后: ")" }), ")"), true, "`)`");
  等(要跳过(场({ 后: "）" }), "）"), true, "全角");
});

测("右边是**别的**闭括号：不跳（要老老实实插进去）", () => {
  // ⚠️ 这条是"括号嵌套"的正解：`([])` 里光标在 `[` 后面打 `]`，
  // 右边是 `)`，必须插进去（成 `[]` ），跳过去就把 `)` 当 `]` 用了。
  等(要跳过(场({ 后: ")" }), "]"), false, "`]` 对上 `)`");
  等(要跳过(场({ 后: ")" }), "("), false, "开括号不跳");
});

测("有选区时一律不跳", () => {
  等(要跳过(场({ 后: ")", 空选区: false }), ")"), false, "选中了一段");
});

组("五、删成对（光标夹在一对空括号中间按退格）");

测("夹在一对**空**的中间：两颗一起删", () => {
  等(要删成对(场({ 前: "(", 后: ")" })), true, "`()` 中间");
  等(要删成对(场({ 前: "「", 后: "」" })), true, "全角");
});

测("中间有字（前一颗不是开括号）：只删一颗", () => {
  等(要删成对(场({ 前: "甲", 后: ")" })), false, "`甲)`");
  等(要删成对(场({ 前: "(", 后: "甲" })), false, "`(甲`");
});

测("配不上的那一对：不删", () => {
  // ⚠️ **只看相邻两颗**，不回头找配对（那要扫一遍文档，而"就近"才是手感）。
  等(要删成对(场({ 前: "(", 后: "]" })), false, "`(]`");
});

测("有选区时不删", () => {
  等(要删成对(场({ 前: "(", 后: ")", 空选区: false })), false, "选中了一段");
});

组("六、跳（Tab 跳出右半边 / Shift+Tab 跳回左半边）");

测("`Tab`：右边紧挨着闭括号就跳", () => {
  等(要跳(场({ 后: ")" }), 1), true, "`)`");
  等(要跳(场({ 后: "a" }), 1), false, "普通字符");
  等(要跳(场({ 后: "" }), 1), false, "行尾");
});

测("`Shift+Tab`：左边紧挨着开括号就跳", () => {
  等(要跳(场({ 前: "(" }), -1), true, "`(`");
  等(要跳(场({ 前: "a" }), -1), false, "普通字符");
  等(要跳(场({ 前: "" }), -1), false, "行首");
});

测("错开的方向不跳（右半边只认闭括号、左半边只认开括号）", () => {
  等(要跳(场({ 后: "(" }), 1), false, "右边是开括号");
  等(要跳(场({ 前: ")" }), -1), false, "左边是闭括号");
});

测("⚠️ 代码块 / 行内代码里不跳（那颗 `Tab` 留给缩进）", () => {
  等(要跳(场({ 后: ")", 代码: true }), 1), false, "代码里 Tab");
  等(要跳(场({ 前: "(", 代码: true }), -1), false, "代码里 Shift+Tab");
});

测("有选区时不跳", () => {
  等(要跳(场({ 后: ")", 空选区: false }), 1), false, "选中了一段");
});

/* ── 七、装配 ───────────────────────────────────────────────────────── */

组("七、装配");

测("`配对处理()` 给出一个非空的插件描述", () => {
  // ⚠️ 只能验到这一步：`$prose` 那一层要真 `Editor.make()` 才会把工厂跑起来
  //（那时才建 `Plugin` 实例）。这条断言的用处是**防"忘了 return"**那种死法。
  const 挂 = 配对处理() as unknown;
  if (挂 === null || 挂 === undefined) throw new Error("配对处理() 返回了空");
});

/* ── 收尾 ─────────────────────────────────────────────────────────────── */

console.log(`\n${"─".repeat(64)}`);
console.log(`通过 ${过} 条，失败 ${败} 条`);
if (败) {
  console.log(`失败的：\n  - ${败的.join("\n  - ")}`);
  process.exitCode = 1;
}
