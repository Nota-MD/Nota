/* ── 一支极小的测试工装（与 `auto-correct.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 逐颗比一串字符串（`等` 是 `!==`，内容一样的两串数组在它眼里永远不相等）。 */
function 等列(实际: readonly string[], 期望: readonly string[], 说明: string): void {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a !== b) throw new Error(`${说明}：期望 ${b}，实际 ${a}`);
}

/** 造一份现场，只写要变的那几格。默认：行首、行尾、正文、没选东西。 */
function 场(部分: Partial<现场> = {}): 现场 {
  return {
    前: "", 后: "", 后二: "", 代码: false, 代码块: false, 空选区: true,
    前是段首: false, 前文: "",
    ...部分,
  };
}

/* ── 一、两张表 ─────────────────────────────────────────────────────── */

组("一、两张表（防死行）");

测("`配对表` 里每一条都能被 `闭括号` 查出来", () => {
  const 坏的: string[] = [];
  for (const [开, 闭] of Object.entries(配对表)) {
    if (闭括号(开) !== 闭) 坏的.push(`${开} → ${闭}（实际 ${闭括号(开)}）`);
  }
  if (坏的.length) throw new Error(`有 ${坏的.length} 条不生效：${坏的.join("、")}`);
});

测("反表与正表严格互逆（左右一一对应）", () => {
  // ⚠️ 这一条是**这份文件里最要紧的断言**：`开括号` 与 `闭括号` 要是对不上，
  // 症状是"跳得进去跳不出来"这类莫名其妙的手感问题。
  const 坏的: string[] = [];
  for (const [开, 闭] of Object.entries(配对表)) {
    if (开括号(闭) !== 开) 坏的.push(`${闭} 反查得到 ${开括号(闭)}，该是 ${开}`);
  }
  if (坏的.length) throw new Error(`反表有 ${坏的.length} 条不对：${坏的.join("；")}`);
});

测("表外的字符一律给 null（不是 undefined）", () => {
  // ⚠️ 这份名单里**曾经有 `[` 与 `]`**——2026-09-28 起两颗都在表里了（第七组），
  // 于是换成了别的真·表外字符。加字符进表时，这里和第七组要一起动。
  for (const 字 of ["a", "`", "#", "-", "*", "」x", "", " "]) {
    等(闭括号(字), null, `闭括号(${JSON.stringify(字)})`);
    等(开括号(字), null, `开括号(${JSON.stringify(字)})`);
    等(是开括号(字), false, `是开括号(${JSON.stringify(字)})`);
    等(是闭括号(字), false, `是闭括号(${JSON.stringify(字)})`);
  }
});

测("是多字符的整串不算（`（）` 那种两字符串）", () => {
  // ⚠️ 判据吃的是**一颗**字符；整串进来必须落空，不能把首字符挑出来。
  等(是开括号("（)"), false, "两字符串");
});

/* ── 二、收哪些、不收哪些（文件头第 2 节的可执行版）──────────────────── */

组("二、该收的收了、不该收的没收");

测("该收的：`(` `{` `[` 与中文那一族", () => {
  for (const [开, 闭] of [
    ["(", ")"],
    ["{", "}"],
    ["[", "]"],
    ["（", "）"],
    ["【", "】"],
    ["「", "」"],
    ["『", "』"],
    ["《", "》"],
    ["〈", "〉"],
  ]) {
    等(闭括号(开 as string), 闭, `${开}配${闭}`);
  }
});

测("⚠️ `[` 2026-09-28 起**在表里**了（用户点名，文件头第 2.2 节）", () => {
  // ⚠️ 这一条**原来是反的**（`等(配对表["["], undefined)`，"不收"）。用户
  // 2026-09-28 原话：「自动补全 `*`、`[` 这种在设置中搞一个选项」——点的是
  // 这颗字符本身。当年挡它的理由（`[文字](地址)` 会被弄坏）靠三件事压住，
  // 逐条写在 `auto-pair.ts` 第 2.2 节；能打通的证据就是下面第七组。
  等(配对表["["], "]", "`[` 在表里，配 `]`");
  等(是开括号("["), true, "`[` 是开括号");
  等(是闭括号("]"), true, "`]` 是闭括号");
});

测("⚠️ 不收直引号：智能标点管着它们", () => {
  // `smart-punctuation.ts` 的输入规则按前一个字符决定弯成 `“` 还是 `”`。
  // 这里再补一颗 = 同一颗按键两套规则。
  for (const 字 of ['"', "'", "“", "”", "‘", "’"]) {
    等(是开括号(字), false, `${字} 不该在表里`);
    等(是闭括号(字), false, `${字} 不该在闭表里`);
  }
});

测("⚠️ 反引号不进括号表；它由自配对逻辑直接落成行内代码", () => {
  等(是开括号("`"), false, "反引号不在表里");
  等(是闭括号("`"), false, "闭表里也没有");
});

测("⚠️ 括号表不收 Markdown 标记字符（它们走自配对表）", () => {
  // ⚠️ `*` 在这条断言里仍然为假：它**没有**进 `配对表`，进的是 `自配对表`
  // （第 2.1 节）。这条留着是为了别让后来的人"顺手把它也加进配对表"——
  // 那会同时放开 `要跳过` / `要删成对` / `要跳` 三条对它的规则，而那些规则
  // 在自配对字符上没说清要什么。
  for (const 字 of ["*", "_", "~", "=", "#", ">", "|"]) {
    等(是开括号(字), false, `${字} 不该在配对表里`);
  }
});

