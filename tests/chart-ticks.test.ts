/**
 * `src/ui/chart-ticks.ts`（图上的刻度）的**可运行**测试集。
 *
 * # 跑法（与 `tests/lang-icons.test.ts` 同一套：不装任何包，`esbuild` ＋ `node`）
 *
 * ```sh
 * cd <仓库>
 * npx esbuild tests/chart-ticks.test.ts --bundle --platform=node --format=esm \
 *   --outfile=/tmp/nota-chart-ticks-test/chart-ticks.test.mjs
 * node /tmp/nota-chart-ticks-test/chart-ticks.test.mjs
 * ```
 *
 * ⚠️ 这份**不读文件**，所以在哪儿跑都行（不像 `lang-icons` 那份要找仓库根）。
 *
 * # 挡的是什么
 *
 * 三件都是**看着不像坏**的坏：
 *
 * 1. **刻度上的数字是错的**——标着 100 的那条线不在它该在的位置。这是最坏的一种：
 *    图还是那张图，只是**读出来的数不对**，而没有人会去怀疑刻度。
 * 2. **插件给的坏刻度把整块图带崩**（`null`、`at` 是字符串、标签是一整句话）。
 * 3. **首末两档探出画布**（第一个标签左半边被切、最后一个右半边被切）。
 */

import { 推纵刻度, 读刻度, 格式化数 } from "../src/ui/chart-ticks";

/* ── 极小的测试工装（与 `mark-hint.test.ts` / `lang-icons.test.ts` 同一套）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/* ── 用例 ─────────────────────────────────────────────────────────────── */

组("纵轴刻度由数据推出来");

测("三档：极大在顶（at=0）、极小在底（at=1）、中间那档在 0.5", () => {
  const 刻度 = 推纵刻度([10, 40, 90]);
  // ⚠️ 方向是**顶 = 极大**：`PanelBody.tsx` 里 `纵向()` 是 `(上限 - v)/跨度`，
  //    上下界反过来的话，刻度与曲线就是镜像的——而"镜像的图"单看仍然像张图。
  等(刻度.length, 3, "该有三档");
  等(刻度[0].at, 0, "极大值在顶");
  等(刻度[0].label, "90", "顶上是极大值");
  等(刻度[1].at, 0.5, "中间那档在中线");
  等(刻度[1].label, "50", "中线是上下界的平均");
  等(刻度[2].at, 1, "极小值在底");
  等(刻度[2].label, "10", "底下是极小值");
});

测("一直平着（极大 = 极小）只给一档、摆中线", () => {
  // 给三档的话上面和下面是同一个数，读起来像"上下差着什么"。
  const 刻度 = 推纵刻度([7, 7, 7]);
  等(刻度.length, 1, "只该有一档");
  等(刻度[0].at, 0.5, "摆在中线");
  等(刻度[0].label, "7", "写的就是那个值");
});

测("空数组没有刻度（不是给一排 0）", () => {
  等(推纵刻度([]).length, 0, "没有点就没有纵轴刻度");
});

测("负值、小数都正常", () => {
  const 刻度 = 推纵刻度([-2.5, 1.5]);
  等(刻度[0].label, "1.5", "顶上是 1.5");
  等(刻度[2].label, "-2.5", "底下是 -2.5");
  // 中线是 (-2.5+1.5)/2 = -0.5。⚠️ 它**不是**数据里的点，是坐标轴上的位置——
  // 刻度线本来就该这么标（标成某个数据的值才是错的）。
  等(刻度[1].label, "-0.5", "中线是两头的平均");
});

测("⚠️ 中线上那档的数经得起十倍错（回归：109.5 曾经写成 11）", () => {
  // 极大 200、极小 19 → 中线 (200+19)/2 = 109.5。这一段**不是编的**：
  // 面板上任何一段"峰值 200、谷值 19"的曲线都会走到这一支。
  const 刻度 = 推纵刻度([19, 200]);
  等(刻度[1].label, "110", "中线写成 110");
});

组("插件给的横轴刻度");

测("正常的一份：按位置排好、夹在 0~1", () => {
  const 刻度 = 读刻度([
    { at: 1, label: "现在" },
    { at: 1 / 3, label: "-2 分" },
    { at: 0, label: "-3 分" },
  ]);
  等(刻度.length, 3, "三档都在");
  等(刻度[0].label, "-3 分", "最左那档排在最前");
  等(刻度[2].label, "现在", "最右那档排在最后");

  // 越界的位置夹回来：跑到画布外面的刻度是看不见的，而"看不见"比"越界"难查。
  const 越界 = 读刻度([
    { at: -3, label: "太左" },
    { at: 9, label: "太右" },
  ]);
  等(越界[0].at, 0, "负数夹到 0");
  等(越界[1].at, 1, "大于 1 夹到 1");
});

测("坏项丢掉、好项照画（不整块不画）", () => {
  const 刻度 = 读刻度([
    { at: 0.5, label: "好" },
    null,
    "不是对象",
    { at: "左边", label: "at 不是数" },
    { at: Number.NaN, label: "NaN" },
    { at: Number.POSITIVE_INFINITY, label: "无穷" },
    { at: 0.2 },
    { at: 0.3, label: "   " },
    { at: 0.4, label: 42 },
  ]);
  等(刻度.length, 1, "只该剩下那一条好的");
  等(刻度[0].label, "好", "剩下的就是它");
});

测("非数组、缺字段一律当没有刻度", () => {
  for (const 坏 of [undefined, null, "x", 3, {}, [1, 2]]) {
    等(读刻度(坏).length, 0, `${JSON.stringify(坏)} 该当成没有刻度`);
  }
});

测("一档标签写成一整句话会被截短，档数也有上限", () => {
  const 长句 = 读刻度([{ at: 0.5, label: "这是".repeat(30) }]);
  断言(长句[0].label.length <= 12, `标签该被截到 12 个字以内，实际 ${长句[0].label.length}`);

  const 一堆 = 读刻度(
    Array.from({ length: 30 }, (_, i) => ({ at: i / 29, label: `t${i}` })),
  );
  等(一堆.length, 8, "最多认 8 档（再多就是一排糊字）");
});

测("⚠️ 大单位那个标记**只在恰好是 true** 时留下", () => {
  // 用户 2026-09-27：「时间应该以分钟为单位，而到小时就用稍微大一点的字体标出来
  // 是几小时」。插件标"这一档是大单位"，字号是多少由渲染层定——所以这里透传的
  // 是一个**真假值**，不是一个字号。
  const 刻度 = 读刻度([
    { at: 0, label: "开始" },
    { at: 0.5, label: "1 小时", 大单位: true },
    { at: 1, label: "2 小时", 大单位: false },
  ]);
  等(刻度[1].大单位, true, "标了大单位的那档");
  // ⚠️ `false` 与"没写"是同一件事。多留一个 `大单位: false` 的键，快照/目检里
  // 那串 JSON 会凭白长一截，而行为一模一样（与"按位置排"同一条理由）。
  等("大单位" in 刻度[0]!, false, "没写这个字段的档不该多出键来");
  等("大单位" in 刻度[2]!, false, "写了 false 的档也不该多出键来");
  // 不是 `true` 的杂值一律当没写（插件是 Lua，什么都送得出来）。
  for (const 杂 of [1, "true", {}, null]) {
    const 一 = 读刻度([{ at: 0.5, label: "x", 大单位: 杂 }]);
    等("大单位" in 一[0]!, false, `大单位 = ${JSON.stringify(杂)} 该当没写`);
  }
});

组("数字怎么写");

测("整数原样、小数按量级定小数位、末尾的零去掉", () => {
  等(格式化数(0), "0", "零");
  等(格式化数(-0), "0", "负零也写成零");
  等(格式化数(124), "124", "整数");
  等(格式化数(-12), "-12", "负整数");
  等(格式化数(12.34), "12.3", "两位数只要一位小数");
  等(格式化数(123.4), "123", "三位数不要小数");
  等(格式化数(1.25), "1.25", "个位数保留两位");
  等(格式化数(0.001), "0", "小到看不见就是 0（不是 0.00）");
  等(格式化数(Number.NaN), "", "NaN 写不出字");
});

测("⚠️ 百位以上不留小数时，**不许把整数末尾的零也去掉**（2026-09-27 修）", () => {
  // 这条曾经是坏的：`(109.5).toFixed(0)` 是 `"110"`，而那条"去尾零"的正则
  // （`\.?0+$`）在没有小数部分时去掉的正是**整数末尾的零** → `"11"`。
  // 后果不是"字写得难看"，是**刻度上的数差十倍**：一条标着 11 的线其实在 110，
  // 而图还是那张图，没有人会去怀疑刻度。
  等(格式化数(109.5), "110", "109.5 该写成 110");
  等(格式化数(100.04), "100", "100.04 该写成 100");
  等(格式化数(1000.2), "1000", "1000.2 该写成 1000");
  等(格式化数(-120.4), "-120", "负号那一侧同样");
});

/* ── 收尾 ─────────────────────────────────────────────────────────────── */

console.log(`\n${"─".repeat(64)}`);
console.log(`通过 ${过} 条，失败 ${败} 条`);
if (败) {
  console.log(`失败的：\n  - ${败的.join("\n  - ")}`);
  process.exitCode = 1;
}
