/**
 * `src/editor/code-block-cm.ts` 里那**几个纯函数**的判据
 * （backlog 第 101 项：代码块换成 CodeMirror 之后的编辑手感；
 * 第五组是 2026-10-07 补的空选区复制/剪切）。
 *
 * 跑法（不装任何包，`esbuild` 与 `node` 仓库里都现成）：
 *
 * ```sh
 * cd <仓库>
 * npx esbuild tests/code-block-editing.test.ts --bundle --platform=node --format=esm \
 *   --outfile=/tmp/nota-code-block-editing/code-block-editing.test.mjs
 * node /tmp/nota-code-block-editing/code-block-editing.test.mjs
 * ```
 *
 * # 为什么只测这三件
 *
 * 手感类的东西（配对、`Tab`、光标跳不跳）**只能开窗量**，这一份不假装能证。
 * 但下面这三件是**纯字符串算术**，而它们各自的边界条件正好是"错了也不会响、
 * 只会偶尔出一个怪字符"的那一类：
 *
 * - `算最小改动`：改动的起止**不许切在半个字符中间**（`"😀"` → `"😁"` 这种
 *   两版的高位码元相同，逐码元比就正好停在中间）。
 * - `分色`：区间要**拼回原文**（少一个字符就是高亮与文字错位一格，
 *   而且在深色主题下未必看得出来）。
 * - `回车续行`：缩进、再进一级、空括号展开三档的**光标落点**。
 * - `行界` / `整行剪贴`：空选区按复制/剪切拿走的是哪一段——**那个换行符带不带**
 *   是这一族唯一的难点（见第五组）。
 *
 * ⚠️ 它证明不了的（一律算未验）：CodeMirror 真的有没有装上、
 * 配对真的有没有发生、与 ProseMirror 的双向同步会不会抖。那些是开窗目检。
 */

import { 分色, 回车续行, 算最小改动, 整行剪贴, 行界 } from "../src/editor/code-block-cm";

/* ── 工装（与 `hints.test.ts` 同一套长相）────────────────────────────── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

/**
 * 相等断言。⚠️ 对象走 `JSON` 比：`{入, 出}` / `{from, to}` 那一族是**每次新建**
 * 的普通对象，用 `===` 的话每条都是红的，而报错信息里两边打印出来一模一样。
 */
function 等(实际: unknown, 期望: unknown, 说明: string): void {
  const 一样 =
    实际 !== null && typeof 实际 === "object"
      ? JSON.stringify(实际) === JSON.stringify(期望)
      : 实际 === 期望;
  if (!一样) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

function 真(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

/** 照 `算最小改动` 的结果把旧文变成新文——**这一条是所有用例的总判据**。 */
function 重放(旧文: string, 新文: string): string {
  const { 删起, 删到, 插入 } = 算最小改动(旧文, 新文);
  return 旧文.slice(0, 删起) + 插入 + 旧文.slice(删到);
}

/* ── 用例 ─────────────────────────────────────────────────────────────── */

组("一、算最小改动：朴素的四种");

测("两版一样 → 空改动（删起＝删到＝长度）", () => {
  const r = 算最小改动("abc", "abc");
  等(r.删起, 3, "删起");
  等(r.删到, 3, "删到");
  等(r.插入, "", "插入");
});

测("尾巴上加字", () => {
  const r = 算最小改动("ab", "abc");
  等(r.删起, 2, "删起");
  等(r.删到, 2, "删到");
  等(r.插入, "c", "插入");
});

测("中间换一个字", () => {
  const r = 算最小改动("abc", "aXc");
  等(r.删起, 1, "删起");
  等(r.删到, 2, "删到");
  等(r.插入, "X", "插入");
});

测("整段换掉", () => {
  const r = 算最小改动("abc", "xyz");
  等(r.删起, 0, "删起");
  等(r.删到, 3, "删到");
  等(r.插入, "xyz", "插入");
});

测("空 ↔ 非空", () => {
  const 加 = 算最小改动("", "x");
  等(加.删起, 0, "加：删起");
  等(加.删到, 0, "加：删到");
  等(加.插入, "x", "加：插入");

  const 减 = 算最小改动("x", "");
  等(减.删起, 0, "减：删起");
  等(减.删到, 1, "减：删到");
  等(减.插入, "", "减：插入");
});

组("二、算最小改动：字符边界（**错了只会偶尔出一个怪字**）");

测("换一个 emoji：不许切在高低位中间", () => {
  const r = 算最小改动("😀", "😁");
  等(r.删起, 0, "删起（要退到完整字符上）");
  等(r.删到, 2, "删到（两码元一起换）");
  等(r.插入, "😁", "插入");
});

测("同一个 emoji 后面再加一个：前缀停在中间也要退回来", () => {
  // ⚠️ 这一格的**前缀会一路走到第 2 个码元**（两个 emoji 的高低位都一样），
  // 真正断在第 3 个码元（`B` vs 第二个 emoji 的高位）——所以起点 2 是
  // **两边都合法的字符边界**（第一个 emoji 之后），改动是"在那儿插一个 emoji"。
  // 判据落在两个地方：重放要回新文、插入的那一段必须是一个**完整**的 emoji。
  等(重放("😀B", "😀😀B"), "😀😀B", "重放");
  const r = 算最小改动("😀B", "😀😀B");
  等(r.删起, 2, "删起（第一个 emoji 之后，两边都合法）");
  等(r.删到, 2, "删到（不删任何东西）");
  等(r.插入, "😀", "插入");
});

测("末尾同一个 emoji 再补一个", () => {
  等(重放("a😀", "a😀😀"), "a😀😀", "重放");
  const r = 算最小改动("a😀", "a😀😀");
  等(r.删起, 3, "删起");
  等(r.删到, 3, "删到");
  等(r.插入, "😀", "插入");
});

测("穷举一批配对：重放都要回到新文，且**不许剩下半个字符**", () => {
  const 单 = ["a", "b", "\n", " ", "😀", "😁", "你", "好"];
  const 样本: string[] = ["", "a", "ab", "😀", "😀B", "你 好", "a\nb", "😀😀"];
  for (const x of 单) for (const y of 单) 样本.push(x + y);
  for (const 旧文 of 样本) {
    for (const 新文 of 样本) {
      const 得 = 重放(旧文, 新文);
      等(得, 新文, `重放 ${JSON.stringify(旧文)} → ${JSON.stringify(新文)}`);
      // 孤立的代理码元（切在半个字符上）→ 就说明边界退得不对。
      for (let i = 0; i < 得.length; i++) {
        const c = 得.charCodeAt(i);
        const 是高位 = c >= 0xd800 && c <= 0xdbff;
        const 是低位 = c >= 0xdc00 && c <= 0xdfff;
        if (!是高位 && !是低位) continue;
        const 配 = 是高位 ? 得.charCodeAt(i + 1) : 得.charCodeAt(i - 1);
        真(
          (是高位 && 配 >= 0xdc00 && 配 <= 0xdfff) ||
            (是低位 && 配 >= 0xd800 && 配 <= 0xdbff),
          `结果里有孤立的代理码元：${JSON.stringify(得)} @${i}`,
        );
      }
    }
  }
});

组("三、分色：区间要能拼回原文");

测("空文、没给语言、不认识的语言 → 一个区间都没有（且不抛）", () => {
  等(分色("", "javascript").length, 0, "空文");
  等(分色("const a = 1", "").length, 0, "没给语言");
  等(分色("const a = 1", "这门语言不存在").length, 0, "不认识的语言");
});

测("javascript：区间拼回去要逐字等于原文", () => {
  const 文 = "const a = 1; // 注释\nfunction f(x) { return \"s\"; }";
  const 区间 = 分色(文, "javascript");
  真(区间.length > 0, "至少要分出几个区间来");
  let 拼 = "";
  let 上到 = 0;
  for (const 块 of 区间) {
    真(块.从 >= 上到, `区间不许重叠/倒序：${JSON.stringify(块)} 跟在 ${上到} 后面`);
    拼 += 文.slice(上到, 块.从);
    拼 += 文.slice(块.从, 块.到);
    上到 = 块.到;
  }
  拼 += 文.slice(上到);
  等(拼, 文, "拼回去");
});

测("类名是 prism 那一套（`token` 打头），CSS 才认得", () => {
  const 区间 = 分色("const a = 1", "javascript");
  for (const 块 of 区间) 真(/(^| )token( |$)/.test(块.类), `类名不认识：${块.类}`);
});

测("截断的代码也不许抛", () => {
  等(Array.isArray(分色("{", "json")), true, "半个对象");
  等(Array.isArray(分色("def f(:", "python")), true, "半截函数头");
});

组("四、回车续行：缩进 / 再进一级 / 空括号展开");

测("上一行没有缩进 → 新行也没有", () => {
  const r = 回车续行("abc", "", "    ");
  等(r.插入, "\n", "插入");
  等(r.光标, 1, "光标");
  等(r.删多少, 0, "删多少");
});

测("延续上一行的缩进", () => {
  const r = 回车续行("    abc", "", "    ");
  等(r.插入, "\n    ", "插入");
  等(r.光标, 5, "光标");
});

测("上一行以 `{` / `(` / `[` 结尾 → 再进一级", () => {
  for (const 开 of ["{", "(", "["]) {
    const r = 回车续行(`    if x ${开}`, "", "    ");
    等(r.插入, "\n        ", `${开}：插入`);
    等(r.光标, 9, `${开}：光标`);
  }
});

测("上一行以别的字符结尾 → **不**多进一级（`a +` 这种）", () => {
  const r = 回车续行("    let x = a +", "", "    ");
  等(r.插入, "\n    ", "插入");
});

测("光标正好夹在一对空括号中间 → 展开成三行", () => {
  const r = 回车续行("  f(", ")", "    ");
  等(r.插入, "\n      \n  ", "插入（中间那行再进一级）");
  等(r.光标, 7, "光标（落在中间那一行）");
});

测("后括号前面有空白也算夹在中间", () => {
  const r = 回车续行("f(", "   )", "    ");
  等(r.插入, "\n    \n", "插入");
});

测("括号不配对就不展开（`f(` 后面跟的是别的字）", () => {
  const r = 回车续行("  f(", "x", "    ");
  等(r.插入, "\n      ", "插入（还是进了那一级，但不展开）");
});

测("停在纯空白后面 → 那截空白并进新行（上一行不留尾随空白）", () => {
  const r = 回车续行("    ", "", "    ");
  等(r.删多少, 4, "删多少（把旧行那截空白删掉）");
  等(r.插入, "\n    ", "插入");
  等(r.光标, 5, "光标");
});

/* ── 五、行界 / 整行剪贴（空选区按复制/剪切）──────────────────────────── */

组("五、行界：一行的边界（不含换行符）");

const 三行 = "aa\nbb\ncc";

测("行中间的格子 → 整行，`出` 不含换行", () => {
  const { 入, 出 } = 行界(三行, 4);
  等(入, 3, "入（`bb` 的开头）");
  等(出, 5, "出（`bb` 的后面那个换行**不算**）");
  等(三行.slice(入, 出), "bb", "切出来就是这一行");
});

测("光标**正好落在换行符上** → 还是它自己那一行", () => {
  等(行界(三行, 2), { 入: 0, 出: 2 }, "`aa` 和换行之间");
});

测("⚠️ 光标贴着换行**后面**（行首）→ 算**下一行**的开头", () => {
  // `lastIndexOf` 的起点是 `位 - 1`，正好捡到光标前面那个 `\n`。反过来的话，
  // 光标停在行首按 Ctrl+C 会拿到**上面**那一行——用户完全看不懂。
  等(行界(三行, 3), { 入: 3, 出: 5 }, "`bb` 那一行");
});

测("最后一行 / 位置越界都夹回两端", () => {
  等(行界(三行, 7), { 入: 6, 出: 8 }, "最后一行");
  等(行界(三行, 999), { 入: 6, 出: 8 }, "超出长度");
  等(行界(三行, -5), { 入: 0, 出: 2 }, "负数");
});

组("五之二、整行剪贴：中间的行带换行，末尾那一行不带");

测("复制**中间**那一行 → 文本连换行一起带走（粘到别处还是一行）", () => {
  const r = 整行剪贴(三行, 4, false)!;
  真(r !== null, "该算得出来");
  等(r.文本, "bb\n", "带走的那一段");
  等(r.删, null, "复制不删东西");
  等(r.光标, 3, "什么都不做时光标不动（这里给的是行首）");
});

测("复制**末尾**那一行 → 不带换行（凭空补一个会让粘贴处多出空行）", () => {
  等(整行剪贴(三行, 7, false)!.文本, "cc", "最后一行没有换行可带");
});

测("剪切中间那一行 → 连它后面那个换行一起删", () => {
  const r = 整行剪贴(三行, 4, true)!;
  等(r.文本, "bb\n", "复制走的那一段");
  等(r.删, { from: 3, to: 6 }, "删 `bb` ＋ 它后面的换行");
  等(三行.slice(0, r.删!.from) + 三行.slice(r.删!.to), "aa\ncc", "删完剩两行");
  等(r.光标, 3, "光标落在原来那一行的行首");
});

测("⚠️ 剪切**末尾**那一行 → 删的是它**前面**那个换行（否则留下一个空行）", () => {
  const r = 整行剪贴(三行, 7, true)!;
  等(r.删, { from: 5, to: 8 }, "`\\ncc` 整段");
  等(三行.slice(0, r.删!.from) + 三行.slice(r.删!.to), "aa\nbb", "末尾不留空行");
  等(r.光标, 5, "光标接到 `bb` 后面");
});

测("只有一段的文档：剪切时没有「前面那个换行」，删它自己", () => {
  const r = 整行剪贴("xyz", 1, true)!;
  等(r.删, { from: 0, to: 3 }, "整段");
  等(r.光标, 0, "光标回到开头");
});

测("空文 → null（交回 CodeMirror 自己那份默认行为）", () => {
  等(整行剪贴("", 0, false), null, "空文");
});

