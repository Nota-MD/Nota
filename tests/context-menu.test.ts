/* ── 一支极小的测试工装（与 `bar-close.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

function 真(条件: boolean, 说明: string): void {
  if (!条件) throw new Error(说明);
}

/** 读 `src/` 下的一份源码。⚠️ 路径一律从仓库根算（跑法里 `cd` 到仓库根）。 */
function 读(...段: string[]): string {
  return readFileSync(join("src", ...段), "utf8");
}

/** 一份菜单里**点得动**的那些 id：图标行的每一颗 ＋ 普通条目；子菜单父项不进去。 */
function 点得动的(行们: readonly 行[]): string[] {
  const 收: string[] = [];
  for (const r of 行们) {
    if (r.kind === "icons") 收.push(...r.ids);
    else if (r.kind === "item") {
      if (r.spec.submenu) {
        for (const e of r.spec.submenu) if (isMenuItem(e)) 收.push(e.id);
      } else 收.push(r.spec.id);
    }
  }
  return 收;
}

/** 一份菜单里那些**只展开子菜单、自己不执行**的父项 id。 */
function 点不动的(行们: readonly 行[] = 给行("编辑器", true)): string[] {
  return 行们
    .filter((r) => r.kind === "item" && Boolean(r.spec.submenu))
    .map((r) => (r as Extract<行, { kind: "item" }>).spec.id);
}

