测("外壳 → 什么都不画（用户 2026-10-04 选的「只拦不弹」）", () => {
  等(给行("外壳", true).length, 0, "外壳那一档");
  等(给行("外壳", false).length, 0, "外壳那一档（正式构建）");
});

测("不弹 → 同样什么都不画（这一档由 TabBar 自己画）", () => {
  等(给行("不弹", true).length, 0, "不弹那一档");
});

测("输入框 → 短菜单，且**不含**任何一行图标", () => {
  const 行们 = 给行("输入框", true);
  真(行们.length > 0, "输入框那一档是空的");
  真(
    行们.every((r) => r.kind !== "icons"),
    "输入框那一档里出现了图标行——那一档是纯文字条目",
  );
  const 真条目 = 行们.filter((r) => r.kind === "item").length;
  等(真条目, 输入框条目.filter((id) => id !== "sep").length, "条目条数");
});

测("编辑器 → 三排图标 ＋ 两个子菜单父项", () => {
  const 行们 = 给行("编辑器", false);
  const 排 = 行们.filter((r) => r.kind === "icons");
  等(排.length, 3, "图标排数");
  真(
    行们.some((r) => r.kind === "item" && r.spec.id === "ctx.paragraph"),
    "少了「段落」那一栏",
  );
  真(行们.some((r) => r.kind === "item" && r.spec.id === "ctx.insert"), "少了「插入」那一栏");
});

测("⚠️ 开发者工具只在开发模式里出现", () => {
  const 有 = 给行("编辑器", true).some((r) => r.kind === "item" && r.spec.id === "view.devtools");
  const 无 = 给行("编辑器", false).some((r) => r.kind === "item" && r.spec.id === "view.devtools");
  真(有, "开发模式下没有「开发者工具」——被拦掉的原生菜单里有 `Inspect Element`，得留个门");
  真(!无, "正式构建里不该有「开发者工具」");
});

测("行的 key 不重复（重复了 React 只会让某一行认错身份，不报错）", () => {
  const 键 = 给行("编辑器", true).map((r) => r.key);
  等(new Set(键).size, 键.length, "`给行` 出来的 key 有重复");
});

测("`MENUS` 本身没有被右键菜单改坏（借 id 不该往表里塞东西）", () => {
  const id集 = new Set<string>();
  const 收 = (entries: readonly (typeof MENUS)[number]["items"]) => {
    for (const e of entries) {
      if (e === "sep") continue;
      id集.add(e.id);
      if (e.submenu) 收(e.submenu);
    }
  };
  for (const m of MENUS) 收(m.items);
真(!id集.has("ctx.paragraph"), "`ctx.paragraph` 混进 `MENUS` 了——它是右键菜单独有的");
  真(!id集.has("ctx.insert"), "`ctx.insert` 混进 `MENUS` 了");
});

/* ── 组十：拼写那一段（2026-10-11）──────────────────────────────────────── */

组("拼写 · 错词上右键多出来的那一段");

const 一份线索 = { 建议们: ["hello", "halo"], 加词典: "Add to dictionary", 忽略: "Ignore" };

测("建议在前、两个动作在后，id 都带 `spell.` 前缀", () => {
  const 行们 = 拼写行(一份线索);
  const 拼写条目 = 行们.filter((r) => r.kind === "spell");
  等(拼写条目.length, 4, "两条建议 ＋ 两个动作");
  const ids = 拼写条目.map((r) => (r.kind === "spell" ? r.id : ""));
  等(ids[0], `${拼写替换前缀}0`, "第一条建议的 id");
  等(ids[1], `${拼写替换前缀}1`, "第二条建议的 id");
  等(ids[2], 拼写加词典, "「加入词典」的 id");
  等(ids[3], 拼写忽略, "「忽略」的 id");
  // ⚠️ 标签**原样**（不过 `t()`）：那是从词典里查出来的真词，不是文案。
  const 标签们 = 拼写条目.map((r) => (r.kind === "spell" ? r.label : ""));
  等(标签们[0], "hello", "建议的文字要原样");
  等(标签们[2], "Add to dictionary", "动作名是调用方翻好递进来的");
});

测("⚠️ 一条建议都没有时**不画那一格空行**，但两个动作照旧在", () => {
  const 行们 = 拼写行({ ...一份线索, 建议们: [] });
  const 拼写条目 = 行们.filter((r) => r.kind === "spell");
  等(拼写条目.length, 2, "只有两个动作");
  真(
    行们[0]?.kind === "spell" && 行们[0].id === 拼写加词典,
    "没有建议时第一条就该是「加入词典」（中间多一条分隔线会画成空一格）",
  );
});

测("给行 · 错词那一段挂在**最前面**（不比剪贴那排靠后）", () => {
  const 行们 = 给行("编辑器", true, 一份线索);
  真(行们[0]?.kind === "spell", "第一行不是拼写那一段");
  const 图标行下标 = 行们.findIndex((r) => r.kind === "icons");
  const 最后拼写下标 = 行们.map((r) => r.kind).lastIndexOf("spell");
  真(最后拼写下标 < 图标行下标, "拼写那一段没有全部排在图标行前面");
});

测("给行 · 没落在错词上时一行都不多（默认参数那条路）", () => {
  const 行们 = 给行("编辑器", true);
  真(!行们.some((r) => r.kind === "spell"), "没给线索却画出了拼写那一格");
});

测("给行 · 输入框那一档不挂拼写（那里没有正文、也没有波浪线）", () => {
  // ⚠️ 编辑区里**真有输入框**（公式源码框、代码块的语言框），而它们里头的
  // 文字不属于正文——波浪线画不到那儿，"加入词典"更无从谈起。
  const 行们 = 给行("输入框", true, 一份线索);
  真(!行们.some((r) => r.kind === "spell"), "输入框那一档混进了拼写条目");
});

测("⚠️ 拼写那一段**永远不灰**（它不在 `灰名单` 里，照那份名单查会被当成灰的）", () => {
  const 满灰 = new Set(["spell.add", "spell.ignore", `${拼写替换前缀}0`]);
  // ⚠️ 只查**拼写条目**那几行：同一份里那两条分隔线是"恒灰"的
  //（`整行灰` 对 `sep` 一律给 `true`），拿它们来判会把一条永远成立的事
  // 报成缺陷。
  for (const r of 拼写行(一份线索).filter((x) => x.kind === "spell")) {
    真(!整行灰(r, 满灰), `拼写那一行被画成灰的了：${JSON.stringify(r)}`);
  }
});

测("三个动作在 `ContextMenu.tsx::落到拼写` 里都有落点（id 打错就永远点不动）", () => {
  // 这一条与组四那条同一个理由：这几条的处理器**不在命令表里**（它们的 id 是
  // 现场造的），所以"有没有人实现"只能对着那一份源码查。
  const 源 = 读("ui", "ContextMenu.tsx");
  // ⚠️ 源码里写的是**常量名**（`id === 拼写加词典`），不是那个字面量
  //（`"spell.add"` 住在 `context-menu.ts` 一处）。所以这里查的是"有没有
  // 人拿这两个常量比过"——那正是"加了一条菜单、忘了实现"的判据。
  真(源.includes("id === 拼写加词典"), "`拼写加词典` 在 `落到拼写` 里没有分支");
  真(源.includes("id === 拼写忽略"), "`拼写忽略` 在 `落到拼写` 里没有分支");
  真(源.includes("拼写替换前缀"), "没找到建议那几条认 id 的地方");
});

