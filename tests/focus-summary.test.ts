/**
 * `src/ui/focus-summary.ts`（强制专注结束后的那一轮总结）的**可运行**测试集。
 *
 * # 跑法（不装任何包：`esbuild` 与 `node` 仓库里都现成）
 *
 * ```sh
 * cd <仓库>
 * npx esbuild tests/focus-summary.test.ts --bundle --platform=node --format=esm \
 *   --alias:@=./src \
 *   --outfile=/tmp/nota-测试/focus-summary.mjs
 * node /tmp/nota-测试/focus-summary.mjs
 * ```
 *
 * ⚠️ **要 `--alias:@=./src`**：被测模块 import 了 `@/ui/useForceFocus`（借它的
 * `说时长`）。漏了那个开关的报错是 `Could not resolve "…"`，看着不像"开关没给"。
 * ⚠️ **不需要** `--loader:.svg=text`（不碰那枚 SVG）——那一份只有 `share-card`
 * 要（`docs/06` §6.3）。
 *
 * 全过退出码 0；有不过的退出码 1，并把名字列出来。
 *
 * # 这份测试是为什么写的（2026-09-27）
 *
 * 用户当天提了「记得做一下专注模式结束后的总结功能就是将这一次专注模式的情况
 * 显示出来，并且像心电图那样也支持导出」。这一块**没有任何界面能替它验**：
 * 总结框要跑满一轮 5 秒以上才弹，而里面的数字对不对、曲线画成什么样，肉眼
 * 看不出来（一条余额曲线长得都差不多）。
 *
 * 所以这里钉的三件事，每一件都是"写错了也不会报错、只会悄悄给出一个错的总结"
 * 的那种：
 *
 * 1. **`记一笔` 的"同一秒就地更新"**——错了的话曲线的横轴密度是假的，
 *    而"多密"正是这条曲线要传达的东西（见那个函数的注释）；
 * 2. **`抽稀` 取余额大的那个**——取平均或取后一个会把"扣到底"那一下磨圆，
 *    而那个尖角是这张图唯一的信息；
 * 3. **`专注率` 的分母是专注＋离开**——算进警报冻住那一段的话，用户会因为
 *    "警报响了"而被扣分，而警报恰恰是他回来过的证据。
 *
 * # 测什么、不测什么
 *
 * - 测：采样、抽稀、总结、专注率、两个时刻函数、横刻度、分享卡字段；
 * - **不测**：`useFocusTrace` 那个 hook（它要 React 运行时与宿主事件，本仓没有
 *   jsdom）。"结束时抓的是最后一份**在跑**的快照"这条**靠的是读代码**
 *   ——那份文件头里写清了为什么，而这里能验的只有它调用的那几个纯函数。
 * - **不测**：卡片画出来好不好看（那是 `share-card.ts` 的事，`share-card.test.ts`
 *   已有一套）。
 */

import {
  采样上限,
  最短总结秒,
  记一笔,
  抽稀,
  造总结,
  值得总结,
  专注率,
  说时刻,
  文件时刻,
  横刻度,
  造分享卡,
  type 采样点,
  type 总结,
} from "../src/ui/focus-summary";
import { 定语言 } from "../src/i18n";
import type { FocusState } from "../src/bridge/types";

/* ── 极小的测试工装（与前几份同一套）─────────────────────────────────── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 造一份宿主快照。给的字段覆盖默认值（默认是"正在跑、余额 25 分钟"）。 */
function 快照(改: Partial<FocusState> = {}): FocusState {
  return {
    running: true,
    balance_ms: 25 * 60 * 1000,
    cap_ms: 25 * 60 * 1000,
    phase: "focusing",
    away_ms: 0,
    grace_ms: 10_000,
    elapsed_ms: 0,
    focused_ms: 0,
    away_total_ms: 0,
    alarms: 0,
    ...改,
  };
}

/** 一秒一拍地喂 `n` 秒（余额从 `起` 开始每秒掉 1）——省得手写一串点。 */
function 喂(秒数: number, 起点?: 采样点[]): 采样点[] {
  let 出 = 起点 ?? [];
  for (let i = 1; i <= 秒数; i++) {
    出 = 记一笔(出, 快照({ elapsed_ms: i * 1000, balance_ms: (25 * 60 - i) * 1000 }));
  }
  return 出;
}

/* ── 主 ─────────────────────────────────────────────────────────────── */

function 主(): void {
  // ⚠️ **必须先定成中文**：`i18n` 的模块级初值是兜底 `"en"`（`i18n/index.ts`），
  // 不设的话下面那些断言文案的用例会拿到英文，而它们看起来会像"文案错了"。
  定语言("zh-CN");

  /* ── 1. 记一笔 ────────────────────────────────────────────────────── */
  组("记一笔");

  测("没在跑时不记（原样返回**同一个数组**，不触发重画）", () => {
    const 空: 采样点[] = [];
    const 出 = 记一笔(空, 快照({ running: false }));
    // ⚠️ 断言的是**引用相等**而不是"长度 0"：每秒一次的事件路上，返回新数组
    // 就等于每秒一次 `setState`，而这一条正是"什么都没发生"的那条路。
    断言(出 === 空, "应该是原样的那一个数组");
  });

  测("一轮结束后把序列清空（且给的是新数组）", () => {
    const 旧 = 喂(3);
    等(旧.length, 3, "先确认喂进去了");
    const 出 = 记一笔(旧, 快照({ running: false }));
    等(出.length, 0, "结束那一刻要清空");
    断言(出 !== 旧, "清空要给新数组（旧的那个还在别处被读着）");
  });

  测("正常一秒一拍：逐条追加", () => {
    const 出 = 喂(3);
    等(出.length, 3, "三拍三个点");
    等(出[0]!.秒, 1, "第一拍的秒数");
    等(出[2]!.秒, 3, "最后一拍的秒数");
    等(出[0]!.余额, 25 * 60 - 1, "余额按秒记");
  });

  测("⚠️ 同一秒来两帧：就地更新，不追加", () => {
    let 出 = 喂(1);
    出 = 记一笔(出, 快照({ elapsed_ms: 1000, balance_ms: 5 * 1000 }));
    等(出.length, 1, "还是那一个点");
    等(出[0]!.余额, 5, "余额换成后到的那一份");
  });

  测("⚠️ 秒数倒退（乱序到达）也走就地更新，不留一个错位的点", () => {
    let 出 = 喂(5);
    出 = 记一笔(出, 快照({ elapsed_ms: 3000, balance_ms: 7 * 1000 }));
    等(出.length, 5, "不追加");
    等(出[4]!.秒, 3, "末点的秒数被改写");
    等(出[4]!.余额, 7, "末点的余额被改写");
  });

  测("⚠️ 超过上限就抽稀（而不是丢掉最早那一段）", () => {
    const 出 = 喂(采样上限 + 1);
    断言(出.length <= 采样上限, `长度该收在上限内，实际 ${出.length}`);
    等(出.length, Math.ceil((采样上限 + 1) / 2), "整对整对合，长度减半");
    // ⚠️ 横轴仍然从第 1 秒起（丢最早那段的话这里会变成几秒之后）。
    等(出[0]!.秒, 1, "最早那一段还在");
  });

  /* ── 2. 抽稀 ──────────────────────────────────────────────────────── */
  组("抽稀");

  测("⚠️ 相邻两点取**余额大的**那个（保住峰）", () => {
    const 出 = 抽稀([
      { 秒: 1, 余额: 10 },
      { 秒: 2, 余额: 5 },
    ]);
    等(出.length, 1, "两点合一点");
    等(出[0]!.余额, 10, "取大的那个（取平均会磨掉峰，取后一个会取到掉下来的那个）");
  });

  测("余额升上去的那一对取后一个", () => {
    const 出 = 抽稀([
      { 秒: 1, 余额: 3 },
      { 秒: 2, 余额: 9 },
    ]);
    等(出[0]!.余额, 9, "取大的那个");
  });

  测("⚠️ 单数的尾巴原样留着（丢掉的话横轴末尾会缺一小段）", () => {
    const 出 = 抽稀([
      { 秒: 1, 余额: 3 },
      { 秒: 2, 余额: 9 },
      { 秒: 3, 余额: 4 },
    ]);
    等(出.length, 2, "合一个、留一个");
    等(出[1]!.秒, 3, "尾巴还是最后一个点");
    等(出[1]!.余额, 4, "原样");
  });

  /* ── 3. 造总结 / 值得总结 / 专注率 ────────────────────────────────── */
  组("总结与专注率");

  测("⚠️ 时长兜到至少 1 秒（它要当除法的分母）", () => {
    const 总 = 造总结(快照({ elapsed_ms: 0 }), []);
    等(总.时长秒, 1, "0 会让专注率变成 NaN");
  });

  测("负数读数被压成 0（浮点/顺序都可能让它探到负的）", () => {
    const 总 = 造总结(快照({ focused_ms: -1, away_total_ms: -1 }), []);
    等(总.专注秒, 0, "专注");
    等(总.离开秒, 0, "离开");
  });

  测("毫秒取整成年/秒（四舍五入到最近的那一秒）", () => {
    const 总 = 造总结(快照({ elapsed_ms: 1499, focused_ms: 1500 }), []);
    等(总.时长秒, 1, "1499 → 1");
    等(总.专注秒, 2, "1500 → 2");
  });

  测("采样原样带进总结（不再复制一份）", () => {
    const 点 = 喂(2);
    const 总 = 造总结(快照(), 点);
    断言(总.采样 === 点, "同一个数组");
  });

  测(`⚠️ 短于 ${最短总结秒} 秒不值得弹（点错按钮不该收到一张卡）`, () => {
    等(值得总结(造总结(快照({ elapsed_ms: 4000 }), [])), false, "4 秒");
    等(值得总结(造总结(快照({ elapsed_ms: 5000 }), [])), true, "5 秒");
  });

  测("专注率：专注÷（专注＋离开），取整到百分数", () => {
    等(专注率(造总结(快照({ focused_ms: 60_000, away_total_ms: 40_000 }), [])), 60, "60/100");
  });

  测("⚠️ 两个都是 0 时返回 null（画破折号，**不是** 0%）", () => {
    等(专注率(造总结(快照({ focused_ms: 0, away_total_ms: 0 }), [])), null, "没数");
  });

  测("⚠️ 一次都没专注、但走开过：那是 0%（不是 null）", () => {
    等(专注率(造总结(快照({ focused_ms: 0, away_total_ms: 10_000 }), [])), 0, "真的 0%");
  });

  测("⚠️ 分母**不含**警报冻住的那一段", () => {
    // 专注 100 秒、离开 0 秒，但这一轮总共 200 秒（另外 100 秒在警报里冻着）。
    const 总 = 造总结(
      快照({ elapsed_ms: 200_000, focused_ms: 100_000, away_total_ms: 0 }),
      [],
    );
    等(专注率(总), 100, "警报响着那段既不算专注也不算离开，不该拉低它");
  });

  /* ── 4. 说时刻 / 文件时刻 ────────────────────────────────────────── */
  组("两个时刻");

  const 时刻 = new Date(2026, 8, 27, 22, 7, 3);

  测("中文那一条是「2026年9月27日 22:07」（月日不补零，时分补）", () => {
    等(说时刻(时刻), "2026年9月27日 22:07", "中文格式");
  });

  测("文件名里的时刻是纯 ASCII 的 20260927-2207", () => {
    const 名 = 文件时刻(时刻);
    等(名, "20260927-2207", "形状");
    // ⚠️ 它要进文件系统：一个非 ASCII 字符就可能在某些文件系统上出问题。
    断言(/^[\x20-\x7e]+$/.test(名), "必须全是可打印 ASCII");
  });

  测("⚠️ 英文那条走的是**同一条格式串**，只是排布不同（ISO）", () => {
    定语言("en");
    try {
      等(说时刻(时刻), "2026-9-27 22:07", "英文格式");
    } finally {
      // ⚠️ 一定要还原：下面的用例里还有断言中文文案的。
      定语言("zh-CN");
    }
  });

  /* ── 5. 横刻度 ────────────────────────────────────────────────────── */
  组("横刻度");

  测("一个点（或没有点）不给刻度——摆三档等于摆三个一样的数", () => {
    等(横刻度([]).length, 0, "空序列");
    等(横刻度([{ 秒: 1, 余额: 3 }]).length, 0, "一个点");
  });

  测("两个点以上给三档：起、中、末，标签是时长不是序号", () => {
    const 刻 = 横刻度([
      { 秒: 1, 余额: 3 },
      { 秒: 30, 余额: 2 },
      { 秒: 60, 余额: 1 },
    ]);
    等(刻.length, 3, "三档");
    等(刻[0]!.at, 0, "第一档在最左");
    等(刻[1]!.at, 0.5, "第二档在正中");
    等(刻[2]!.at, 1, "第三档在最右");
    等(刻[0]!.label, "0:00", "起点");
    等(刻[1]!.label, "0:30", "中点按**末点的秒数**折半");
    等(刻[2]!.label, "1:00", "末点");
  });

  /* ── 6. 造分享卡 ──────────────────────────────────────────────────── */
  组("造分享卡");

  /** 一份"标准"总结：总共 100 秒、专注 60、离开 40、响 2 次警报。 */
  function 标准总结(): 总结 {
    return 造总结(
      快照({
        elapsed_ms: 100_000,
        focused_ms: 60_000,
        away_total_ms: 40_000,
        alarms: 2,
      }),
      喂(3),
    );
  }

  const 卡 = 造分享卡(标准总结(), 时刻);

  测("⚠️ 大数字是**专注时长**，不是这一轮的总时长（那张卡要能拿去给人看）", () => {
    等(卡.value, "1:00", "专注 60 秒");
    等(卡.label, "这一轮专注了", "大数字上面那行");
  });

  测("三格是「本轮时长 / 专注占比 / 警报」", () => {
    等(卡.stats.length, 3, "三格");
    等(卡.stats[0]!.k, "本轮时长", "第一格的名字");
    等(卡.stats[0]!.v, "1:40", "第一格的数（100 秒）");
    等(卡.stats[1]!.k, "专注占比", "第二格");
    等(卡.stats[1]!.v, "60", "60/100");
    等(卡.stats[1]!.small, "%", "第二格的单位");
    等(卡.stats[2]!.k, "警报次数", "第三格");
    等(卡.stats[2]!.v, "2", "响了两次");
    // ⚠️ 单位**不许**回到 `small` 里：它是个裸字符串，英文那边会印出
    // `Alarm 1 times`（见 `focus-summary.ts` 那一段）。这条就是拦那个的。
    等(卡.stats[2]!.small, "", "单位在抬头里，不在这一格");
  });

  测("⚠️ 三格的抬头都是四字（并列的三格，长短不一看着像没对齐）", () => {
    for (const 格 of 卡.stats) {
      等(格.k.length, 4, `${格.k} 该是四字`);
    }
  });

  测("页脚说的是**离开**了多久", () => {
    等(卡.foot, "本轮离开时长为 0:40。", "离开 40 秒");
  });

  测("副标题不过 t()（与写作统计那张卡同一个口径）", () => {
    等(卡.subtitle, "Focus Session", "英文小字");
  });

  测("时刻与文件名", () => {
    等(卡.date, "2026年9月27日 22:07", "右上角");
    等(卡.file, "nota-focus-20260927-2207.png", "默认文件名");
  });

  测("曲线是余额那一列，序号与采样一一对应", () => {
    等(卡.points.length, 3, "三个点");
    等(卡.points[0], 25 * 60 - 1, "第一拍扣掉一秒的余额");
    等(卡.shape, "curve", "这条线是折线/曲线，不是热力图");
    等(卡.heat, null, "没有热力图");
    等(卡.less, "", "曲线图没有两端图例");
    等(卡.more, "", "同上");
  });

  测("刻度跟着采样走（三个点时才有）", () => {
    等(卡.xTicks.length, 3, "三档");
    等(卡.xMinor, 0, "不画次刻度");
  });

  测("⚠️ 采样为空时兜成一条平线（一个点画不出曲线）", () => {
    const 空卡 = 造分享卡(造总结(快照({ focused_ms: 1000 }), []), 时刻);
    等(空卡.points.length, 2, "补成两个点");
    等(空卡.points[0], 0, "值是 0");
    等(空卡.points[1], 0, "两个点一样（平线）");
  });

  测("⚠️ 采样只有一个点时也兜成两个点（否则刻度与纵轴范围一起退化）", () => {
    const 一卡 = 造分享卡(
      造总结(快照({ focused_ms: 1000 }), [{ 秒: 1, 余额: 42 }]),
      时刻,
    );
    等(一卡.points.length, 2, "补成两个点");
    等(一卡.points[0], 42, "两个点的值都是那一个点");
    等(一卡.points[1], 42, "同上");
  });

  测("⚠️ 专注率为 null 时那一格**留空**，不是写一个 0", () => {
    // 专注 0、离开 0：这一格没数。大数字仍需为正（时长兜到 1 秒）。
    const 没数 = 造分享卡(造总结(快照({ elapsed_ms: 6000 }), []), 时刻);
    等(没数.stats[1]!.v, "", "空着");
    等(没数.stats[1]!.small, "", "单位也空着");
  });

  /* ── 收尾 ─────────────────────────────────────────────────────────── */

  console.log(`\n${"─".repeat(64)}`);
  console.log(`通过 ${过} 条，失败 ${败} 条`);
  if (败) {
    console.log(`失败的：\n  - ${败的.join("\n  - ")}`);
    process.exitCode = 1;
  }
}

主();
