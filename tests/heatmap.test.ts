/**
 * `src/ui/heatmap.ts`（长期记录的热力图）的**可运行**测试集。
 *
 * # 跑法（与 `tests/chart-ticks.test.ts` 同一套：不装任何包，`esbuild` ＋ `node`）
 *
 * ```sh
 * cd <仓库>
 * npx esbuild tests/heatmap.test.ts --bundle --platform=node --format=esm \
 *   --alias:@=./src \
 *   --outfile=/tmp/nota-热力图测试/heatmap.test.mjs
 * node /tmp/nota-热力图测试/heatmap.test.mjs
 * ```
 *
 * ⚠️ **`--alias:@=./src`**：2026-09-27 起这份模块要问一句"界面在说哪种语言"
 * （月份标签），那句话在 `src/i18n`，而它内部用的是 `@/…` 这种路径（Vite 的别名）。
 * ⚠️ 这份**不读文件**，所以在哪儿跑都行。
 *
 * # 挡的是什么
 *
 * 1. **格子错位**——每一格是哪一天全靠算出来的，而错的图**看着完全正常**：
 *    只是"9 月 3 号写了 1200 字"被画到了 9 月 2 号那一格上。热力图上没有数字，
 *    所以这类错误没有任何肉眼可见的症状。
 * 2. **最后一列画出了"未来"**——今天才周三，后面四格却是 0 字。那不是"没写"，
 *    那是**还没到**，两者画成一样的颜色就是在编数据。
 * 3. **时区陷阱**——`new Date("2026-09-27")` 按 **UTC** 解析，在东八区会退到
 *    前一天早上八点，整张图偏一格，而且**只在部分时区偏**（开发机上可能看不出来）。
 * 4. **插件给的坏记录把整块图带崩**（`days` 不是字符串、日期写成 `2026-9-7`、
 *    值是负数、同一天两行）。
 * 5. **月份标签没跟着语言走**——英文界面下发出「9月」，而这张图是要发出去的。
 */

import { 定语言 } from "../src/i18n";
import { 算热力, 读热力记录 } from "../src/ui/heatmap";

/* ── 极小的测试工装（与 `chart-ticks.test.ts` 同一套）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 把一张图压成 `日期=值` 的一串，方便一眼比对。 */
function 摊开(图: ReturnType<typeof 算热力>): string {
  const 出: string[] = [];
  for (const 列 of 图.列) for (const 格 of 列.格) 出.push(`${格.日}=${格.值}`);
  return 出.join(" ");
}

/* ── 读记录 ───────────────────────────────────────────────────────────── */

组("读热力记录（宿主定的那个字符串）");

测("正常的一串：空格分开，日期在前、值在后", () => {
  const r = 读热力记录("2026-09-27:1284 2026-09-26:0 2026-09-25:120");
  等(r.length, 3, "三条");
  等(r[0].日, "2026-09-27", "第一天");
  等(r[0].值, 1284, "第一天那个数");
});

测("坏项丢掉，好的照收（不因为一行坏的就整块不画）", () => {
  const r = 读热力记录("2026-09-27:1284 乱写 2026-9-7:10 2026-09-25:-3 2026-09-24:7:x");
  等(r.length, 1, "只剩一条好的");
  等(r[0].日, "2026-09-27", "留下的正是那条");
});

测("⚠️ 同一天两行：后写的赢（记账那侧本来就不该重复）", () => {
  const r = 读热力记录("2026-09-27:10 2026-09-27:20");
  等(r.length, 1, "合成一条");
  等(r[0].值, 20, "后写的那个");
});

测("不是字符串就没有记录（插件没写 days / 写成了数组）", () => {
  等(读热力记录(undefined).length, 0, "undefined");
  等(读热力记录([{ d: "2026-09-27", v: 1 }]).length, 0, "数组也不算");
});

测("值取整（0.9 字是写不出来的，那只能是算错了）", () => {
  等(读热力记录("2026-09-27:12.9")[0].值, 12, "往下取整");
});

/* ── 铺格子 ───────────────────────────────────────────────────────────── */

组("算热力：格子摆在哪");

测("一周一列、周一在头一行：2026-09-27 是周日 → 它在这一列的最后一行", () => {
  // 2026-09-27 是周日（真查过日历）。止=那天、铺 8 列（下限），
  // 所以最后一列的周一 = 09-21，周日 = 09-27。
  const 图 = 算热力([{ 日: "2026-09-27", 值: 100 }], "2026-09-27", 8);
  等(图.列.length, 8, "8 列");
  等(图.列[7].格.length, 7, "最后一列是满的（周日就是末尾那格）");
  等(图.列[7].格[6].日, "2026-09-27", "最后一行是周日");
  等(图.列[7].格[0].日, "2026-09-21", "第一行是周一");
  等(图.列[7].格[6].值, 100, "那一格的值");
  等(图.止, "2026-09-27", "窗口右端");
});

测("⚠️ 今天才周三：最后一列只画到周三，后面四格**不画**（不是画成 0）", () => {
  const 图 = 算热力([], "2026-09-23", 8); // 2026-09-23 是周三
  等(图.列[7].格.length, 3, "周一到周三，三格");
  等(图.列[7].格[2].日, "2026-09-23", "最后一格就是今天");
});

测("窗口是 8~53 列，认不出来用半年（26）", () => {
  等(算热力([], "2026-09-27", 1).列.length, 8, "太少 → 抬到 8");
  等(算热力([], "2026-09-27", 999).列.length, 53, "太多 → 压到 53");
  等(算热力([], "2026-09-27", Number.NaN).列.length, 26, "NaN → 26");
  等(算热力([], "2026-09-27", 0).列.length, 26, "0 也当没写 → 26");
});

测("跨月的窗口：起止两头都要对（8 列 = 56 天）", () => {
  const 图 = 算热力([], "2026-09-27", 8);
  等(图.起, "2026-08-03", "8 列前那个周一"); // 09-21 往前 7*7 = 49 天 → 08-03
  等(图.止, "2026-09-27", "右端还是那一天");
});

测("除了最后一列，每列都是 7 格", () => {
  const 图 = 算热力([], "2026-09-27", 12);
  for (let i = 0; i + 1 < 图.列.length; i++) 等(图.列[i].格.length, 7, `第 ${i} 列`);
});

组("算热力：三个数（最大 / 总计 / 有字天数）");

测("只数**窗口里**的那些天（窗口外的记录不掺和）", () => {
  const 图 = 算热力(
    [
      { 日: "2026-09-27", 值: 100 },
      { 日: "2026-09-26", 值: 50 },
      { 日: "2020-01-01", 值: 9999 }, // 六年前，不在窗口里
    ],
    "2026-09-27",
    8,
  );
  等(图.最大, 100, "最大值只看窗口里");
  等(图.总计, 150, "总计只看窗口里");
  等(图.天数, 2, "有字的两天");
});

测("没有记录时是一张空图（列是空的，渲染层不画）", () => {
  const 图 = 算热力([], "", 26);
  等(图.列.length, 0, "不画");
  等(图.总计, 0, "总计 0");
});

测("⚠️ 止 认不出来时退到记录里最晚的那一天（不是退到「今天」——这里根本不认识今天）", () => {
  const 图 = 算热力([{ 日: "2026-03-05", 值: 7 }], "不是日期", 8);
  等(图.止, "2026-03-05", "用记录里最晚的那天");
  等(图.总计, 7, "那一格在窗口里");
});

组("算热力：深浅四档");

测("相对这张图的最大值分档：1/4 一档", () => {
  const 图 = 算热力(
    [
      { 日: "2026-09-27", 值: 100 }, // 满档
      { 日: "2026-09-26", 值: 75 }, // 3 档（0.75 ≤ 值/最大）
      { 日: "2026-09-25", 值: 50 }, // 2 档
      { 日: "2026-09-24", 值: 25 }, // 1 档
      { 日: "2026-09-23", 值: 0 }, // 0 档（没写）
    ],
    "2026-09-27",
    8,
  );
  const 找 = (日: string) => 图.列.flatMap((c) => c.格).find((g) => g.日 === 日)!;
  等(找("2026-09-27").档, 4, "最大的一天是满档");
  等(找("2026-09-26").档, 3, "四分之三");
  等(找("2026-09-25").档, 2, "一半");
  等(找("2026-09-24").档, 1, "四分之一");
  等(找("2026-09-23").档, 0, "没写是 0 档");
});

测("一天都没写（最大 = 0）时，有字的那天也画得出颜色（档 1，不是 0）", () => {
  // 走不到：最大 > 0 才会有非零值。这条钉的是"最大 <= 0 时除零不炸"。
  const 图 = 算热力([{ 日: "2026-09-27", 值: 0 }], "2026-09-27", 8);
  等(图.最大, 0, "最大是 0");
  等(图.列.flatMap((c) => c.格).every((g) => g.档 === 0), true, "全是 0 档");
});

组("算热力：月份标签（跟着界面语言走）");

测("同一个月只标一次，标在它出现的第一列上", () => {
  定语言("zh-CN");
  const 图 = 算热力([], "2026-09-27", 8); // 08-03 ~ 09-27
  const 标签 = 图.列.map((c) => c.月);
  等(标签[0], "8月", "第一列标 8 月");
  等(标签.filter((m) => m === "8月").length, 1, "8 月只标一次");
  等(标签.includes("9月"), true, "9 月也标了");
  等(标签.filter((m) => m === "9月").length, 1, "9 月只标一次");
});

测("⚠️ 说英文时标的是 Sep（这张图要发出去，「9月」在英文界面上就是没翻译）", () => {
  定语言("en");
  const 图 = 算热力([], "2026-09-27", 8);
  const 标签 = 图.列.map((c) => c.月);
  等(标签[0], "Aug", "第一列是 Aug");
  等(标签.includes("Sep"), true, "9 月那边是 Sep");
  等(标签.includes("9月"), false, "一个中文的月份都不该剩");
  // ⚠️ `short` 才有这个区分度：`narrow` 在英文里只剩一个字母（S 与 S 撞车）。
  等(new Set(标签.filter(Boolean)).size > 1, true, "两个月的标签是能分开的两个词");
  定语言("zh-CN");
});

/* ── 时区 ─────────────────────────────────────────────────────────────── */

组("⚠️ 时区：日期一律按**本地**算");

测("`2026-09-27` 就是本地那一天，不偏格（UTC 解析在东八区会退到前一天）", () => {
  const 图 = 算热力([{ 日: "2026-09-27", 值: 5 }], "2026-09-27", 8);
  等(图.止, "2026-09-27", "止没变");
  const 那格 = 图.列.flatMap((c) => c.格).find((g) => g.值 === 5);
  断言(那格, "那一格得在图上");
  等(那格!.日, "2026-09-27", "值落在它自己那一天");
});

测("跨夏令时的那几周照样一天一格（不是加 86400 秒）", () => {
  // 2026-11-01 是多数北美时区结束夏令时的那天。窗口横跨 10 月到 11 月，
  // 格子数必须**正好等于**窗口的自然天数——按"加 86400 秒"算的话，
  // 那一天不是 24 小时，会多出一格或者少一格。
  const 图 = 算热力([], "2026-11-15", 8);
  const 格数 = 图.列.reduce((n, c) => n + c.格.length, 0);
  const 起 = 图.起.split("-").map(Number);
  const 止 = 图.止.split("-").map(Number);
  const 天数 =
    Math.round(
      (new Date(止[0], 止[1] - 1, 止[2]).getTime() -
        new Date(起[0], 起[1] - 1, 起[2]).getTime()) /
        86400000,
    ) + 1;
  等(格数, 天数, "格子数 = 窗口的自然天数");
  // 而且跨过那一天的那两格，日期要连着（中间不跳号、不重复）。
  const 前 = 图.列.flatMap((c) => c.格).find((g) => g.日 === "2026-10-31");
  断言(前, "10-31 那格在图上");
  const 后 = 图.列.flatMap((c) => c.格).find((g) => g.日 === "2026-11-01");
  断言(后, "11-01 那格也在（夏令时那天没被吃掉）");
});

测("溢出的日期当没有（`2026-02-30` 不存在）", () => {
  等(读热力记录("2026-02-30:10").length, 0, "2 月没有 30 号");
  等(读热力记录("2026-13-01:10").length, 0, "没有 13 月");
});

