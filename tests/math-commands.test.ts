/* ── 一支极小的测试工装（与 `math-input.test.ts` / `math-view.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** 比字符串数组。 */
function 等列(实际: readonly string[], 期望: readonly string[], 说明: string): void {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a !== b) throw new Error(`${说明}：期望 ${b}，实际 ${a}`);
}

/* ── 两张表 ───────────────────────────────────────────────────────────── */

const 无物理 = 建命令表(false);
const 有物理 = 建命令表(true);

/** 按命令名找一条（找不到返回 `undefined`，让调用处的断言去报）。 */
function 取(表: readonly 候选[], 命令: string): 候选 | undefined {
  return 表.find((条) => 条.命令 === 命令);
}

/** 数一个字符串里 `{}` 出现了几次。 */
function 数洞(串: string): number {
  return 串.split("{}").length - 1;
}

/* ══ 一、表本身 ════════════════════════════════════════════════════════ */

组("一、表本身（自洽、且 physics 那一档开关分明）");

测("physics 关着：一百多条，全是手写那一族，一条 `physics` 都没有", () => {
  断言(无物理.length > 100, `表太小了：${无物理.length} 条`);
  等(无物理.filter((条) => 条.族 === "physics").length, 0, "关着时不该有 physics 条");
});

测("physics 开着：多出来的**正好**是宏表那些条（一条不多一条不少）", () => {
  const 物理条 = 有物理.filter((条) => 条.族 === "physics");
  // ⚠️ `\div` 那条手写的被顶掉了，所以总条数**不是**"手写 ＋ physics"简单地一加。
  等(物理条.length, Object.keys(PHYSICS_MACROS).length, "physics 条数");
});

测("⚠️ 命令名不许重（physics 开与关都不许）——`\\div` 那条真冲突就是这么抓出来的", () => {
  for (const [哪一档, 表] of [
    ["关", 无物理],
    ["开", 有物理],
  ] as const) {
    const 见 = new Map<string, number>();
    for (const 条 of 表) 见.set(条.命令, (见.get(条.命令) ?? 0) + 1);
    const 重 = [...见.entries()].filter(([, 次]) => 次 > 1).map(([命令]) => 命令);
    等列(重, [], `${哪一档}着时重了的命令`);
  }
});

测("⚠️ `\\div` 这条冲突：physics 关着是「除号」（手写的），开着让位给 physics 那条", () => {
  const 关 = 取(无物理, "\\div");
  断言(关, "关着时该有 `\\div`");
  等(关?.族, "命令", "关着时是手写那条");
  等(关?.说明, "除号 ÷", "关着时说的是除号");

  const 开 = 有物理.filter((条) => 条.命令 === "\\div");
  等(开.length, 1, "开着时 `\\div` 只能有一条");
  等(开[0]?.族, "physics", "开着时顶上的是 physics 那条");
  // ⚠️ 这一条正是"让位"的理由：开着的时候 `\div` 在 KaTeX 眼里**已经不是除号**了
  //    （`macros` 压过内置命令），再摆一条写着"除号"的候选就是骗人。
  等(开[0]?.插入, "\\div", "physics 的 `\\div` 是零参宏（它是个算子名，不吃参数）");
});

测("每一条都填齐了：命令带反斜杠、余下全是字母、插入/样本/说明都不空", () => {
  for (const 条 of 有物理) {
    断言(条.命令.startsWith("\\"), `${条.命令} 没有反斜杠`);
    断言(/^\\[A-Za-z]+$/.test(条.命令), `${条.命令} 不是"反斜杠＋字母"`);
    断言(条.插入.length > 0, `${条.命令} 的插入是空的`);
    断言(条.样本.length > 0, `${条.命令} 的样本是空的`);
    断言(条.说明.length > 0, `${条.命令} 的说明是空的`);
    // ⚠️ 插入总是**以命令名起头**（`\frac{}{}` / `\times` / `\left(\right)`）：
    //    不是的话，收下之后源码框里会出现一个跟候选名字对不上的东西。
    断言(条.插入.startsWith(条.命令), `${条.命令} 的插入 ${条.插入} 不是以命令名起头`);
  }
});

测("`常用` 那几条真的都在表里，且**一条都不会被上限挡在外面**", () => {
  const 常 = 无物理.filter((条) => 条.常用).map((条) => 条.命令);
  等(常.length, 10, "常用条数");
  // ⚠️ 顺序就是**表里的先后**（结构那一段在前，希腊那一段在后），不是按常用度。
  等列(
    常,
    ["\\frac", "\\sqrt", "\\sum", "\\int", "\\lim", "\\left", "\\right", "\\text", "\\alpha", "\\theta"],
    "常用那几条",
  );
  // ⚠️ 这一条是**故意**的（`候选上限` 就是照"常用有几条"定的）：写在 `常用名`
  //    里却被上限切掉的名字，等于白写——用户永远看不见它，而代码里看着"有"。
  断言(常.length <= 候选上限, `常用 ${常.length} 条 > 上限 ${候选上限}`);
});

测("样本必须**单独立得住**：`\\right` 出来了就得有 `\\left` 配着（BUG-64）", () => {
  // ⚠️ 这条管的是"弹窗里那一格画成什么样"。KaTeX 里 `\right` 必须跟一个 `\left`
  //    配对才画得出来，所以**离开配对就标不出东西**的命令，样本不能吃
  //    `手写候选` 那条"空串就跟名字一样"的兜底——兜底出来的 `\right` 会让那一行
  //    变成**一句红色的报错**（2026-10-04 开窗目检抓到的，`docs/07` BUG-64）。
  //    ⚠️ 判据只查**配对**这一条 KaTeX 规矩，不是"渲染得成不成功"——
  //    真渲染要真 DOM，这颗假 DOM 里跑不了 `katex.render`（见 `tests/fake-dom.ts`）。
  // ⚠️ **不能用 `includes("\\right")`**：`\rightarrow` 里就含着 `\right` 这六个字符
  //    （第一版这么写，当场把 `\rightarrow` 判成了"有 \right 却没有 \left"）。
  //    命令名的边界在**后面那个字母**上：`\right` 后面跟着字母就是别的命令了。
  //    （同 `tools/doc-sync-check.sh` ⑤ 那条"子串匹配会把自己的说明文字也当命中"。）
  const 有 = (源: string, 命令: string): boolean =>
    new RegExp(`\\\\${命令}(?![A-Za-z])`).test(源);
  for (const 条 of 有物理) {
    if (!有(条.样本, "right")) continue;
    断言(有(条.样本, "left"), `${条.命令} 的样本里有 \\right 却没有 \\left：${条.样本}`);
  }
  等(取(无物理, "\\right")?.样本, "\\left. x \\right)", "`\\right` 的样本换成了一条能独立渲染的");
});

测("带洞的命令：`{}` 的个数与它该收的参数个数对得上", () => {
  等(数洞(取(无物理, "\\frac")?.插入 ?? ""), 2, "`\\frac` 两个参数");
  等(数洞(取(无物理, "\\sqrt")?.插入 ?? ""), 1, "`\\sqrt` 一个参数");
  等(数洞(取(无物理, "\\sum")?.插入 ?? ""), 2, "`\\sum` 上下两个（不是参数，但一样要留洞）");
  等(数洞(取(无物理, "\\left")?.插入 ?? ""), 0, "`\\left(\\right)` 不留洞");
  等(取(无物理, "\\times")?.插入, "\\times", "纯符号：插入就是命令本身");
});

测("physics 那族的插入是**从宏定义数出来的**参数个数", () => {
  // `\dv` 的展开式是 `\frac{d#1}{d#2}` ⇒ 两个参数。
  等(取(有物理, "\\dv")?.插入, "\\dv{}{}", "`\\dv` 两个参数");
  // `\dd` 是零参宏（`\mathrm{d}`），插入不许给它挂洞——挂了就会吃掉后面一个字符。
  等(取(有物理, "\\dd")?.插入, "\\dd", "`\\dd` 零参数");
  等(取(有物理, "\\abs")?.插入, "\\abs{}", "`\\abs` 一个参数");
});

测("physics 那族的样本来自宏表那份用例（不是命令名顶上去的）", () => {
  const 条 = 取(有物理, "\\dv");
  断言(条, "有 `\\dv`");
  断言(条.样本 !== 条.命令, "样本不该是命令名本身（那说明用例表里没这条）");
  // ⚠️ 反查一下：样本必须在那个宏的**展开式**里出现过的命令名，否则说明两处岔了。
  断言(条.样本.includes("\\dv"), `样本 ${条.样本} 里没有 \\dv`);
});

测("空的词挑出来的那几条**全部**是 `常用`（不是「表的前几条」）", () => {
  const 列 = 挑候选(无物理, "");
  等(列.length, 10, "十条常用都露脸（没超过上限）");
  断言(列.every((条) => 条.常用), "有不常用的混进来了");
});

测("⚠️ physics 关着时 `\\vb` 一条都不许露面（收下就是红字）", () => {
  等列(挑候选(无物理, "vb").map((条) => 条.命令), [], "关着时挑 `vb`");
  const 开 = 挑候选(有物理, "vb").map((条) => 条.命令);
  断言(开.includes("\\vb"), `开着时该挑得到 \`\\vb\`：${JSON.stringify(开)}`);
  断言(开.every((命令) => 命令.startsWith("\\vb")), "挑出来的该全是 `vb` 开头的");
});

