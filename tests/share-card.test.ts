/* ── 极小的测试工装（与前几份同一套，只多一个 `测异步`）───────────────── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

async function 测(名称: string, 体: () => void | Promise<void>): Promise<void> {
  try {
    await 体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 断言(条件: unknown, 说明: string): void {
  if (!条件) throw new Error(说明);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

/** `子` 在 `串` 里出现几次（用来数"画了几格 / 几档"）。 */
function 次数(串: string, 子: string): number {
  return 串.split(子).length - 1;
}

/** 正则里要用的字面量。 */
function 引(文: string): string {
  return 文.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

interface 一处字 {
  x: number;
  y: number;
  号: number;
  色: string;
  锚: string;
}

/**
 * 找出`内容`那几个字画在哪（卡片里的字全是 `<text>`）。
 *
 * ⚠️ 返回**列表**：同一句话可能出现不止一次（"Nota" 顶上一个、页脚一个），
 * 而"出现两次"本身就是要断言的东西之一。
 */
function 找字(svg: string, 内容: string): 一处字[] {
  const re = new RegExp(
    `<text x="([-\\d.]+)" y="([-\\d.]+)"[^>]*?font-size="([\\d.]+)" font-weight="[\\d.]+"` +
      ` fill="([^"]+)"( text-anchor="([^"]+)")?[^>]*>${引(内容)}</text>`,
    "g",
  );
  const 出: 一处字[] = [];
  for (const m of svg.matchAll(re)) {
    出.push({ x: +m[1], y: +m[2], 号: +m[3], 色: m[4], 锚: m[6] ?? "start" });
  }
  return 出;
}

/** 必须恰好找到一处，省得每处都写一遍 `[0]!`。 */
function 一处(svg: string, 内容: string): 一处字 {
  const 们 = 找字(svg, 内容);
  if (们.length !== 1) throw new Error(`「${内容}」应该刚好画一处，实际 ${们.length} 处`);
  return 们[0]!;
}

/**
 * 曲线上每个采样点的**纵坐标**。
 *
 * ⚠️ 从描线那条 `path` 的 `Q` 段里取**控制点**：那条曲线是"相邻两点取中点做二次
 * 贝塞尔"（`曲线段`），每一段 `Q cx cy mx my` 里的 `cx/cy` 正好就是**第 i 个
 * 采样点**自己，`mx/my` 是中点。最后那段收口把控制点与终点写成同一个数，所以
 * 取出来的个数和点数一样，顺序也一样。
 */
function 曲线纵(svg: string): number[] {
  const 线 = svg.match(/<path d="([^"]+)" fill="none"/)?.[1];
  if (!线) throw new Error("没找到描线那条 path");
  return [...线.matchAll(/Q [\d.-]+ ([\d.-]+) /g)].map((m) => +m[1]!);
}

/**
 * 量字宽的替身。
 *
 * ⚠️ 测试里**必须**传一个：线上那个用 canvas 真量（node 里没有 canvas），不传就
 * 走 `估宽`。用一个写死的比例，量出来的位置才是可复现的——它只影响"大数字和单位
 * 之间隔多远"，不影响任何一条要断言的坐标。
 */
const 量宽 = (文: string, 号: number, 粗: number) => 文.length * 号 * 0.6 * (粗 >= 700 ? 1.02 : 1);

