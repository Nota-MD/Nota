/**
 * 源码模式里**行内标记的开关**（BUG-57）：选中的文字已经加粗时再按 Ctrl+B
 * 应当**摘掉**那两颗星，而不是再包一层。2026-09-30 与
 * `src/editor/source-mark.ts` ＋ `src/editor/source.ts` 同批落地。
 *
 * # 跑法
 *
 * ```sh
 * npx esbuild tests/source-mark.test.ts --bundle --platform=node --format=esm \
 *   --alias:@=./src --outfile=/tmp/nota-tests/source-mark.mjs
 * node /tmp/nota-tests/source-mark.mjs
 * ```
 *
 * # 用户报的原话（判据就是照它写的）
 *
 * > 现在选中已经加粗的文本，再按 Ctrl+B，会再加两个 `*`。应该是去掉。
 * > 类似的，Ctrl+I、U，排查代码。此问题仅源码或分栏模式有。
 *
 * # 这份测试盯的是什么
 *
 * - **第一组是承重的**：把八族行内标记各拨一遍，判据不是"改动列表长得对"，
 *   而是**把改动真的套回字符串之后，盘上是那几个字**（`套改动` 那一支）。
 *   改动列表本身是中间产物，用户看到的只有文本。
 * - **第二组盯"嵌套一律不动"**：`***甲***` 那种，文本层分不清该摘哪一对。
 *   这一组的期望是**一个字符都不改**——它比"摘对一对"更该被钉住，因为
 *   改错方向（包一层）会得到 `*****甲*****` 那种垃圾，而那是**回不去**的。
 * - 第三组是边界：空选区、只有半边定界符、跨行、以及"拨两下回到原样"。
 * - 第四组读 `source.ts` 的源码文本，钉住"八族都换成了开关、而链接没换"。
 *   那一处**没有任何类型检查能兜住**：谁把某一行改回 `wrapSelection`，
 *   编译、`tsc`、四道闸全都不吭声，只有开窗按一下才知道。
 *
 * # ⚠️ 这份测试**证明不了**什么
 *
 * - ⚠️ **"按了 Ctrl+B 真的会走到这里"没验**。那是按键到命令的那条链
 *   （`ui/useMenus.ts` 的 `defaultPrevented` 判据 ＋ 命令表），要真窗口。
 * - ⚠️ **`view.dispatch` 那一下没验**（本仓没有 jsdom，造不出真 CodeMirror
 *   视图）。这份测试量的是"该派什么"，不是"派下去之后盘上是不是那样"。
 *   后者只能开窗目检（`docs/06`）。
 * - ⚠️ **分栏模式只是"同一条路"这个判断**（左窗格就是 `createSourceEditor`），
 *   没有单独验。
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

import {
  试摘定界符,
  type 文本改动,
  type 选区范围,
  type 摘定界,
} from "@/editor/source-mark";

/* ── 一支极小的测试工装（与 `sidebar-resize.test.ts` 同一套长相）── */

let 过 = 0;
let 败 = 0;
const 败的: string[] = [];

function 测(名称: string, 体: () => void): void {
  try {
    体();
    过++;
    console.log(`  ✔ ${名称}`);
  } catch (e) {
    败++;
    败的.push(名称);
    console.log(`  ✘ ${名称}`);
    console.log(`      ${e instanceof Error ? e.message : String(e)}`);
  }
}

function 组(名: string): void {
  console.log(`\n【${名}】`);
}

function 等(实际: unknown, 期望: unknown, 说明: string): void {
  if (实际 !== 期望) {
    throw new Error(`${说明}：期望 ${JSON.stringify(期望)}，实际 ${JSON.stringify(实际)}`);
  }
}

function 等深(实际: unknown, 期望: unknown, 说明: string): void {
  const a = JSON.stringify(实际);
  const b = JSON.stringify(期望);
  if (a !== b) throw new Error(`${说明}：期望 ${b}，实际 ${a}`);
}

/* ── 两个小工具：把改动套回字符串、把选区包一层 ─────────────────────── */

/**
 * 按 `CodeMirror` 的语义套改动。
 *
 * ⚠️ **从后往前套**：改动里的偏移量全部按**原文档**算（`source-mark.ts` 的
 * 类型注释里写着），正着套的话前面那条一改，后面那条的偏移量就偏了。
 * 这一步跑通，才说明"两条改动"的偏移量没算错。
 */
function 套改动(文: string, 改动: 文本改动[]): string {
  let 结果 = 文;
  for (const c of [...改动].sort((a, b) => b.from - a.from)) {
    结果 = 结果.slice(0, c.from) + c.insert + 结果.slice(c.to);
  }
  return 结果;
}

/** 把选区包进一对定界符（`wrapSelection` 的纯文本版，用来验"拨两下回到原样"）。 */
function 包一层(文: string, 选区: 选区范围, before: string, after: string): string {
  return (
    文.slice(0, 选区.anchor) +
    before +
    文.slice(选区.anchor, 选区.head) +
    after +
    文.slice(选区.head)
  );
}

/** 断言"这一下是**摘**"，并顺手把文本与选区都验一遍。 */
function 应摘(
  文: string,
  from: number,
  to: number,
  before: string,
  after: string,
  期望文本: string,
  期望选区: 选区范围,
): void {
  const 果: 摘定界 | null = 试摘定界符(文, from, to, before, after);
  if (果 === null) throw new Error(`判成了"没带标记"（会去包一层），但应当摘：${文}`);
  if (果.结果 === "不动") throw new Error(`判成了"不动"，但应当摘：${文}`);
  等(套改动(文, 果.改动), 期望文本, `${文} 摘完的文本`);
  等深(果.选区, 期望选区, `${文} 摘完的选区`);
}

/** 断言"这一下**不动**"（嵌套那几种）。 */
function 应不动(文: string, from: number, to: number, before: string, after: string): void {
  const 果 = 试摘定界符(文, from, to, before, after);
  if (果 === null) throw new Error(`判成了"没带标记"，但应当"不动"：${文}`);
  等(果.结果, "不动", `${文} 的判定`);
}

/** 断言"没带这一对定界符"（调用方会去包一层）。 */
function 应没带(文: string, from: number, to: number, before: string, after: string): void {
  等(试摘定界符(文, from, to, before, after), null, `${文} 的判定`);
}

/* ── 一、八族各拨一遍（承重） ───────────────────────────────────────── */

组("一、选中的文字已经带着这一对 ⇒ 摘掉");

// ⚠️ 每一行都是「双击选中正文」（星号**不**进选区）——那是默认手势，
// 也是用户报的那一下。`|` 标出选区两端。
测("`**|甲|**` ＋ Ctrl+B ⇒ `甲`", () => {
  应摘("**甲**", 2, 3, "**", "**", "甲", { anchor: 0, head: 1 });
});

测("`*|甲|*` ＋ Ctrl+I ⇒ `甲`", () => {
  应摘("*甲*", 1, 2, "*", "*", "甲", { anchor: 0, head: 1 });
});

测("`~~|甲|~~` ＋ Ctrl+Shift+X ⇒ `甲`", () => {
  应摘("~~甲~~", 2, 3, "~~", "~~", "甲", { anchor: 0, head: 1 });
});

测("`` `|甲|` `` ＋ Ctrl+E ⇒ `甲`", () => {
  应摘("`甲`", 1, 2, "`", "`", "甲", { anchor: 0, head: 1 });
});

测("`==|甲|==` ＋ 高亮 ⇒ `甲`", () => {
  应摘("==甲==", 2, 3, "==", "==", "甲", { anchor: 0, head: 1 });
});

测("`^|甲|^` ＋ 上标 ⇒ `甲`", () => {
  应摘("^甲^", 1, 2, "^", "^", "甲", { anchor: 0, head: 1 });
});

测("`~|甲|~` ＋ 下标 ⇒ `甲`", () => {
  应摘("~甲~", 1, 2, "~", "~", "甲", { anchor: 0, head: 1 });
});

// ⚠️ 下划线是**唯一不同形**的一对（`<u>` / `</u>`）：上面七族 `before === after`，
// 判据里凡是用"两端同一串"偷懒的地方，这一族都会露馅。
测("`<u>|甲|</u>` ＋ Ctrl+U ⇒ `甲`", () => {
  应摘("<u>甲</u>", 3, 4, "<u>", "</u>", "甲", { anchor: 0, head: 1 });
});

测("用户把星号**一起框进来**也算带标记（`|**甲**|`）", () => {
  应摘("**甲**", 0, 5, "**", "**", "甲", { anchor: 0, head: 1 });
});

测("`|<u>甲</u>|` 全选 ＋ Ctrl+U ⇒ `甲`", () => {
  应摘("<u>甲</u>", 0, 8, "<u>", "</u>", "甲", { anchor: 0, head: 1 });
});

测("标记在句子中间（选区两端是空格，不是文首文末）", () => {
  // `词 **甲** 词`：选中的 `甲` 落在 4..5，摘掉的两对是 2..4 与 5..7。
  应摘("词 **甲** 词", 4, 5, "**", "**", "词 甲 词", { anchor: 2, head: 3 });
});

测("⚠️ 跨行的标记也认得（选区里那一行只是其中一段）", () => {
  应摘("**甲\n乙**", 2, 5, "**", "**", "甲\n乙", { anchor: 0, head: 3 });
});

/* ── 二、嵌套：一律「一颗字都不动」 ─────────────────────────────────── */

组("二、嵌套分不清该摘哪一对 ⇒ 一个字符都不改");

测("`***|甲|***` ＋ Ctrl+B（左边那两颗只是三颗星的后两颗）", () => {
  应不动("***甲***", 3, 4, "**", "**");
});

测("`|***甲***|` 全选 ＋ Ctrl+B（里面还压着一颗）", () => {
  应不动("***甲***", 0, 7, "**", "**");
});

测("`***|甲|***` ＋ Ctrl+I", () => {
  应不动("***甲***", 3, 4, "*", "*");
});

测("`|**甲**|` 全选 ＋ Ctrl+I（加粗的两颗不是斜体那一颗）", () => {
  应不动("**甲**", 0, 5, "*", "*");
});

测("`~~|甲|~~` ＋ 下标（`~~` 是删除线，不是两个下标）", () => {
  应不动("~~甲~~", 2, 3, "~", "~");
});

测("`|~~甲~~|` 全选 ＋ 下标", () => {
  应不动("~~甲~~", 0, 5, "~", "~");
});

测("`**粗体**` 里只选中 `*粗体*`（选区只是更长一串的一段）", () => {
  // 摘了会把"加粗"变成"斜体"——那是改意思，不是去掉。
  应不动("**粗体**", 1, 6, "*", "*");
});

/* ── 三、边界 ───────────────────────────────────────────────────────── */

组("三、边界");

测("空选区：没有「已经加粗」可判，交给调用方插占位词", () => {
  应没带("**甲**", 3, 3, "**", "**");
});

测("没带标记：`|甲|` ＋ Ctrl+B ⇒ 去包一层", () => {
  应没带("甲", 0, 1, "**", "**");
});

测("只有半边：`**|甲|`（右边没闭上）⇒ 去包一层，与今天的行为一致", () => {
  应没带("**甲", 2, 3, "**", "**");
});

测("只有半边：`|甲|**` ⇒ 去包一层", () => {
  应没带("甲**", 0, 1, "**", "**");
});

测("`*|甲|*` ＋ Ctrl+B：一颗星不够两颗，那是斜体不是加粗 ⇒ 去包一层", () => {
  // 包出来是 `***甲***`（加粗叠在斜体上），与所见即所得那边一致。
  应没带("*甲*", 1, 2, "**", "**");
});

测("⚠️ 拨两下回到原样（摘一次、再按原样包一次）", () => {
  const 文 = "这个词**很重**要";
  const from = 5;
  const to = 7; // `很重`
  const 果 = 试摘定界符(文, from, to, "**", "**");
  if (果 === null || 果.结果 === "不动") throw new Error("第一次应当判成摘");
  const 摘后 = 套改动(文, 果.改动);
  等(摘后, "这个词很重要", "第一次摘完的文本");
  // ⚠️ 第二次要用**第一次返回的选区**（不是原来那个）：这正是"选区也得跟着
  // 一起算"的理由，算错的话这里会包到别的地方去。
  等(包一层(摘后, 果.选区, "**", "**"), 文, "再包一次的文本");
});

/* ── 四、接线：八族都换了、链接没换 ─────────────────────────────────── */

组("四、`source.ts` 的接线");

const source源 = readFileSync(join("src", "editor", "source.ts"), "utf8");

测("八族行内标记走的都是 `切换行内标记`（开关）", () => {
  const 命中 = source源.match(/切换行内标记\(view,/g) ?? [];
  等(命中.length, 8, "`切换行内标记(view,` 的条数");
});

测("链接仍旧走 `wrapSelection`（「再插一次链接」算不算开关**还没拍板**）", () => {
  // ⚠️ 这一条是**故意的**：链接的右定界符里带着地址，开关语义得单独判。
  等(source源.includes('wrapSelection(view, "[", `](${payload.href})`'), true, "链接那一行");
});

测("`wrapSelection` 只剩「被开关函数回调」与链接两处调用点", () => {
  const 命中 = source源.match(/wrapSelection\(view,/g) ?? [];
  等(命中.length, 2, "`wrapSelection(view,` 的条数");
});

