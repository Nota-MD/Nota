/**
 * `table-input.ts` 的**判据**（纯函数那几件）。
 *
 * 这里能证明的：一行文字在这边的判据下算不算表格行。这里**不能**证明的：
 * 真窗口里敲下去到底会不会建表——那要 `docs/06` §5.36 那套目检（BUG-51 就是
 * "单测都对、真窗口不动"的典型，所以两边都要跑）。
 *
 * 六组：一 拆单元格、二 判分隔行（含"别把 `---` 当分隔行"那道闸）、
 * 三 判两行、四 **NBSP（BUG-51 的回归）**、五 那道「匹配盖住整段」的闸、
 * 六 输入规则的正则。
 */
import {
  拆单元格,
  匹配盖住整段,
  判两行,
  判表头行,
  判分隔行,
  缩进过深,
  收尾的分隔行,
  type 格子,
} from "../src/editor/table-input";
// 码点只在 `atom-space.ts` 写一次，测试这边同样引名字，不在本文件里手敲那颗字符。
import { 不换行空格 } from "../src/editor/atom-space";

let 过 = 0;
let 败 = 0;
const 失败: string[] = [];

function 断言(名: string, 实: unknown, 期: unknown): void {
  const a = JSON.stringify(实);
  const b = JSON.stringify(期);
  if (a === b) {
    过 += 1;
  } else {
    败 += 1;
    失败.push(`${名}\n    实际 ${a}\n    期望 ${b}`);
  }
}

/** 拆出来的格子只看文字（偏移那一组另有断言）。 */
const 文字 = (格: 格子[]): string[] => 格.map((g) => g.文本);

// ── 一、拆单元格 ──────────────────────────────────────────────
断言("两侧边框不算格子", 文字(拆单元格("| a | b |")), ["a", "b"]);
断言("边框是可选的", 文字(拆单元格("a | b")), ["a", "b"]);
断言("末尾那个空格子要留着（`| a ||` 是 2 格）", 文字(拆单元格("| a ||")), ["a", ""]);
断言("一根光秃秃的竖线不成行", 文字(拆单元格("|")), []);
断言("`\\|` 是内容里的竖线", 文字(拆单元格("| a \\| b | c |")), ["a \\| b", "c"]);
断言("格子两侧的空白去掉", 文字(拆单元格("|   a   |  b  |")), ["a", "b"]);
断言("偏移指回原行（含两侧空白）", 拆单元格("| a | b |"), [
  { 文本: "a", 起点: 2, 终点: 3 },
  { 文本: "b", 起点: 6, 终点: 7 },
]);

// ── 二、判分隔行 ──────────────────────────────────────────────
断言("`---` 自己不是分隔行（交给分割线）", 判分隔行("---"), null);
断言("带冒号的认得出", 判分隔行("| :-: | - |"), ["center", null]);
断言("⚠️ 没冒号是 null 不是 'left'", 判分隔行("| - | - |"), [null, null]);
断言("`:--` 是左对齐", 判分隔行("| :-- | --: |"), ["left", "right"]);
断言("格子里有别的字就不算", 判分隔行("| -x | - |"), null);
断言("缩进 4 列是代码块", 判分隔行("    | - | - |"), null);
断言("空行不算表头行", 判表头行(""), null);
断言("只有竖线的行不算表头行", 判表头行("|"), null);
断言("缩进宽度 Tab 算 4", 缩进过深("\t| a |"), true);
断言("两列空格不算缩进", 缩进过深("  | a |"), false);

// ── 三、判两行 ────────────────────────────────────────────────
断言("列数一致才成表", 判两行("| a | b |", "| - | - |") !== null, true);
断言("列数对不上不成表", 判两行("| a | b |", "| - |"), null);
断言("表头搬进来的是格子文字", 判两行("| a | b |", "| - | - |")?.表头, [
  { 文本: "a", 起点: 2, 终点: 3 },
  { 文本: "b", 起点: 6, 终点: 7 },
]);

// ── 四、NBSP（BUG-51 的回归）───────────────────────────────────
// 真窗口里手打的表格行，空格**全是** NBSP（WebKit 在行末插空格会换成它）。
const 头 = `|${不换行空格}1${不换行空格}|${不换行空格}2${不换行空格}|${不换行空格}3${不换行空格}|`;
const 隔 = `|${不换行空格}---${不换行空格}|${不换行空格}---${不换行空格}|${不换行空格}---${不换行空格}|`;

断言("NBSP 当空白：格子拆得出来", 文字(拆单元格(隔)), ["---", "---", "---"]);
断言("NBSP 当空白：分隔行认得出", 判分隔行(隔), [null, null, null]);
断言("NBSP 当空白：两行成表（BUG-51 本体）", 判两行(头, 隔) !== null, true);
断言("NBSP 当空白：表头文字干净（NBSP 不进格子）", 文字(判两行(头, 隔)!.表头), [
  "1",
  "2",
  "3",
]);
断言("表头格子文字里没有 NBSP（padding 被丢掉）", 拆单元格(头).some((g) => g.文本.includes(不换行空格)), false);
断言("旧行为没变：ASCII 空格照样行", 判两行("| 1 | 2 | 3 |", "| --- | --- | --- |") !== null, true);
断言("半 NBSP 半 ASCII 也认（用户打了一半的样子）", 判两行("| 1 | 2 | 3 |", 隔) !== null, true);
// ⚠️ 三列的表头配两列的分隔行**不该**成表——两列那条是**对**的（`| --- | --- |`
//    首尾竖线是边框，只有 2 格；这条以前在真窗口里误导过一次排查）。
断言("列数对不上就是不成表（三列头配两组横线）", 判两行(头, "| --- | --- |"), null);

// ── 五、那道「匹配盖住整段」的闸（BUG-51 的真凶） ──────────────
// 匹配串是 `prosemirror-inputrules` 拿「文档文字 ＋ 刚敲进去那颗字符」拼的，
// 而文档那颗在行末会是不换行空格——逐字比会在**正当**情况下翻车。
断言("ASCII：匹配盖住整段", 匹配盖住整段("| --- | --- | --- |", "| --- | --- | --- "), true);
断言("⚠️ NBSP：文档那颗是 NBSP、匹配串那颗是竖线，也算盖住", 匹配盖住整段(`| ---${不换行空格}|`, `| ---${不换行空格}`), true);
断言("NBSP 在半路也算盖住", 匹配盖住整段(`|${不换行空格}1${不换行空格}|${不换行空格}2${不换行空格}|`, `|${不换行空格}1${不换行空格}|`), true);
断言("没盖住（匹配短一截）就不算", 匹配盖住整段("| --- |", "| --- | --- | --- "), false);
断言("段落长过窗口时匹配只是尾巴：照样挡住（这道闸的本意）", 匹配盖住整段("| --- |", "甲".repeat(600) + "| --- |"), false);

// ── 六、输入规则那条正则 ──────────────────────────────────────
断言("完整的分隔行（ASCII）", 收尾的分隔行.test("| --- | --- |"), true);
断言("完整的分隔行（全 NBSP）", 收尾的分隔行.test(隔), true);
断言("开头带冒号的也认", 收尾的分隔行.test("| :---: | --- |"), true);
断言("少了收尾竖线不认（那一路归回车）", 收尾的分隔行.test("| --- | ---"), false);
断言("`---` 不认（交给分割线）", 收尾的分隔行.test("---"), false);
断言("普通文字不认", 收尾的分隔行.test("| 甲 | 乙 |"), false);

console.log(`通过 ${过} 条，失败 ${败} 条`);
if (败) {
  for (const f of 失败) console.log(`  ✗ ${f}`);
  process.exit(1);
}
