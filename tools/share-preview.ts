/* ── 长期那本账（热力图那张卡）─────────────────────────────────────────── */

// ⚠️⚠️ **必须在 `场景们` 那张表**前面**调**：月份标签是 `热力图卡()` 里铺格子时
// （`ui/heatmap.ts::月名`）取的 `Intl` 格式器，而那张表是**模块顶层**的字面量——
// 等它求完值再点这一下就晚了，宣传图上印出来的还是英文兜底的 `Apr May Jun`
// （第一版就是这样，中文的图配一串英文月份）。
// ⚠️ 语言**默认是英文兜底**（`i18n/index.ts` 的 `兜底`），没挂宿主时就是它。
定语言("zh-CN");

/** `2026-09-27` → 本地那一天（同 `ui/heatmap.ts::日号` 的写法：**不**用 `new Date(串)`，那按 UTC 解析，东八区会整体偏一格）。 */
function 日(d: string): Date {
  return new Date(Number(d.slice(0, 4)), Number(d.slice(5, 7)) - 1, Number(d.slice(8, 10)));
}

/** 反过来：本地那一天 → `2026-09-27`。 */
function 串(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

/** 加减天数（走 `setDate`，会自己跨月）。 */
function 移(d: Date, 天: number): Date {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate() + 天);
}

/**
 * 造一本**像真的**半年账：`止` 那天往回 `周数` 周（与 `算热力` 铺的窗口同一个月一节）。
 *
 * ⚠️ 这里的"像真的"不是随手写几个随机数，是四条能一眼看穿的规律：
 *
 *   1. **有节奏**：周一到周五 800~2,400 字，周六轻、周日多半休息；
 *   2. **有起伏**：每 7~10 天里挑一天写成"大日子"（3,000~5,500 字）；
 *   3. **有断档**：8 月里连着出去了一周（一个字没写），另有两处三五天的空；
 *   4. **有长进**：开头几周整体轻一点（习惯还没养成），越往后越稳。
 *
 * 一张真的贡献图上，这四样都看得见；四样都对的假图，看着就不像随机噪点。
 *
 * ⚠️ 返回的是**窗口里每一天**（没写的那天也在，值为 0）——插件发的就是这种
 * "打开一本账，从头到尾每天一行"的串，图的空白格正来自那些 0。
 */
function 造长期账(止: string, 周数: number): 热力记录[] {
  const 末 = 日(止);
  // 末列的周一（与 `算热力` 同一个退回法），再往前数满 `周数 - 1` 行。
  const 末列一 = 移(末, -((末.getDay() + 6) % 7));
  const 首 = 移(末列一, -(周数 - 1) * 7);
  const 乱 = 伪随机(20260406);

  // 三处断档：连着 7 天（八月那趟出门）、4 天、3 天。⚠️ 写死日期不写死"第几天"：
  // 图上那几块空白要落在**看得见的月份里**，不然改一次窗口就挪到别处去了。
  const 断档 = new Set<string>();
  for (const [从, 长] of [["2026-08-08", 7], ["2026-05-27", 4], ["2026-07-14", 3]] as [string, number][]) {
    for (let k = 0; k < 长; k++) 断档.add(串(移(日(从), k)));
  }

  const out: 热力记录[] = [];
  let 大日子倒 = 0;
  for (let d = new Date(首); d <= 末; d = 移(d, 1)) {
    const 日串 = 串(d);
    const 周几 = (d.getDay() + 6) % 7; // 周一 = 0
    // 大日子：每 8~11 天来一次，断档与周日不给（那天本来就该轻）。
    if (大日子倒 <= 0) 大日子倒 = 8 + Math.floor(乱() * 4);
    大日子倒--;

    let 值 = 0;
    if (!断档.has(日串) && 乱() > 0.06) {
      if (大日子倒 === 0 && 周几 < 5) {
        值 = 3000 + Math.round(乱() * 2500);
      } else if (周几 < 5) {
        值 = 800 + Math.round(乱() * 1600);
      } else if (周几 === 5) {
        值 = 300 + Math.round(乱() * 900);
      } else {
        // 周日：多半休息（图上那片规律的白，靠的就是这一行）。
        值 = 乱() < 0.55 ? 0 : 200 + Math.round(乱() * 700);
      }
      // 开头四周打七折（习惯还没养成那阵子）。
      if (d < 移(首, 28)) 值 = Math.round(值 * 0.7);
    }
    out.push({ 日: 日串, 值 });
  }
  return out;
}

/**
 * 月份标签的**中文兜底**（只在工装这份运行环境缺 ICU 时用得上）。
 *
 * ⚠️ 月份名是 `ui/heatmap.ts::月名` 用 `Intl.DateTimeFormat(语言(), { month: "short" })`
 * 取的，而**这份工装跑的 node 可能没有中文的 ICU 数据**：容器里那个 22.x 是
 * small-icu，`supportedLocalesOf(["zh-CN"])` 返回空数组，它会**静默退回英文**——
 * 于是中文的宣传图上印着一串 `Apr May Jun`。宿主（WebKit）那份 ICU 是全的，
 * 应用里显示的是「4月」，所以这不是产品行为，是这份工装缺东西。
 * 在 ICU 齐全的机器上（宿主那个 node 24 就是）标签本来就是中文，**这张表一个字
 * 都不会用上**。
 *
 * ⚠️ 只翻标签、**不动"哪几列有标签"**：那件事由 `算热力` 按标签串比出来（同一个月
 * 只标一次），而每个月的中文名与英文名一样是独一无二的，翻完还是同一批列。
 */
const 中文月: Record<string, string> = {
  Jan: "1月", Feb: "2月", Mar: "3月", Apr: "4月", May: "5月", Jun: "6月",
  Jul: "7月", Aug: "8月", Sep: "9月", Oct: "10月", Nov: "11月", Dec: "12月",
};

/**
 * 热力图那张卡（`shape = "heat"`）。
 *
 * ⚠️ 格子是**真的铺出来的**：走 `ui/heatmap.ts::算热力`——与 `panel-nodes.ts`
 * 解析插件那串 `days` 之后调的是同一个函数。这里只是把"插件算出来的那串字"
 * 换成一本编的账，铺法一个字节都没假。
 */
function 热力图卡(): PanelShare {
  const 止 = "2026-09-27";
  const 周数 = 26;
  const 铺好的 = 算热力(造长期账(止, 周数), 止, 周数);
  // 补齐运行环境缺的那一步（理由见 `中文月` 那段）。
  const 图 = { ...铺好的, 列: 铺好的.列.map((列) => ({ ...列, 月: 中文月[列.月] ?? 列.月 })) };
  return 卡({
    title: "写作统计",
    subtitle: "Writing Stats · 半年",
    date: "2026年9月27日 22:31",
    shape: "heat",
    heat: 图,
    less: "少",
    more: "多",
    points: [],
    label: "长期总字数",
    value: 分组(图.总计),
    unit: "字",
    stats: [
      格("有字的天数", String(图.天数), "天"),
      格("日均", 分组(图.天数 > 0 ? 图.总计 / 图.天数 : 0), "字/天"),
      格("单日最多", 分组(图.最大), "字"),
    ],
    foot: `最近 ${周数} 周，你在 ${图.天数} 天里写下了 ${分组(图.总计)} 个字`,
    file: `nota-stats-long-${止}.png`,
  });
}

