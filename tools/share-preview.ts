/* ── 量宽：一张照 Noto Sans CJK 量的表 ────────────────────────────────── */

/**
 * 各类字符占几个 `em`。
 *
 * ⚠️ 这些数是**照着 Noto Sans CJK SC 量的**（`rsvg-convert` 出的图就是它）。
 * 换了字体（`share-card.ts` 里那个 `字体` 串换了一家）这张表就偏了——但偏的是
 * **大数字后面那颗单位的起始位置**，不是卡片版式。
 */
const 每字宽 = (字: string): number => {
  // ⚠️ 数字 **0.60**（不是 0.55、也不是 0.58）：这两个数是**从图上量出来的**——
  // 210px 那一档的 `209,758` 实测 815 像素宽，按 0.58 算只有 790，于是紧跟其后的
  // 那颗单位**压在最后一个数字上**（宣传图上一眼就能看见）。要再改动这张表，
  // 拿 `magick` 量一下那张 PNG 里大数字的右边界，别凭感觉调。
  if (/[0-9]/.test(字)) return 0.6;
  if (/[.,]/.test(字)) return 0.28;
  if (/[-–—]/.test(字)) return 0.4;
  if (字 === " ") return 0.26;
  if (字 === "/") return 0.3;
  // ⚠️ **拉丁字母是半个全角左右**，不是 1：页脚那个 `Nota` 按 1 算会宽出一倍，
  // 于是图标被推到很左边——用户报的「图标和 nota 字差的有点远」里，一半是这个
  // 估宽、一半是宿主那边少写了右对齐（两处都改了）。
  if (/[A-Za-z]/.test(字)) return 0.55;
  // 汉字、全角标点、以及"字 / 分钟"里那一串——按一个全角算。
  return 1;
};

/** 粗体比常规宽一点（`800` 那档最明显）。 */
const 量: 量宽器 = (文, 号, 粗) => {
  let 宽 = 0;
  for (const 字 of 文) 宽 += 每字宽(字);
  return 宽 * 号 * (粗 >= 700 ? 1.0 : 0.98);
};

/** 千位分隔（与插件 `ticks.group_text` 同一个写法）。⚠️ 不走 `toLocaleString`：那张表看 ICU 的脸色，同一份代码在两台机器上可能一个带逗号一个不带。 */
function 分组(值: number): string {
  return String(Math.round(值)).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
}

/* ── 造一条一天的曲线 ─────────────────────────────────────────────────── */

/** 确定性伪随机（mulberry32）。**要确定性**：同一份代码重跑必须出同一张图。 */
function 伪随机(种子: number): () => number {
  let a = 种子 >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 一段连续写作：`[从第几分钟, 到第几分钟, 字/分钟]`。**段与段之间自动算停笔**。 */
type 段 = [number, number, number];

/**
 * 某时刻的基准速度。不在任何一段里就是 **0**（停笔）。
 *
 * ⚠️ 用"写了几段"来描述一天，而不是"一条插值折线上的拐点"：停笔是**一个个区间**
 * 不是一个点，用拐点写就得每处停笔写两遍（降到 0、再从 0 升起来），而"这两点之间
 * 到底是不是 0"要靠读的人自己推——`[640, 110]` 后面跟一个 `[660, 0]`，那 640~660
 * 这一段的斜率是插出来的，于是"停笔"变成了"速度平滑地掉下去"。
 *
 * ⚠️ 两端都**闭**（`从 <= 分 <= 到`）：写成左闭右开的话，每一段自己的**最后一分钟**
 * 会被判成停笔——结尾那一段就是一个从速度跌到 0 的斜坡（看图的人会以为"他越写
 * 越慢"，实际上只是那一段写完了）。代价是相邻两段不能重叠，而"笔停了一下"本来
 * 就该写成两段之间留个空。
 */
function 基准(作息: 段[], 分: number): number {
  for (const [从, 到, 速] of 作息) if (分 >= 从 && 分 <= 到) return 速;
  return 0;
}

/** 一条曲线算出来的那几个数（卡片上那几格全是它们）。 */
interface 一笔账 {
  /** 第一条曲线所在的那一分钟 / 最后一条结束的那一分钟（横轴的两端）。 */
  起: number;
  止: number;
  pts: number[];
  /** 总字数 = Σ(速度 × 一桶几分钟)。 */
  字数: number;
  /** 净打字时间（分钟）＝ 速度大于 0 的那几桶。 */
  净分: number;
  /** 跨了多少分钟（含中间的停笔）。⚠️ 插件 `main.lua` 里**本轮**的平均速度用的就是它（`round_rate` = 总字数 ÷ `elapsed_ms`），**今日**那份用的是净时间（`day_rate` = 字数 ÷ `today.ms`）。两条账口径不同是插件本来的行为，这里照抄。 */
  跨分: number;
  峰值: number;
}

/**
 * 把作息摊成一条**等距**的曲线，并把它自己那几个数算出来。
 *
 * ⚠️⚠️ **速度就是作息里写的那个数，不许整体缩放**（第一版试过"缩放到某个总字数"，
 * 结果是**峰值被压平**：作息里明明写 190，缩放系数一乘出来卡片上印着 82——
 * 「一天打了非常多字」那张图最该有说服力的数反而成了全图最不准的数）。
 * 要改"打了多少字"，改的是**作息里的速度或各段长短**，不是最后乘一个系数。
 *
 * @param 桶 一桶几分钟（`spread` 在插件那边做的事是同一个：点太多就合并）。
 */
function 造一天(作息: 段[], 桶: number): 一笔账 {
  const 首 = 作息[0];
  if (!首) return { 起: 0, 止: 0, pts: [], 字数: 0, 净分: 0, 跨分: 0, 峰值: 0 };
  let 起 = 首[0];
  let 止 = 首[1];
  for (const [a, b] of 作息) {
    if (a < 起) 起 = a;
    if (b > 止) 止 = b;
  }

  const 桶数 = Math.floor((止 - 起) / 桶) + 1;
  const 乱 = 伪随机(20260927);
  const pts: number[] = [];
  for (let i = 0; i < 桶数; i++) {
    const 分 = 起 + i * 桶;
    const 底 = 基准(作息, 分);
    // ⚠️ 停笔那几段是**真的 0**、也**不许四舍五入掉**：它们就是这张图要说的事
    // （"什么时候停过"），加一点噪声就成了"一直在写"。
    if (底 <= 0) {
      pts.push(0);
      continue;
    }
    // 噪声 ±12%：真人打字不会每一分钟都一样快。
    pts.push(Math.max(1, Math.round(底 * (0.88 + 乱() * 0.24))));
  }

  let 字数 = 0;
  let 净分 = 0;
  let 峰值 = 0;
  for (const v of pts) {
    字数 += v * 桶;
    if (v > 0) 净分 += 桶;
    if (v > 峰值) 峰值 = v;
  }
  return { 起, 止, pts, 字数, 净分, 跨分: 止 - 起, 峰值 };
}

/** 净平均速度（字/分）＝ 字数 ÷ 净打字时间。今日那张用它（同插件的 `day_rate`）。 */
const 净平均 = (账: 一笔账) => (账.净分 > 0 ? Math.round(账.字数 / 账.净分) : 0);
/** 跨平均速度（字/分）＝ 字数 ÷ 总跨时。本轮那张用它（同插件的 `round_rate`）。 */
const 跨平均 = (账: 一笔账) => (账.跨分 > 0 ? Math.round(账.字数 / 账.跨分) : 0);

/* ── 刻度尺（插件那一半：这里手写好让宿主画）───────────────────────────── */

/**
 * 全日的横轴：**整点一小时一格**，每 `步` 小时写一个字。
 *
 * 用户原话：「如果是全天的话，那就一个小时为一个单位的横坐标标尺。」
 * 落到这里就是：主刻度落在**整点**上、每 `步` 小时一个；`x_minor = 步`
 * ——也就是**每一个小时都有一道小格**（有字的那个之外，其余是没字的短线）。
 *
 * ⚠️ 主刻度只取**整点**，不从"第一分钟"起：标尺的格子对齐的是钟，不是这次
 * 写作什么时候开始。所以第一个有字的刻度可能比曲线左端晚几十分钟。
 */
function 钟点尺(起分: number, 止分: number): { 尺: 刻度[]; 细: number } {
  const 跨小时 = (止分 - 起分) / 60;
  const 步 = [1, 2, 3, 4, 6].find((h) => 跨小时 / h <= 5) ?? 6;
  const 尺: 刻度[] = [];
  const 首个整点 = Math.ceil(起分 / 60) * 60;
  // ⚠️ 只丢掉**真的挤在左端**的那一档（< 2.5%）。这个门槛第一版写成 4%，于是
  // 「09:30 开始写、10:00 是第一个整点」那种一天**开头三个半小时一个刻度都没有**，
  // 看图的人以为这段图没画标尺。宿主那边 `横锚` 会把 4.5% 以内的一档改成左对齐，
  // 所以留下它是安全的。
  for (let m = 首个整点; m <= 止分; m += 步 * 60) {
    if ((m - 起分) / (止分 - 起分) < 0.025) continue;
    尺.push({ at: (m - 起分) / (止分 - 起分), label: 钟点(m) });
  }
  return { 尺, 细: 步 };
}

/** 第几分钟 → `09:12`。 */
function 钟点(分: number): string {
  const m = ((分 % 1440) + 1440) % 1440;
  return `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;
}

/**
 * 单次的横轴：**按这一轮自己的时间尺度选单位**。
 *
 * 用户原话：「比如说单次打字，那就以开始计时，依据它的时间尺度自行判断横坐标
 * 要用什么样的单位。」于是分两档：
 *
 * | 这一轮多长 | 一格 | 刻度上写什么 |
 * |---|---|---|
 * | **不到 1 小时** | `1/2/5/10/15/20/30` 分钟里挑一个 | `N 分` |
 * | **1 小时以上** | `60/120/180/360` 分钟里挑一个 | `N 小时`，**画大一号** |
 *
 * ⚠️ 两档**不混**：不会出现"30 分 … 1 小时 … 90 分"那种一档一个单位。用户
 * 「到小时就用稍微大一点的字体标出来是几小时」要的是一个**能看出来的换档**，
 * 而一格里两套单位正好把这个换档抹掉了。
 *
 * ⚠️ 0 那一档写「开始」，右端写「结束」——**但右端那档离最后一格主刻度太近
 * 就不写**（< 8%），否则两个字会叠在一起。
 */
function 计时尺(总分钟: number): { 尺: 刻度[]; 细: number } {
  const 上小时 = 总分钟 >= 60;
  const 候选 = 上小时 ? [60, 120, 180, 360, 720] : [1, 2, 5, 10, 15, 20, 30];
  const 步 = 候选.find((s) => 总分钟 / s <= 5) ?? 候选[候选.length - 1] ?? 60;

  const 尺: 刻度[] = [{ at: 0, label: "开始" }];
  for (let m = 步; m <= 总分钟; m += 步) {
    const at = m / 总分钟;
    尺.push({
      at,
      label: 上小时 ? `${m / 60} 小时` : `${m} 分`,
      // 大一号只给**小时**那几档：用户点名要的就是"到小时"这个换档。
      ...(上小时 ? { 大单位: true } : {}),
    });
  }
  if ((总分钟 - (尺[尺.length - 1]?.at ?? 0) * 总分钟) / 总分钟 > 0.08) {
    尺.push({ at: 1, label: "结束" });
  }
  // 小格：分钟档分 5 格（10 分 → 2 分一格），小时档分 4 格（1 小时 → 15 分一格）。
  return { 尺, 细: 上小时 ? 4 : 5 };
}

/* ── 卡片 ─────────────────────────────────────────────────────────────── */

/** 三格指标。`small` 是空的就不画（`share-card.ts` 那条）。 */
function 格(k: string, v: string, small: string): PanelShareStat {
  return { k, v, small };
}

/** 时长按用户的规矩写成 `60 分` / `7.2 小时`（不到一分钟写秒）。 */
function 时长(毫秒: number): { v: string; small: string } {
  const 分 = 毫秒 / 60000;
  if (分 < 1) return { v: String(Math.round(毫秒 / 1000)), small: "秒" };
  if (分 < 60) return { v: String(Math.round(分)), small: "分" };
  const 小时 = 分 / 60;
  // ⚠️ 整小时不写 `.0`（`7.2 小时` 对，`7.0 小时` 不像话）。
  return { v: Number.isInteger(Math.round(小时 * 10) / 10) ? String(Math.round(小时)) : (Math.round(小时 * 10) / 10).toFixed(1), small: "小时" };
}

